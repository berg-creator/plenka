    t = {k: [] for k in ("мелодия", "пэд", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    def hush(notes: list[N]) -> list[N]:                         # в паузах петли молчит музыка
        for a, b in QUIET:
            notes = mute(notes, a, b)
        return notes

    for b in range(BARS):
        o, s, odd = b * 16, section(b), b % 2
        cell = o - 16 * odd                                      # начало двухтактной клетки
        breathe = odd and b % 16 != 15                           # низ дышит во второй половине чётного такта

        # Тема: зов в нечётных тактах (счёт с единицы), ответ — в чётных; с такта 9
        if s in MUSIC and b >= 8:
            if b >= BARS - 2:
                notes = ANSWER_END if odd else CALL
            elif odd:
                notes = ANSWER_F if s == "F" else ANSWER_2 if s in ("G", "I") or b % 4 == 3 else ANSWER
            else:
                notes = CALL_2 if s in ("D", "G") else CALL
            bar = [N(o + p, ln, k, v) for p, ln, k, v in notes]
            if not odd and b % 8 == 6 and s in ("D", "G", "I"):  # подъезд к ре раз в восьмёрку: до-диез → ре
                top = next(n for n in bar if n.key == 74)
                bar = [n for n in bar if n != top] + grace(top, -1, .5)
            t["мелодия"] += bar

        # Пэд: аккорд на два такта, только в главных частях
        if s in ("D", "G") and not odd:
            chord = PAD_D if (b // 2) % 2 == 0 else PAD_B
            t["пэд"] += [N(o, 24, k, v) for k, v in chord]

        # 808: клетка на два такта, рисунок части
        if s != "Z" and not odd:
            pat = (BASS_F if s in ("F", "F2", "I") else BASS_H if s in ("A", "C", "E", "H") else BASS_B)[(b // 2) % 4]
            t["808"] += [N(o + p, ln, k, 112) for p, ln, k in pat]
        if s != "Z" and odd and not breathe:                     # конец шестнадцатого такта: низ доигрывает со слайдом
            t["808"] += [N(o + 8, 4, C, 112)] + glide(o + 12, 4, C, AS, at=2, over=1.5)

        # Кик как перк — задранная бочка во второй половине такта, где низ молчит
        if b == 45:
            t["бочка"] += [N(o + 8, .3, 93, 116), N(o + 9, .3, 96, 116)] + \
                          [N(o + 12 + i * .5, .3, k, v) for i, (k, v) in enumerate(((98, 108), (96, 90), (93, 70)))]
        if b == 87:
            t["бочка"] += [N(o + 10 + i * .5, .3, k, v)
                           for i, (k, v) in enumerate(((86, 80), (89, 90), (93, 100), (96, 110), (98, 122)))]

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in BREATHS:
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        # Мотив хука перком в части без музыки
        if s == "H" and odd:
            t["перк"] += [N(o + p, .75, 60 + k, v) for p, k, v in MOTIF]

        if s not in DRUMS or b == 57:                            # такт 58 — без барабанов, как у образца
            continue

        if not odd:
            kick = hits(cell, KICKS[(b // 2 + (2 if s in ("G", "H") else 0)) % len(KICKS)], vel=112, ghost=.45)
            t["бочка"] += swing(kick, SW)

        claps = [N(o + 8, 1, 60, 110)]
        if b % 4 == 3:
            claps.append(N(o + 11, 1, 60, 58))
        if b in (24, 56, 95):
            claps = flam(claps[0], .25, .5) + claps[1:]

        key = 63 if s == "D" else 57 if s == "G" else 60
        plan = PLANS[(b // 8 + (3 if s in ("C", "H") else 0)) % len(PLANS)].split()[b % 8]
        bone, fills = int(plan[0]), plan[1:]
        hat = swing(spread(hits(o, nudge(BONES[bone], b), key=key, vel=84, ln=.5), 38, seed=b), SW)
        hat = over(hat, *(FILLS[f](o, key) for f in fills))

        perc = []
        if s != "H":
            perc = [N(o + 6, 1, 60, 72)] if odd else [N(o + 14, 1, 62, 64)] if b % 4 == 2 else []
            if b % 8 == 7:
                perc += echo([N(o + 3, 1, 62, 92)], 1.5, times=2, decay=.6, width=46, pitch=-2)
            perc = swing(spread(perc, 48, seed=b + 300), SW)
        ohat = [N(o + (6 if b % 8 == 1 else 12), 2, 60, 80)] if b % 4 == 1 else []

        if b == 95:                                              # обрыв барабанов перед концом
            claps, hat, perc, ohat = (mute(x, o + 12, o + 16) for x in (claps, hat, perc, ohat))
        if b in BREATHS:
            claps, hat, perc, ohat = (mute(x, o + 8, o + 16) for x in (claps, hat, perc, ohat))
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat

    # Низ дышит по карте образца: вторая половина чётного такта, кроме каждого шестнадцатого; во вдохах — тишина
    low = {"808": t["808"], "бочка": t["бочка"]}
    for b in range(BARS):
        o = b * 16
        if b % 2 and b % 16 != 15 or b in BREATHS or b >= BARS - 2:
            for k in low:
                keep = [n for n in low[k] if k == "бочка" and n.key > 75 and o + 8 <= n.pos < o + 16]
                low[k] = mute(low[k], o + 8, o + 16) + keep
        if b == 95:
            low["бочка"] = mute(low["бочка"], o + 12, o + 16)
        if b == 57:                                              # клетка бочки такта 57 залезла бы в такт без барабанов
            low["бочка"] = mute(low["бочка"], o, o + 16)
        if section(b) == "Z":
            low["808"] = mute(low["808"], o, o + 16)
    t["808"] = human(swing(low["808"], SW), 6, seed=146)
    t["бочка"] = low["бочка"]
    t["мелодия"], t["пэд"] = hush(t["мелодия"]), hush(t["пэд"])
    return {k: sorted(set(v)) for k, v in t.items()}

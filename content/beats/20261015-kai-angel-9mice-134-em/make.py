def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "клавиши", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    for b in range(BARS):
        o, s, odd = b * 16, section(b), b % 2
        music = b >= 4 and b not in SILENT and s != "end"

        # Тема: зов над ми, ответ над до
        if music:
            if b == 54:
                notes = ANSWER_END
            elif s == "F":
                notes = ANSWER_B if odd else CALL_B
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 else ANSWER
            else:
                notes = CALL
            bar = [N(o + p, ln, k, v) for p, ln, k, v in notes]
            if not odd and b % 8 == 4 and s == "E":              # подъезд к вершине раз в восьмёрку
                top = next(n for n in bar if n.key == 76)
                bar = [n for n in bar if n != top] + grace(top, -2, .5)
            if b in BREATHS:
                bar = mute(bar, o + 8, o + 16)
            t["мелодия"] += bar

        # Пэд: ми с си и до с солью, до шага 12 — конец такта дышит
        if music and s in "CDEF" and b != 24:
            keys = (55, 60) if odd else (52, 59)
            bar = [N(o, 12, k, v) for k, v in zip(keys, (84, 74))]
            t["пэд"] += mute(bar, o + 8, o + 16) if b in BREATHS else bar

        if music and s == "F" and odd:
            t["клавиши"] += [N(o + p, ln, k, v) for p, ln, k, v in KEYS[(b - 39) // 2 % 3]]

        # 808
        if b in DROP_BASS:
            bar = [N(o + p, ln, k, 104) for p, ln, k in DROP_BASS[b]]
        elif b in NO_DRUMS - {38} or b == 25:
            bar = []
        else:
            bar = [N(o + p, ln, k, 110) for p, ln, k in (BASS_B if s == "F" else BASS_A)[b % 8]]
            if b in SLIDES:                                      # слайд вверх на кварту — событие
                last = bar[-1]
                bar = bar[:-1] + glide(last.pos, last.ln, last.key, last.key + 5, at=last.ln - 1.5, over=1.5)
            if b in STUTTER:                                     # своя находка: 808 заикается
                last = bar[-1]
                bar = bar[:-1] + [N(last.pos + i * .5, .5, last.key, v) for i, v in enumerate((70, 88, 104, 122))]
        if b in BREATHS:
            bar = mute(bar, o + 8, o + 16)
        t["808"] += swing(bar, SW)

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in BREATHS:
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        # Кик как перк: задранная бочка
        if b == 22:
            t["бочка"] += [N(o + 13, .35, 88, 118), N(o + 14, .35, 91, 104), N(o + 15, .35, 95, 92)]
        if b == 38:
            t["бочка"] += [N(o + 4 + i * .5, .3, k, v) for i, (k, v) in
                           enumerate(((88, 120), (91, 108), (95, 100), (100, 112), (95, 84)))]
        if b in NO_DRUMS:
            continue

        kick = hits(o, KICKS[(b + (3 if s == "F" else 0)) % 8], vel=112, ghost=.45)
        claps = [N(o + 8, 1, 60, 110)]
        if b % 4 == 3:
            claps.append(N(o + 14, 1, 60, 72))
        if b in (8, 27, 39):
            claps = flam(claps[0], .25, .5) + claps[1:]

        key = 62 if s == "F" else 60
        plan = PLANS[(b // 8) % len(PLANS)].split()[b % 8]
        bone, fill = int(plan[0]), plan[1]
        hat = swing(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b), SW)
        hat = over(hat, FILLS[fill](o, key) if fill != "." else [])

        perc = [N(o + 7, 1, 60, 74)] if odd else [N(o + 11, 1, 62, 66)] if b % 4 == 2 else []
        if b % 8 == 5:
            perc += echo([N(o + 13, 1, 64, 96)], 1, times=2, decay=.6, width=46, pitch=-2)
        perc = swing(spread(perc, 48, seed=b + 300), SW)
        ohat = [N(o + (12 if b % 8 == 2 else 6), 2, 60, 80)] if b % 4 == 2 and s in "CEF" else []

        if b in BREATHS:
            kick, claps, hat, perc, ohat = (mute(x, o + 8, o + 16) for x in (kick, claps, hat, perc, ohat))
        t["бочка"] += swing(kick, SW)
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat
    t["808"] = human(t["808"], 6, seed=134)
    return {k: sorted(v) for k, v in t.items()}

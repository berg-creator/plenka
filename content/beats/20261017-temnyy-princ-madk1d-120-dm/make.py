    t = {k: [] for k in ("мелодия", "пэд", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    def hush(notes: list[N]) -> list[N]:                         # в паузах петли молчит музыка
        for a, b in QUIET:
            notes = mute(notes, a, b)
        return notes

    for b in range(BARS):
        o, s, odd = b * 16, section(b), b % 2

        # Тема: зов в чётных тактах, ответ в нечётных; во вступлении — одна петля
        if s != "I":
            if b == BARS - 1:
                notes = ANSWER_END
            elif odd:
                notes = ANSWER_D if s == "D" else ANSWER_2 if b % 4 == 3 else ANSWER
            else:
                notes = CALL_2 if s in ("C", "E") else CALL
            bar = [N(o + p, ln, k, v) for p, ln, k, v in notes]
            if not odd and b % 8 == 6 and s in ("B", "D"):       # подъезд к фа раз в восьмёрку: ми → фа
                top = next(n for n in bar if n.key == 77)
                bar = [n for n in bar if n != top] + grace(top, -1, .5)
            t["мелодия"] += bar

        # Пэд: аккорд на два такта, с такта 11; гаснет вместе с ответом мелодии
        if s not in ("I", "A") and not odd:
            chord = PAD_AM if (b // 2) % 2 == 0 else PAD_F
            t["пэд"] += [N(o, 28, k, v) for k, v in chord]         # конец такта ответа — тишина всей музыки, кроме петли

        # Хэт-тень ответа: в части без барабанов, на последней доле такта ответа — ход ответа высотой хэта
        if s == "D" and odd and b not in BREATHS:
            t["хэт"] += [N(o + 12 + i, .5, 60 + k - 69, v) for i, (k, v) in enumerate(((69, 70), (72, 78), (76, 90), (72, 62)))]

        # 808
        if s != "I":
            pat = BASS_B if s in DRUMS else BASS_A
            bar = [N(o + p, ln, k, 112) for p, ln, k in pat[b % 8]]
            if s == "E" and b % 4 == 1:                          # прыжок на октаву — раз в четыре такта
                last = bar[-1]
                bar = bar[:-1] + [last._replace(key=last.key + 12, ln=1.5)]
            if s not in DRUMS:
                for h in (2 * b, 2 * b + 1):
                    if h in GAPS:
                        bar = mute(bar, h * 8, h * 8 + 8)
            if b in BREATHS or b == BARS - 1:
                bar = mute(bar, o + 8, o + 16)
            t["808"] += swing(bar, SW)

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in BREATHS:
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        # Кик как перк: задранная бочка, вверх по ля минору
        if b == 33:
            t["бочка"] += [N(o + 12 + i, .35, k, v) for i, (k, v) in enumerate(((81, 92), (84, 106), (88, 120)))]
        if b == 41:
            t["бочка"] += [N(o + 8 + i * .5, .3, k, v)
                           for i, (k, v) in enumerate(((76, 84), (79, 92), (81, 100), (84, 110), (88, 122)))]
        if s not in DRUMS:
            continue

        kick = hits(o, KICKS[(b + (3 if s == "C" else 0)) % 8], vel=112, ghost=.45)
        claps = [N(o + 4, 1, 60, 110), N(o + 12, 1, 60, 106)]
        if b % 4 == 3:
            claps.append(N(o + 15, 1, 60, 62))
        if b in (18, 34, 58):
            claps = flam(claps[0], .25, .5) + claps[1:]

        key = 57 if s == "C" else 60
        plan = PLANS[(b // 8) % len(PLANS)].split()[b % 8]
        bone, fills = int(plan[0]), plan[1:]
        hat = swing(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b), SW)
        hat = over(hat, *(FILLS[f](o, key) for f in fills))

        perc = [N(o + 7, 1, 60, 72)] if odd else [N(o + 14, 1, 63, 64)] if b % 4 == 2 else []
        if b % 8 == 7:
            perc += echo([N(o + 10, 1, 62, 94)], 1.5, times=2, decay=.6, width=46, pitch=2)
        perc = swing(spread(perc, 48, seed=b + 300), SW)
        ohat = [N(o + (6 if b % 8 == 1 else 14), 2, 60, 80)] if b % 4 == 1 else []

        if b == 41:                                              # обрыв перед частью без барабанов
            kick, claps, hat, perc, ohat = (mute(x, o + 12, o + 16) for x in (kick, claps, hat, perc, ohat))
        t["бочка"] += swing(kick, SW)
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat
    t["мелодия"], t["пэд"] = hush(t["мелодия"]), hush(t["пэд"])
    t["808"] = human(t["808"], 6, seed=120)
    return {k: sorted(v) for k, v in t.items()}

def sg(notes: list[N]) -> list[N]:
    return swing(notes, SW)


def bar(o: float, notes, louder: int = 0) -> list[N]:
    return sg([N(o + p, ln, k, max(1, min(127, v + louder))) for p, ln, k, v in notes])


def high_kick(o: float, notes, only=None) -> list[N]:
    return sg([N(o + p, .4, k, v) for p, k, v in notes if only is None or p in only])


def low(o: float, notes, vel: int = 108) -> list[N]:
    return sg([N(o + p, ln, k, vel + (6 if p == 0 else 0)) for p, ln, k in notes])


def accent(notes: list[N]) -> list[N]:
    """Сила хэта рисунком: доля, «и», прочие шестнадцатые; призрак «o» оставлен тихим."""
    return [n._replace(vel=n.vel if n.vel < 50 else HAT_V.get(round(n.pos) % 4, 60)) for n in notes]


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "подголосок", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    # Вступление: 1–4 — петля одна; 5–8 — тихий хэт и перк
    for b in range(4, 8):
        o = b * 16
        t["хэт"] += spread(sg(hits(o, ("x.x.x.x.x.x.xo..", "x.x...x.x.x.x.x.", "x.xox.x.x.x...x.", "x.x.x.x.")[b - 4],
                                   vel=56, ln=.5)), 36, seed=b)
        t["перк"] += sg([N(o + 6, 1, 60, 70, -45), N(o + 14, 1, 62, 64, 45)] if b < 7 else [N(o + 6, 1, 60, 74, -45)])

    # До перелома: куплет 9–24, припев 25–31, куплет 33–48, припев 49–55
    for b in [*range(8, 31), *range(32, 55)]:
        o, i = b * 16, b % 8
        hook = 24 <= b < 31 or 48 <= b < 55
        if b in (44, 52):                         # стоп-тайм: всё — вместе с аккордами клаве петли
            stops = sg([N(o + p, 1, 60, 112) for p in (0, 3, 6, 10, 12)])
            t["бочка"] += stops
            t["808"] += [n._replace(ln=2, key=C, vel=110) for n in stops]
            t["хэт"] += [n._replace(ln=.5, vel=96 - 6 * k, pan=(-30, 30)[k % 2]) for k, n in enumerate(stops)]
            t["клэп"].append(N(o + 12 + 3 * T, 1, 60, 118))
            continue
        t["бочка"] += sg([N(o + p, 1, 60, v) for p, v in KICK[b % 2].items()])
        late = (3 * T, 4 * T)
        t["клэп"] += [N(o + 4 + late[0], 1, 60, CLAP[b % 2][0]), N(o + 12 + late[1], 1, 60, CLAP[b % 2][1])]
        if not hook and i == 3:
            t["клэп"].append(sg([N(o + 15, .5, 60, 38)])[0])
        pattern = (BASS_H if hook else BASS_V)[(i + (4 if b >= 32 else 0)) % 8]
        t["808"] += low(o, pattern)
        plan = PLAN[b // 8 * 8].split()[i]
        if plan == ".":                           # такт вдоха — хэт здесь пишет «плёнка встаёт» ниже
            plan = "7."
        bone, fill = BONES[int(plan[0])], plan[1]
        hat = spread(sg(accent(hits(o, bone, vel=60, ln=.5))), 38, seed=b)
        t["хэт"] += over(hat, FILLS[fill](o)) if fill != "." else hat
        # открытый хэт и перк — по ушам
        if hook and i % 2 == 1:
            t["открытый хэт"] += sg([N(o + 14, 2, 60, 86)])
        elif not hook and i % 4 == 2:
            t["открытый хэт"] += sg([N(o + 6, 1.5, 60, 80)])
        t["перк"] += sg([N(o + 3, 1, 60, 72, -48), N(o + 11, 1, 60, 66, 48)] if i % 2 == 0 else
                        [N(o + 7, 1, 62, 76, 40)] + ([N(o + 13, 1, 65, 70, -40)] if i % 4 == 3 else []))
        # мелодия: хук в припевах, в куплете 2 — ответы только в паузах петли
        if hook:
            k = (b - 24) % 4
            t["мелодия"] += bar(o, END2 if b == 51 and k == 3 else HOOK[k])
    for b, notes in ((15, ((12, 1, 70, 84), (13, 3, 72, 92))),
                     (39, ((8, 2, 67, 90), (10, 1, 70, 96), (12, 4, 74, 106))),
                     (43, ((12, 3, 67, 80),)),
                     (47, ((6, 1, 62, 76), (12, 3, 70, 88)))):
        t["мелодия"] += bar(b * 16, notes)
    t["мелодия"] += bar(31 * 16, ((0, 2, 67, 100), (4, 4, 62, 90)))                      # такт 32 — хвост в провал

    # Слайды 808 — событие: фа к си-бемолю (такты 40 и 52), до к соли после перелома (66)
    for b, a, z in ((39, F, A), (51, F, A)):
        t["808"] = [n for n in t["808"] if int(n.pos // 16) != b]
        t["808"] += sg(glide(b * 16, 7, a, z, at=5, over=2) + [N(b * 16 + 10, 2, z, 104), N(b * 16 + 13, 3, z, 100)])

    # Задранная бочка играет клаве там, где петля вырезана
    t["бочка"] += sg([N(26 * 16 + 8, .4, 96, 110), N(26 * 16 + 9, .4, 98, 96)])                 # такт 27, дыра 6–10
    t["бочка"] += high_kick(31 * 16, CLAVE) + echo(sg([N(31 * 16 + 14, .4, 98, 110)]), 1, times=2, decay=.6,
                                                    width=45, pitch=-5)                       # такт 32, провал
    t["бочка"] += high_kick(54 * 16, CLAVE_BACK, only=(8, 11, 14))                             # такт 55, дыра
    t["бочка"] += high_kick(55 * 16, CLAVE_BACK, only=(2, 4))                                   # такт 56, провал

    # После перелома: клэп на третьей доле, хэт триолями, 808 под перегрузом
    for b in range(CUT, BARS):
        o, i = b * 16, b - CUT
        t["бочка"] += sg([N(o + p, 1, 60, v) for p, v in KICK_S[b % 2].items()])
        t["клэп"].append(N(o + 8 + 4 * T, 1, 60, (116, 108)[b % 2]))
        if i % 4 == 3:
            t["клэп"] += flam(N(o + 15, 1, 60, 92), gap=.5)
        t["808"] += low(o, BASS_S[i % 8])
        code = PLAN_S.split()[i]
        bone = [N(o + p, .5, 60, 100 if p in (0, 8) else 82 if p % 4 == 0 else 62) for p in BONES_S[int(code[0])]]
        bone = spread(bone, 40, seed=b + 300)
        t["хэт"] += over(bone, FILLS_S[code[1]](o)) if code[1] != "." else bone
        t["перк"] += ping(sg([N(o + 5, 1, 60, 70), N(o + 13, 1, 63, 64)]), 50)
        if i % 2 == 1:
            t["открытый хэт"] += [N(o + 4, 2, 60, 84)]
        t["мелодия"] += bar(o, (LATE_END if b >= 68 else LATE)[i % 4])
        if i % 2 == 1:
            t["подголосок"] += bar(o, ((0, 6, 48, 84),) if i % 4 == 1 else ((0, 4, 48, 80), (8, 4, 43, 76)))
    t["808"] = [n for n in t["808"] if int(n.pos // 16) != 65]
    t["808"] += sg(glide(65 * 16, 7, C, G, at=5, over=2) + [N(65 * 16 + 10, 6, G, 104)])        # такт 66
    t["бочка"] += high_kick(63 * 16, CLAVE_BACK, only=(8, 11, 14))                              # такт 64, вдох

    # Вдохи и провалы: плёнка встаёт во второй половине тактов 24, 48 и 56
    for start, end in ((8.5, 9), (24.5, 25), (48.5, 49), (56, 57), (64.5, 65), (72.5, 73), (32, 33)):
        a, z = (start - 1) * 16, (end - 1) * 16
        for k in ("808", "клэп", "хэт", "открытый хэт", "перк"):
            t[k] = mute(t[k], a, z)
        t["бочка"] = [n for n in t["бочка"] if not a <= n.pos < z or n.key > 80]
    for b in (23, 47, 55):
        t["хэт"] += roll(b * 16 + 8, 8, 12, vel=(110, 50), pitch=-12, curve=.5)

    t["хэт"] = human(t["хэт"], 2, seed=115)
    return {k: sorted(v) for k, v in t.items()}

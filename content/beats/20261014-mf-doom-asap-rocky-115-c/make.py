def cut(*pieces) -> list:
    """Куски нарезки одного такта — (куда, откуда, длина[, вид]) в шестнадцатых: «куда» на нечётном шаге сдвинут свингом
    петли и от сдвига кусок короче, а не лезет на следующий; «откуда» на шагах 3 и 11 такта петли — 3,16 и 11,16:
    там её куски и стоят."""
    def at(x: float) -> float:
        return round(swing(x, SW), 3)
    return [[at(to), at(frm % 16) + frm // 16 * 16, round(min(ln, at(to + ln) - at(to)), 3), *kind]
            for to, frm, ln, *kind in pieces]



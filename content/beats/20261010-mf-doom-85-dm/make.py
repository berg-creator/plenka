def bar(o: int, notes, louder: int = 0) -> list[N]:
    return [N(o + p, ln, k, v + louder) for p, ln, k, v in notes]


def perc_kick(o: int, notes) -> list[N]:
    return [N(o + p, .4, k, v) for p, k, v in notes]


def lead(o: int, phrase, louder: int = 0) -> list[N]:
    """Фраза мелодии; перед долгим ля (от трёх шестнадцатых) — короткий подъезд снизу."""
    out = []
    for n in bar(o, phrase, louder):
        out += grace(n, step=-2, ln=.5) if n.key == 69 and n.ln >= 3 else [n]
    return out



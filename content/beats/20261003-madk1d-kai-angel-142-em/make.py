    for k in t:
        t[k] = mute(t[k], (FALSE - 1) * 16 + 8, FALSE * 16)
    # Ложный вход: первые полтакта припева — тишина всем партиям, удар — на шаге 8
    for k in t:
        t[k] = mute(t[k], FALSE * 16, FALSE * 16 + 8)
    t["бочка"].append(N(FALSE * 16 + 8, 1, 60, 104))
    t["808"].append(N(FALSE * 16 + 8, 2, 28, 118))
    # Такты без низа: 808 и бочка молчат, хвосты обрываются
    for k in ("808", "бочка"):
        for b in DROPS:
            t[k] = mute(t[k], b * 16, (b + 1) * 16)
    t["808"] = human(sorted(t["808"]), 7, seed=3)

    # Плёнка встаёт: перед каждым припевом хэт тормозит и съезжает вниз на октаву
    for b in (7, FALSE - 1):
        t["хэт"] = mute(t["хэт"], b * 16 + 8, (b + 1) * 16)
        t["хэт"] += roll(b * 16 + 8, 8, 12, vel=(100, 55), pan=(-30, 30), pitch=-12, curve=.5)
    return {k: sorted(v) for k, v in t.items()}

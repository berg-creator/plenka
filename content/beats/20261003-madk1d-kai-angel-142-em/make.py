def bars(*parts):
    return [b for a, z in parts for b in range(a, z)]


def swap(hats: list[N], fill: list[N]) -> list[N]:
    """Дробь встаёт вместо ударов основного рисунка на своём отрезке."""
    if not fill:
        return hats
    start, end = min(n.pos for n in fill), max(n.pos + n.ln for n in fill)
    return [h for h in hats if not start <= h.pos < end] + fill


def motif(o: int, second: bool, down: int = 0, vel: int = 100, low_b: bool = False) -> list[N]:
    out = []
    for p, ln, k in (MOTIF_B if second else MOTIF_A):
        k = k - 12 if low_b and k == 71 else k
        k = k - down if k != 52 else k                 # ми октавой ниже остаётся на месте: ниже — каша с 808
        out.append(N(o + p, ln, k, vel if p % 8 == 0 else vel - 12))
    return out


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("аккорды", "мелодия", "контрмелодия", *DRUMS)}
    hook, verse = set(bars(*HOOKS)), set(bars(*VERSES))

    # Музыка парами тактов: в припеве, вступлении и конце орган тянется, в куплете рублен; конец пары пуст
    for a in range(0, INFO["bars"], 2):
        o = a * 16
        if a + 1 in DROPS:                             # такт без низа — и без музыки
            t["аккорды"] += [N(o, 16, k, 82) for k in CHORD]
        elif a == 6:                                   # вступление: вторая половина такта 8 — вдох
            t["аккорды"] += [N(o, 24, k, 82) for k in CHORD]
        elif a in verse:
            t["аккорды"] += chop(o, CHORD, "x-----x-----x---x-----x----.....", vel=74)
        elif a == 74:                                  # конец: один аккорд на полтакта
            t["аккорды"] += [N(o + 16, 8, k, 70) for k in CHORD]
        else:
            t["аккорды"] += [N(o, 27, k, 82) for k in CHORD]

    for b in [*range(4, 8), *bars(*HOOKS), *range(72, 75)]:
        if b in DROPS:
            continue
        o, second = b * 16, b % 2 == 1
        notes = motif(o, second, low_b=b in bars(HOOK2) and not second)
        if b == 7:                                     # вдох перед первым припевом
            notes = [n for n in notes if n.pos < o + 8]
        t["мелодия"] += notes
        if b >= 16 and b not in bars(INTRO) and b < 74:     # контрмелодия: со второй половины первого припева
            t["контрмелодия"] += motif(o, second, down=12, vel=84)

    # Вступление: томы рисунком, хэта нет до «плёнки» в такте 8
    for b in bars(INTRO):
        o = b * 16
        t["перк"] += hits(o, "x.....x.......x.", key=55, vel=96) if b % 2 == 0 else hits(o, "x.....x.........", key=55, vel=90)

    for b in bars(*HOOKS, *VERSES):
        o, c = b * 16, b % 4
        first = b in (HOOK1[0], VERSE1[0], HOOK2[0], VERSE2[0])
        # клэп только на шаге 8; первый клэп блока — с форшлагом
        clap = N(o + 8, 1, 60, 112)
        t["клэп"] += flam(clap, gap=.5) if first else [clap]

        if b not in DROPS:
            # бочка: на первой доле первого и третьего такта круга, на третьей доле — второго и четвёртого
            t["бочка"] += hits(o, "x..............." if c in (0, 2) else "........x.......", vel=96)
            for p, ln, key in BASS[c]:
                if b + 1 in DROPS and p == 13:         # раз в блок: ре съезжает слайдом на ми
                    t["808"] += glide(o + p, ln, key, 28, at=1, over=2, vel=110)
                else:
                    t["808"].append(N(o + p, ln, key, 110))

        if b in hook:
            hats = hits(o, "X.x.X.x.X.x.X.x.", vel=84, ln=.5)
            fill = roll(o + 12, 4, 6, vel=(55, 106), pan=(-35, 35), curve=1.6) if b % 8 == 7 and b not in DROPS else []
            if b % 2 == 1 and b not in DROPS:          # лестница томов в пустой доле музыки
                t["перк"] += [N(o + p, 2, k, v, pan) for p, k, v, pan in STAIRS]
        else:
            hats = hits(o, "x.X.x.X.x.X.x.X.", vel=80, ln=.5)
            fill = roll(o + 12, 4, 3, vel=(70, 96)) if b % 8 == 7 and b not in DROPS else []
            if c == 3:
                t["открытый хэт"].append(N(o + 14, 2, 60, 86))
        t["хэт"] += swap(spread(hats, 6, seed=b), fill)


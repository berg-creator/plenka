def kick_perk(b: int, o: float) -> list[N]:
    """Кик как перк — та же бочка высоко, по нотам петли; фигуры свои, не из «Фонаря» и «Витрины»."""
    hi = b >= CUT
    tri = (96, 101, 108) if hi else (97, 99, 103)          # до, фа, до — до-диез, ре-диез, соль
    reply = (111, 101) if hi else (111, 100)
    up = (99, 101, 104, 108) if hi else (97, 99, 100, 103)
    bar = b + 1
    if bar in (2, 12, 28, 52, 68):                          # тройка триолью на четвёртой доле, слева — центр — справа
        return [N(o + 12 + i * 4 / 3, .3, k, v, p) for i, (k, v, p) in enumerate(zip(tri, (124, 112, 120), (-45, 0, 45)))]
    if bar in (4, 18, 36, 60, 76):                          # ответ клэпу: два удара сразу за ним
        return [N(o + 9, .3, reply[0], 124, 40), N(o + 10, .3, reply[1], 110, -40)]
    if bar in (44, 84):                                     # лесенка вверх на четвёртой доле
        return [N(o + 12 + i, .3, k, 106 + i * 6) for i, k in enumerate(up)]
    if bar == 40:                                           # съезд на две октавы перед частью без барабанов
        return [x._replace(ln=min(x.ln, .3)) for x in roll(o + 12, 4, 10, key=111, pitch=-24, curve=.8,
                                                           vel=(120, 50, 20, 8))]
    return []


def nudge(bone: str, seed: int) -> str:
    """Деталь такта: в половине тактов одна шестнадцатая костяка меняется — призрак в пустую нечётную или пропуск
    восьмой вне доли. Костяк возвращается через восемь тактов, детали — нет."""
    r, cells = random.Random(seed), list(bone)
    if r.random() < .5:
        return bone
    empty = [i for i in (1, 3, 5, 7, 9, 11, 13, 15) if cells[i] == "."]
    weak = [i for i in (2, 6, 10, 14) if cells[i] != "."]
    if empty and (r.random() < .6 or not weak):
        cells[r.choice(empty)] = "o"
    elif weak:
        cells[r.choice(weak)] = "."
    return "".join(cells)


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "плак", "808", "бочка", "бочка 2", "клэп", "хэт", "открытый хэт", "перк")}

    for b in range(BARS):
        o, odd, bar, name = b * 16, b % 2, b + 1, part(b)
        rel, late = b - START[name], b >= CUT
        bar_t = {k: [] for k in t}

        # Музыка: пэд — во всех частях, кроме вступления и второй половины конца; мелодия — в главных частях,
        # в части без барабанов — только зов, тише; плак — с такта 13 в главных частях
        if name not in ("вступление",) and b < 84:
            bar_t["пэд"] += [N(o, 14, k, 80) for k in (BODY_B if late else BODY)[odd]]
        if name in ("первая", "вторая", "перелом", "третья") or (name == "сухая" and not odd):
            if late:
                notes = (ANSWER_B2 if name == "третья" else ANSWER_B) if odd else \
                        (CALL_B2 if b % 4 == 2 else CALL_B)
            elif name == "сухая":
                notes = CALL_2 if b % 4 == 2 else CALL
            elif b == 39:
                notes = ANSWER_END
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 or name == "вторая" and rel >= 8 else ANSWER
            else:
                notes = CALL_2 if b % 4 == 2 else CALL
            soft = .72 if name == "сухая" else 1
            bar_t["мелодия"] += [N(o + p, ln, k, round(v * soft)) for p, ln, k, v in notes]
        if (name in ("первая", "вторая") and b >= 12) or name in ("перелом", "третья"):
            bar_t["плак"] += swing([N(o + p, ln, k, v) for p, ln, k, v in (BRIGHT_B if late else BRIGHT)[odd]], sw(b))

        # 808: клетка на два такта, рисунок части; в тихих частях — долгие ноты
        if not odd:
            if name in ("тихая", "сухая"):
                pat = BASS_LONG
            elif name == "конец":
                pat = BASS_LONG_B
            elif name == "вступление":
                pat = ()
            else:
                cells = BASS_B if late else BASS_A
                pat = cells[(b // 2 + (2 if name == "вторая" else 0)) % 4]
            t["808"] += [N(o + p, ln, k, 112) for p, ln, k in pat]
        if bar in SLIDES:                                    # слайд — событие: в конце такта нота уезжает
            a, z = SLIDES[bar]
            t["808"] = mute(t["808"], o + 13, o + 16)
            t["808"] += glide(o + 13, 3, a, z, at=1.5, over=1)

        bar_t["бочка 2"] += kick_perk(b, o)

        if b in PLENKA:                                      # «плёнка встаёт»
            bar_t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        if hat_only(b):                                      # тихая и конец: хэт четвертями с дробью
            key = 60 if name == "тихая" else 57
            hat = swing(spread(hits(o, QUARTERS[b % 4], key=key, vel=78, ln=.5), 38, seed=b), sw(b))
            hat = over(hat, (FILLS["d"], FILLS["e"], FILLS["g"], FILLS["i"])[b % 4](o, key))
            bar_t["хэт"] += mute(hat, o + 8, o + 16) if b in PLENKA else hat
            perc = hits(o, PERCS[late][odd], key=60, vel=66, accent=1.2, ghost=.45)
            bar_t["перк"] += swing(spread(perc, 46, seed=b + 500), sw(b))

        if drums_on(b):
            kick = hits(o, KICKS[name][rel % 4], vel=104, ghost=.45)
            bar_t["бочка"] += swing(kick, sw(b))

            # Клэп на третьей доле на 9 мс позже; через такт отвечает сам себе: до перелома шаг 12, на три полутона ниже,
            # после — шаг 14, на три выше; сторона ответа меняется каждый раз
            claps = [N(o + 8.1, 1, 60, 112)]
            if odd:
                side = 40 if (b // 2) % 2 else -40
                claps += [N(o + 14, 1, 63, 74, side)] if late else [N(o + 12, 1, 57, 72, side)]
            if rel % 4 == 2:
                claps += [N(o + (2 if late else 14), 1, 60, 40)]          # тихий призрак
            if b in ENTRY:
                claps = flam(claps[0], .25, .5) + claps[1:]
            bar_t["клэп"] += swing(claps, sw(b))

            key = {"первая": 60, "вторая": 62, "перелом": 58, "третья": 57}[name]
            plan = PLANS[(b // 8 + (3 if late else 0)) % len(PLANS)].split()[b % 8]
            bone, fills = int(plan[0]), plan[1:]
            hat = swing(spread(hits(o, nudge((BONES_B if late else BONES)[bone], b), key=key, vel=84, ln=.5), 38, seed=b),
                        sw(b))
            hat = over(hat, *(FILLS[f](o, key) for f in fills))
            if b % 8 == 7 and b not in PLENKA:              # хэт-лесенка в последнем такте восьмёрки
                hat = [n._replace(key=n.key + LADDER[int(n.pos % 16 // 4)]) for n in hat]
            bar_t["хэт"] += hat

            perc = hits(o, PERCS[late][odd], key=64 if odd else 60, vel=72, accent=1.2, ghost=.45)
            if b % 8 == 3:
                perc += echo([N(o + 13, 1, 60, 90)], 1, times=2, decay=.6, width=44, pitch=-3)
            bar_t["перк"] += swing(spread(perc, 46, seed=b + 300), sw(b))
            if b % 4 == 2:
                bar_t["открытый хэт"] += [N(o + (14 if b % 8 == 2 else 6), 2, 60, 78)]

        if b in STOP:                                        # стоп-тайм: всё бьёт вместе на шагах 0, 6 и 12, между — тишина
            for k in ("бочка", "клэп", "хэт", "перк", "открытый хэт"):
                bar_t[k] = []
            stab = (0, 6, 12)
            bar_t["бочка"] = [N(o + s, 1, 60, v) for s, v in zip(stab, (120, 104, 112))]
            bar_t["клэп"] = [N(o + s, 1, 60, v) for s, v in zip(stab, (90, 100, 114))]
            bar_t["хэт"] = [N(o + s, .5, 60, 96, p) for s, p in zip(stab, (-30, 0, 30))]
            if b == 19:                                      # отскок в конце стоп-тайма перед тихой частью
                bar_t["бочка"] += [N(o + 14, .5, 60, 108), N(o + 14.32, .4, 60, 89), N(o + 14.84, .4, 60, 64)]
        if b in BOUNCE:                                      # отскок перед концом
            bar_t["бочка"] = [n for n in bar_t["бочка"] if n.pos < o + 12] + [
                N(o + 12, .5, 60, 108), N(o + 12.32, .4, 60, 89), N(o + 12.84, .4, 60, 64)]

        # Плёнка и провал перед концом: барабаны молчат вторую половину такта, кроме дроби хэта
        if b in PLENKA:
            for k in ("бочка", "клэп", "перк", "открытый хэт"):
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        if b == 79:
            for k in ("бочка", "клэп", "хэт", "перк", "открытый хэт"):
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        for k, notes in bar_t.items():
            t[k] += notes

    # 808 в стоп-тайме — только на шагах 0, 6, 12; молчит во вдохах и провалах
    for b in STOP:
        o = b * 16
        t["808"] = mute(t["808"], o, o + 16)
        root = E if b < CUT else C
        t["808"] += [N(o + s, 2, root, 112) for s in (0, 6, 12)]
    for a, z in [(b * 16 + 8, b * 16 + 16) for b in (*PLENKA, 79)] + [(87 * 16 + 8, 88 * 16)]:
        t["808"] = mute(t["808"], a, z)
    t["808"] = human(swing([n for n in t["808"] if n.pos < CUT * 16], .56)
                     + swing([n for n in t["808"] if n.pos >= CUT * 16], .60), 6, seed=150)
    for k in ("мелодия", "пэд", "плак"):                     # в паузах петли молчат и свои партии
        for a, z in QUIET:
            t[k] = mute(t[k], a, z)
    t["пэд"] = mute(t["пэд"], 84 * 16, 88 * 16)
    return {k: sorted(set(v)) for k, v in t.items()}

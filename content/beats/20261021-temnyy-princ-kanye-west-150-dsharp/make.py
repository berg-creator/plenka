    """Часть по такту, счёт с нуля."""
    for name, end in (("вступление", 4), ("первая", 20), ("тихая", 24), ("вторая", 40), ("сухая", 48),
                      ("перелом", 64), ("третья", 80)):
        if b < end:
            return name
    return "конец"



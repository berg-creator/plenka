HAT = "XoxoxoX.xoXox.xo"                                 # 14 ударов: дыры на шагах 7 и 13
ROLLS = (D1 - 1, BRK - 1, D2 - 1, SOFT - 1, D3 - 1, BARE - 1, D4 - 1, OUT - 1)       # дробь в последней доле такта

def drums(b: int) -> bool:
    return D1 <= b < BRK or D2 <= b < OUT


def high(b: int) -> bool:
    """Суб октавой выше: вступление с разгоном, тихая часть и конец."""
    return b < D1 or SOFT <= b < D3 or b >= OUT


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("аккорды", "808", "клэп", "хэт")}

    # Аккорды: один такт весь бит; в провале молчат, в тихой части — тише
    for b in range(BARS):
        if BRK <= b < D2:
            continue
        soft = .6 if SOFT <= b < D3 else 1
        t["аккорды"] += [N(b * 16 + p, 2, k, round(v * soft)) for p, keys, v in STABS for k in keys]
    t["аккорды"] = human(sorted(t["аккорды"]), 5, seed=140)

    # Суб: весь бит, рисунок на восемь тактов; последние два такта — одна нота ми
    for b in range(BARS - 2):
        t["808"] += [N(b * 16 + p, ln, k + 12 * high(b), 110) for p, ln, k in SUB[b % 8]]
    t["808"] = [n for n in t["808"] if n.pos < (BARS - 2) * 16 - 1e-6 or n.pos + n.ln <= (BARS - 2) * 16]
    t["808"].append(N((BARS - 2) * 16, 32, E + 12, 110))

    # Клэп: третья доля; через такт — тихий удар на шаге 2; в каждом четвёртом такте три удара в конце
    for b in range(BARS):
        o, clap = b * 16, N(b * 16 + 8, 1, 60, 112)
        if b in (RISE + 7, D1 - 1):                       # одиночные удары до входа барабанов
            t["клэп"].append(clap._replace(vel=98))
        if not drums(b):
            continue
        t["клэп"] += flam(clap) if b in (D1, D2, D3, D4) else [clap]
        if BARE <= b < D4:
            continue
        if b % 2:
            t["клэп"].append(N(o + 2, 1, 60, 72))
        if b % 4 == 3:
            t["клэп"] += [N(o + 12, 1, 60, 58), N(o + 13, 1, 60, 66), N(o + 14, 1, 60, 80)]

    # Хэт: один такт по кругу, дробь в конце части и триоли; в тактах 65–72 молчит
    for b in range(BARS):
        o = b * 16
        fill = roll(o + 12, 4, (4, 8), vel=(58, 108), pan=(-30, 30)) if b in ROLLS else []
        if drums(b) and not BARE <= b < D4:
            bone = spread(hits(o, HAT, vel=84, ln=.5, ghost=.6), 30, seed=b)
            trip = roll(o + 8, 4, 6, vel=[92, 60, 72], pan=[-20, 20]) if b in TRIPS else []
            t["хэт"] += over(bone, fill, trip)
        else:
            t["хэт"] += fill                              # дробь ко входу дропа: такты 24, 40 и 72
    return {k: sorted(v) for k, v in t.items()}

def drums(b: int) -> bool:
    return D1 <= b < BRK or D2 <= b < OUT


def high(b: int) -> bool:
    """Суб октавой выше: вступление с разгоном, тихая часть и конец."""
    return b < D1 or SOFT <= b < D3 or b >= OUT


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("аккорды", "808", "снейр", "клэп", "второй снейр", "бочка", "хэт")}

    # Аккорды: один такт весь бит; в провале молчат, в тихой части — тише
    for b in range(BARS):
        if BRK <= b < D2:
            continue
        soft = .6 if SOFT <= b < D3 else 1
        t["аккорды"] += [N(b * 16 + p, 2, k, round(v * soft)) for p, keys, v in STABS for k in keys]
    t["аккорды"] = human(sorted(t["аккорды"]), 5, seed=140)

    # Суб: весь бит, рисунок на восемь тактов
    for b in range(BARS):
        bar = SUB[b % 8] if b < BARS - 2 else END[b - BARS + 2]
        t["808"] += [N(b * 16 + p, ln, k + 12 * high(b), 110) for p, ln, k in bar]

    for b in range(BARS):
        o, turn = b * 16, b % 4
        if b == RISE + 7:                                 # такт 16: четыре удара клэпа с нарастанием
            t["клэп"] += [N(o + 12 + i, 1, 60, v) for i, v in enumerate((44, 58, 78, 108))]
        if b == D1 - 1:                                   # такт 24: два удара ко входу барабанов
            t["второй снейр"] += [N(o + 9, 1, RIM, 76), N(o + 12, 1, RIM, 96)]
        if not drums(b):
            continue
        t["снейр"].append(N(o + 8, 1, SNARE, 127))        # главный удар: третья доля каждого такта
        t["клэп"].append(N(o + 8, 1, 60, 120))
        if BARE <= b < D4:                                # такты 65–72: один главный удар
            continue
        t["второй снейр"] += [N(o + p, 1, RIM, 118) for p in SECOND[turn]]
        t["хэт"] += human(spread(hits(o, HAT[turn], vel=88, ln=.5), 30, seed=b), 5, seed=b)
        if turn == 3:
            t["бочка"] += [N(o + p, 1, TOM, v) for p, v in KNOCK]
            t["хэт"] += roll(o + 12, 2.5, 5, vel=(72, 104), pan=(-30, 30))
    return {k: sorted(v) for k, v in t.items()}

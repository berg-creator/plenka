def root(b: int) -> int:
    """Бас автора по тактам петли: D# D# C C D# D# C C."""
    return EB if b % 8 in (0, 1, 4, 5) else C


def sw8(notes: list[N], share: float = SW) -> list[N]:
    """Свинг восьмых: счёт «половиной» — шестнадцатые андера здесь восьмые бита, и гнуть надо их."""
    out = []
    for n in notes:
        a, z = 2 * swing(n.pos / 2, share), 2 * swing((n.pos + n.ln) / 2, share)
        out.append(n._replace(pos=a, ln=z - a))
    return out



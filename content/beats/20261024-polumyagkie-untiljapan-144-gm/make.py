def ostinato(o: int, pat: str, base: int) -> list[N]:
    """Спиккато восьмыми: сильная доля громче, слабая и шестнадцатые — тише, как смычок вверх и вниз."""
    out = []
    for s, c in enumerate(pat):
        if c in OST_KEY:
            v = base + (8 if s % 4 == 0 else 0) - (10 if s % 2 else 0)
            out.append(N(o + s, 1, OST_KEY[c], max(1, min(127, v))))
    return out


def theme(o: int, t: int, shift: int = 0, add: int = 0, peak: bool = False) -> list[N]:
    notes = cells(o, PEAK[t] if peak and t in PEAK else THEME[t], shift, add)
    if t in (0, 4):                                      # подъезд к ре с до — короче шестнадцатой
        notes = notes[:1] + grace(notes[1], step=-2, ln=.5)
    return sw8(notes)


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in (*MUSIC, "808", "бочка", "бочка 2", "клэп", "хэт", "открытый хэт", "перк", "литавры")}

    for b in range(BARS):
        o, name, r = b * 16, part(b), root(b)
        rel = b - START[name]
        share = SW3 if b in THREE else SW
        bar = {k: [] for k in t}

        # Пэд: во вступлении и концовке — на два такта; в куплетах дышит — полтора такта из двух; в припевах — по такту
        if name in ("вступление", "концовка") and b % 2 == 0 and b < 70:
            bar["пэд"] += [N(o, 32, k, 70 + 8 * (b % 4)) for k in PAD[KIND[r]]]
        elif name in ("куплет", "куплет 2", "куплет 3") and b % 2 == 0:
            bar["пэд"] += [N(o, 24, k, 84 + 2 * (name == "куплет 2")) for k in PAD[KIND[r]]]
        elif name in HOOKS:
            bar["пэд"] += [N(o, 16, k, {"припев": 86, "припев 2": 90}.get(name, 100)) for k in PAD[KIND[r]]]

        # Тема: голова пианино во вступлении, целиком в припевах, оборванная — в концовке
        if name == "вступление" and b % 2:
            bar["пианино"] += theme(o, 0, add=-30 + 6 * b)
        elif name == "припев":
            bar["мелодия"] += theme(o, rel)
        elif name == "припев 2":
            bar["мелодия 3"] += theme(o, rel, -12, -4)
            bar["пианино"] += theme(o, rel, 0, -22)
        elif name == "кульминация":
            for k, shift in (("мелодия", 0), ("мелодия 2", 0), ("мелодия 3", -12)):
                bar[k] += theme(o, rel, shift, 10, peak=True)
        elif b == 68:
            bar["пианино"] += theme(o, 0, add=-34)
        elif b == 69:
            bar["пианино"] += sw8([N(o, 4, 75, 70), N(o + 4, 4, 74, 62)])

        # Остинато: с 9-го такта, от части к части гуще и сильнее
        if name == "куплет" and b >= 8:
            bar["остинато"] += sw8(ostinato(o, OST[name][0], 56 + 2 * (b - 8)))
        elif name in ("припев", "куплет 2", "припев 2", "кульминация"):
            base = {"припев": 84, "куплет 2": 74 + rel, "припев 2": 94, "кульминация": 106}[name]
            bar["остинато"] += sw8(ostinato(o, OST[name][b % 2], base))
        elif name == "куплет 3" and rel >= 4:
            pat = "g.d.g.d.gdgdgdgd" if b == 58 else OST[name][0]
            bar["остинато"] += sw8(ostinato(o, pat, 70 + 18 * (rel - 4)))

        # Виолончель — свой рисунок
        if name == "куплет 2":
            bar["контрмелодия"] += cells(o, CELLO_V2[(rel // 4) % 2][rel % 4], add=8 + 2 * (rel // 4))
        elif name in ("припев 2", "кульминация"):
            v = 104 if name == "припев 2" else 118
            bar["контрмелодия"] += sw8([N(o + p, ln, k, v - 4 * (p == 12)) for p, ln, k in CELLO_RUN[rel]])
        elif name == "куплет 3" and rel < 7:
            bar["контрмелодия"] += cells(o, CELLO_V3[rel], add=8)

        # Валторна — с 57-го такта и в кульминации, фанфара на последних двух
        if name == "куплет 3" and rel in (4, 5, 6):
            bar["валторна"] += [N(o, 16, (38, 43, 38)[rel - 4], (78, 86, 98)[rel - 4])]
        elif name == "кульминация":
            if rel == 6:
                bar["валторна"] += [N(o, 8, HORN[r], 112), N(o + 8, 8, 43, 116)]
            else:
                bar["валторна"] += [N(o, 14 + 2 * (rel == 7), HORN[r], 106 + 2 * rel)]

        # Яркий слой пианино — свинговые «и» куплета 2
        if name == "куплет 2":
            bar["пианино"] += sw8([N(o + p, ln, k, v) for p, ln, k, v in BRIGHT[r][b % 2]])

        # 808 за бочкой
        if name in BASS:
            if b in THREE:
                cs = [(p, 4, "r") for p, c in enumerate(THREE_KICK[b % 2]) if c != "."]
            else:
                cs = BASS[name][rel % 4]
            bar["808"] += sw8([N(o + p, ln, r + (12 if d == "8" else 0), 112) for p, ln, d in cs], share)
            if b in SLIDE:
                a, z = SLIDE[b]
                bar["808"] = mute(bar["808"], o + 6, o + 8) + sw8(glide(o + 6, 2, a, z, at=1, over=1))

        # Бочка
        if name in KICK:
            pat = THREE_KICK[b % 2] if b in THREE else KICK[name][rel % 4]
            bar["бочка"] += sw8(hits(o, pat, vel=104, ghost=.48), share)
        elif b == 3:                                            # подхват «4-а» в конце вступления
            bar["бочка"] += sw8([N(o + 14, 1, 60, 100)])

        # Кик-перк — голова темы: соль — ре — ми-бемоль
        if b in PERK:
            bar["бочка 2"] += [N(o + s, .3, k, v) for s, k, v in ((0, 91, 124), (8, 98, 118), (12, 99, 112))]

        # Клэп: в куплетах лениво (8,12), в припевах и кульминации точно и второй тише на 14; призраки малого
        if name in ("куплет", "куплет 2", "куплет 3"):
            claps = [N(o + 8.12, 1, 60, 110)]
            ghosts = [(12, 44)] + ([(14, 38)] if b % 2 else [])
            if rel % 8 == 7:
                claps = flam(claps[0], .25, .5)
            bar["клэп"] += claps + sw8([N(o + s, 1, 60, v) for s, v in ghosts])
        elif name in HOOKS:
            extra = [(14, 70)] + ([(6, 52)] if name != "припев" and b % 2 else [])
            bar["клэп"] += [N(o + 8, 1, 60, 112)] + sw8([N(o + s, 1, 60, v) for s, v in extra])
            if rel == 0:
                bar["клэп"] = flam(bar["клэп"][0], .25, .5) + bar["клэп"][1:]

        # Хэт: во вступлении — с 3-го такта, в куплете 3 — с 57-го
        if name != "концовка" and not (name == "вступление" and b < 2) and not (name == "куплет 3" and rel < 4):
            plans = PLANS[name]
            plan = (plans if isinstance(plans, str) else plans[(rel // 8) % len(plans)]).split()[rel % (4 if name == "вступление" else 8)]
            bone, fills = int(plan[0]), plan[1:]
            if name == "куплет 2" and rel < 8 and b % 2 == 0:  # триоли восьмых целым тактом, высота волной
                hat = roll(o, 8, 6, vel=(96, 64, 88), pitch=(0, 2, 0)) + roll(o + 8, 8, 6, vel=(90, 60, 100), pitch=(0, -2, 1))
                hat = spread(hat, 36, seed=b)
            else:
                key = 62 if name in HOOKS else 60
                hat = sw8(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b))
                hat = over(hat, *(FILLS[f](o) for f in fills))
            bar["хэт"] += hat
        if b in PLENKA:
            bar["хэт"] = mute(bar["хэт"], o + 8, o + 16) + roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30),
                                                                pitch=-12, curve=.5)
        if b == 58:                                             # перед стопом хэт разгоняется
            bar["хэт"] = mute(bar["хэт"], o + 8, o + 16) + roll(o + 8, 8, (4, 8), vel=(60, 112), pan=(-24, 24), curve=1.4)

        # Открытый хэт — в припевах через такт; перк — на свинговых «и»
        if name in HOOKS and b % 2:
            bar["открытый хэт"] += sw8([N(o + 6, 2, 60, 76)])
        if name in (*HOOKS, "куплет 2") or (name in ("куплет", "куплет 3") and b % 2):
            bar["перк"] += sw8(ping(hits(o, PERC[b % 2], key=60 + 2 * (b % 2), vel=70, accent=1.2), 46), share)

        # Литавры — сердце во вступлении и концовке, тремоло перед стопом; там, где играет 808, их нет
        if name == "вступление":
            bar["литавры"] += [N(o, 6, 60, 84 + 4 * b), N(o + 6, 6 + 4 * (b != 2), 60, 104 + 4 * b)]
            if b == 2:
                bar["литавры"] += [N(o + 12, 4, 60, 72)]
            if b == 3:
                bar["литавры"] += roll(o + 8, 6, 6, vel=(60, 116))
        elif b == 58:
            bar["литавры"] += roll(o + 8, 8, (4, 8), vel=(60, 124), curve=1.3)
        elif name == "концовка":
            bar["литавры"] += [N(o, 6 if rel < 2 else 16, 60, 100 - 10 * rel)] + ([N(o + 6, 10, 60, 116 - 12 * rel)] if rel < 2 else [])

        # Вдохи, бит-скип, провал и стоп
        if b in PLENKA:
            for k in ("бочка", "клэп", "перк", "открытый хэт"):
                bar[k] = mute(bar[k], o + 8, o + 16)
            bar["808"] = mute(bar["808"], o + 8, o + 16)
        if b in SKIP:
            for k in ("бочка", "клэп", "перк", "открытый хэт", "808", "хэт", "остинато"):
                bar[k] = mute(bar[k], o + 8, o + 16)
        if b in HOLE:
            for k in (*DRUMS, *MUSIC):
                bar[k] = [n for n in bar[k] if k == "бочка 2"]
        if b == 51:                                             # перед подъездом последняя доля пуста
            for k in ("бочка", "клэп", "перк", "открытый хэт", "808", "хэт"):
                bar[k] = mute(bar[k], o + 12, o + 16)
        if b == 58:                                             # бас и бочка уходят перед стопом
            for k in ("бочка", "808"):
                bar[k] = mute(bar[k], o + 8, o + 16)
        if b == STOP:
            bar = {k: [] for k in bar}
        if b == 60:                                             # 808 входит после удара
            bar["808"] = mute(bar["808"], o, o + 4)
        for k, notes in bar.items():
            t[k] += notes

    t["808"] = human(t["808"], 6, seed=144)
    for k in MUSIC:                                         # в паузах молчит вся музыка
        for b in PLENKA:
            t[k] = mute(t[k], b * 16 + 8, b * 16 + 16)
        t[k] = mute(t[k], HOLE[0] * 16, HOLE[0] * 16 + 16)
        t[k] = mute(t[k], STOP * 16, STOP * 16 + 16)
        t[k] = [n._replace(ln=min(n.ln, BARS * 16 - n.pos)) for n in t[k]]
    return {k: sorted(set(v)) for k, v in t.items()}

def nudge(bone: str, seed: int) -> str:
    """Деталь такта: в половине тактов одна шестнадцатая костяка меняется — призрак в пустую нечётную или пропуск
    восьмой вне доли. Костяк возвращается через четыре такта, детали — нет: так у владельца (мерка хэта)."""
    r, cells = random.Random(seed), list(bone)
    if r.random() < .5:
        return bone
    empty = [i for i in (1, 3, 5, 7, 9, 11, 13, 15) if cells[i] == "."]
    weak = [i for i in (2, 6, 10, 14) if cells[i] != "."]
    if empty and (r.random() < .6 or not weak):
        cells[r.choice(empty)] = "o"
    elif weak:
        cells[r.choice(weak)] = "."
    return "".join(cells)


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "плак", "808", "бочка", "бочка 2", "клэп", "хэт", "открытый хэт", "перк")}

    def hush(notes: list[N]) -> list[N]:                         # в паузах петли молчат и свои партии
        for a, b in QUIET:
            notes = mute(notes, a, b)
        return notes

    for b in range(BARS):
        o, odd, bar, name = b * 16, b % 2, b + 1, part(b)
        rel = b - START[name]
        cell = o - 16 * odd                                      # начало двухтактной клетки
        bar_t = {k: [] for k in t}

        # Музыка — как в v2, сдвинута на 12 тактов
        if body_on(b):
            bar_t["пэд"] += [N(o, 16, k, 88) for k in BODY[odd]]
        if bright_on(b):
            bar_t["плак"] += [N(o + p, 2, k, v) for p, k, v in BRIGHT[odd]]
        if tune_on(b):
            if b >= BARS - 2:
                notes = ANSWER_END if odd else CALL
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 or b >= 39 else ANSWER
            else:
                notes = CALL_2 if 23 <= b < 32 or b >= 62 else CALL
            tune = [N(o + p, ln, k, v) for p, ln, k, v in notes]
            if not odd and (b - 4) % 8 == 2 and b >= 4:          # подъезд к верхнему си раз в восьмёрку
                top = next(n for n in tune if n.key == 71)
                tune = [n for n in tune if n != top] + grace(top, -1, .5)
            bar_t["мелодия"] += tune

        # 808: клетка на два такта, рисунок части
        if not odd:
            if b in HALF or b + 1 in HALF:
                pat = BASS_HALF[(b // 2) % 2]
            else:
                pat = (BASS_B if b >= 39 else BASS_A)[(b // 2) % 4]
            t["808"] += [N(cell + p, ln, k, 112) for p, ln, k in pat]
        if b in (31, 67):                                        # слайд — событие: си съезжает на фа-диез
            t["808"] = mute(t["808"], o + 14, o + 18)
            t["808"] += glide(o + 14, 2, B, FS, at=1, over=1)

        # Кик как перк — свой канал
        if bar in PERK:
            bar_t["бочка 2"] += PERK[bar](o)

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in PLENKA:
            bar_t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        if hat_only(b):                                          # вступление и разгон: один хэт четвертями
            hat = swing(spread(hits(o, HALF_BONES[b % 4], key=60, vel=78, ln=.5), 38, seed=b), sw(b))
            hat = over(hat, (FILLS["d"], FILLS["e"], FILLS["g"], FILLS["i"])[b % 4](o, 60))
            bar_t["хэт"] += mute(hat, o + 8, o + 16) if b in PLENKA else hat
            if bar == 39:                                        # дробь снейра вверх по высоте — в третью часть
                bar_t["клэп"] += roll(o + 8, 8, (4, 8), key=60, vel=(56, 118), pitch=(0, 7))

        if drums_on(b):
            kick = hits(o, KICKS[name][rel % len(KICKS[name])], vel=104, ghost=.45)
            if bar in ODD_KICK and kick:
                last = max(kick)
                kick = [n._replace(key=ODD_KICK[bar]) if n == last else n for n in kick]
            bar_t["бочка"] += swing(kick, sw(b))

            key = 62 if 23 <= b < 32 else 58 if 39 <= b < 55 else 60
            if b in HALF:                                        # своя находка: половинный счёт
                claps = swing([N(o + 8.1, 1, 60, 114)] + ([N(o + 14, 1, 60, 44)] if rel % 2 else []), sw(b))
                hat = swing(spread(hits(o, HALF_BONES[b % 4], key=key, vel=84, ln=.5), 38, seed=b), sw(b))
                hat = over(hat, (FILLS["d"], FILLS["e"], FILLS["g"], FILLS["i"])[b % 4](o, key))
                if bar == 62:                                    # выход: дробь снейра вверх на октаву
                    claps += roll(o + 12, 4, (3, 6), key=60, vel=(70, 112), pitch=(0, 12))
            else:
                claps = [N(o + 4.1, 1, 60, 106), N(o + 12.1 + (1 if bar in LATE else 0), 1, 60, 112)]
                claps += [] if bar in LADDER else [N(o + s, 1, 60, v) for s, v in GHOSTS[rel % 4]]
                claps += [N(o + s, 1, k, v) for s, k, v in LAUGH.get(LADDER.get(bar, 0), ())]
                if bar in ACROSS:
                    claps += [N(o + 14, 1, 60, 90)]
                if bar - 1 in ACROSS:
                    claps += [N(o + 2, 1, 60, 78)]
                if b in ENTRY:
                    claps = flam(claps[0], .25, .5) + claps[1:]
                claps = swing(claps, sw(b))
                plan = PLANS[((b - 4) // 8 + (2 if b >= 39 else 0)) % len(PLANS)].split()[(b - 4) % 8]
                bone, fills = int(plan[0]), plan[1:]
                hat = swing(spread(hits(o, nudge(BONES[bone], b), key=key, vel=84, ln=.5), 38, seed=b), sw(b))
                hat = over(hat, *(FILLS[f](o, key) for f in fills))
                if name == "тихая":                              # хэт волной: высота ходит ±4 полутона через два такта
                    hat = [n._replace(key=n.key + round(4 * math.sin(math.pi * (n.pos - START[name] * 16) / 16)))
                           for n in hat]
                if bar == 48:                                    # провал: хэт дробью по ушам
                    hat = over(hat, roll(o + 8, 8, (4, 8, 12), key=key, vel=(70, 110, 50), pan=(-40, 40), pitch=(0, 7, -5)))
            bar_t["клэп"] += [n for n in claps if not (b in PLENKA and n.pos >= o + 8)]
            bar_t["хэт"] += mute(hat, o + 8, o + 16) if b in PLENKA else hat

            perc = hits(o, PERCS[name in ("тихая", "конец")][odd], key=64 if odd else 60, vel=72, accent=1.2, ghost=.45)
            if (b - 4) % 8 == 3:
                perc += echo([N(o + 13, 1, 60, 92)], 1, times=2, decay=.6, width=44, pitch=3)
            bar_t["перк"] += swing(spread(perc, 46, seed=b + 300), sw(b))
            if (b - 4) % 4 == 2 and b not in HALF:
                bar_t["открытый хэт"] += [N(o + (14 if (b - 4) % 8 == 2 else 6), 2, 60, 78)]

        if b in BOUNCE:                                          # отскок перед входом: три удара, сила падает
            bar_t["бочка"] = [n for n in bar_t["бочка"] if n.pos < o + 10] + [
                N(o + 10, .5, 60, 108), N(o + 10.32, .4, 60, 89), N(o + 10.84, .4, 60, 64)]

        # Провалы и «плёнка»: глушим названных
        drop = DROPS.get(bar) or ((8, 16, DRUMS) if b in PLENKA else None)
        if drop:
            for k in drop[2]:
                if k != "808":
                    bar_t[k] = mute(bar_t[k], o + drop[0], o + drop[1])
        for k, notes in bar_t.items():
            t[k] += notes

    # 808: входит с такта 5, молчит в провалах, «плёнке» и разгоне; в сухой 33–36 — первая половина тактов 33 и 35
    silent = [(0, 64), (32 * 16 + 8, 34 * 16), (34 * 16 + 8, 39 * 16)]
    silent += [((bar - 1) * 16 + a, (bar - 1) * 16 + z) for bar, (a, z, who) in DROPS.items() if "808" in who]
    silent += [(b * 16 + 8, b * 16 + 16) for b in PLENKA]
    for a, z in silent:
        t["808"] = mute(t["808"], a, z)
    t["808"] = human(swing([n for n in t["808"] if n.pos < 39 * 16], .58) + swing([n for n in t["808"] if n.pos >= 39 * 16], .62),
                     6, seed=135)
    for k in ("мелодия", "пэд", "плак"):
        t[k] = hush(t[k])
    return {k: sorted(set(v)) for k, v in t.items()}

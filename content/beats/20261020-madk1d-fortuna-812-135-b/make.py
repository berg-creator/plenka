def nudge(bone: str, seed: int) -> str:
    """Деталь такта: в половине тактов одна шестнадцатая костяка меняется — призрак в пустую нечётную или пропуск
    восьмой вне доли. Костяк возвращается через четыре такта, детали — нет: так у владельца (мерка хэта)."""
    r, cells = random.Random(seed), list(bone)
    if r.random() < .5:
        return bone
    empty = [i for i in (1, 3, 5, 7, 9, 11, 13, 15) if cells[i] == "."]
    weak = [i for i in (2, 6, 10, 14) if cells[i] != "."]
    if empty and (r.random() < .6 or not weak):
        cells[r.choice(empty)] = "o"
    elif weak:
        cells[r.choice(weak)] = "."
    return "".join(cells)


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}
    low = low_map()

    def hush(notes: list[N]) -> list[N]:                         # в паузах петли молчит мелодия, кроме 5–11
        for a, b in QUIET:
            if a == 4 * 16:
                continue
            notes = mute(notes, a, b)
        return notes

    for b in range(BARS):
        o, odd = b * 16, b % 2
        cell = o - 16 * odd                                      # начало двухтактной клетки

        # Тема: зов в нечётных тактах (счёт с единицы), ответ — в чётных; с такта 5. В 5–11 — одна и тише
        if b >= 4:
            if b >= BARS - 2:
                notes = ANSWER_END if odd else CALL
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 or b >= 51 else ANSWER
            else:
                notes = CALL_2 if 35 <= b < 44 or b >= 74 else CALL
            soft = 14 if b < 11 else 0
            bar = [N(o + p, ln, k, v - soft) for p, ln, k, v in notes]
            if not odd and b % 8 == 6 and b >= 16:               # подъезд к верхнему си раз в восьмёрку
                top = next(n for n in bar if n.key == 71)
                bar = [n for n in bar if n != top] + grace(top, -1, .5)
            t["мелодия"] += bar

        # 808: клетка на два такта, рисунок части
        if not odd:
            if b in HALF or b + 1 in HALF:
                pat = BASS_HALF[(b // 2) % 2]
            else:
                pat = (BASS_B if b >= 51 else BASS_A)[(b // 2) % 4]
            t["808"] += [N(cell + p, ln, k, 112) for p, ln, k in pat]
        if b in (43, 79):                                        # слайд — событие: си съезжает на фа-диез
            t["808"] = mute(t["808"], o + 14, o + 18)
            t["808"] += glide(o + 14, 2, B, FS, at=1, over=1)

        # Кик как перк — задранная бочка по нотам петли
        if b == 46:
            t["бочка"] += [N(o + 8 + i * 2, .3, k, v) for i, (k, v) in enumerate(((83, 112), (78, 104), (77, 96), (95, 120)))]
        if b == 64:
            t["бочка"] += [N(o + 8 + i * .75, .3, k, v)
                           for i, (k, v) in enumerate(((95, 118), (90, 104), (89, 90), (83, 76), (78, 60), (77, 44)))]

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in PLENKA:
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        if not drums_on(b):
            continue

        if not odd:
            kick = hits(cell, KICKS[(b // 2 + (1 if b >= 51 else 0)) % len(KICKS)], vel=112, ghost=.45)
            t["бочка"] += swing(kick, SW)

        key = 62 if 35 <= b < 44 else 58 if 51 <= b < 67 else 60
        if b in HALF:                                            # своя находка: половинный счёт
            claps = [N(o + 8, 1, 60, 114)]
            hat = swing(spread(hits(o, HALF_BONES[b % 4], key=key, vel=84, ln=.5), 38, seed=b), SW)
            fill = (FILLS["d"], FILLS["e"], FILLS["g"], FILLS["i"])[b % 4]
            hat = over(hat, fill(o, key))
        else:
            claps = [N(o + 4, 1, 60, 106), N(o + 12, 1, 60, 112)]
            if b % 4 == 3:
                claps.append(N(o + 15, 1, 60, 54))
            if b in (16, 19, 51, 74):
                claps = flam(claps[0], .25, .5) + claps[1:]
            plan = PLANS[(b // 8 + (2 if b >= 51 else 0)) % len(PLANS)].split()[b % 8]
            bone, fills = int(plan[0]), plan[1:]
            hat = swing(spread(hits(o, nudge(BONES[bone], b), key=key, vel=84, ln=.5), 38, seed=b), SW)
            hat = over(hat, *(FILLS[f](o, key) for f in fills))

        perc = [N(o + 10, 1, 60, 70)] if odd else [N(o + 6, 1, 64, 62)] if b % 4 == 2 else []
        if b % 8 == 7:
            perc += echo([N(o + 13, 1, 60, 92)], 1, times=2, decay=.6, width=44, pitch=3)
        perc = swing(spread(perc, 46, seed=b + 300), SW)
        ohat = [N(o + (14 if b % 8 == 2 else 6), 2, 60, 78)] if b % 4 == 2 and b not in HALF else []

        if b == 43 or b == 83:                                   # обрыв барабанов в последней доле
            claps, hat, perc, ohat = (mute(x, o + 12, o + 16) for x in (claps, hat, perc, ohat))
        if b in PLENKA:
            claps, hat, perc, ohat = (mute(x, o + 8, o + 16) for x in (claps, hat, perc, ohat))
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat

    # Низ — по карте образца, по полтакта; во вдохах «плёнки» тишина; бочка-перк остаётся
    lows = {"808": t["808"], "бочка": t["бочка"]}
    for half, c in enumerate(low):
        a = half * 8
        if c == "#" and not (half % 2 and half // 2 in PLENKA):
            continue
        for k in lows:
            keep = [n for n in lows[k] if k == "бочка" and n.key > 75 and a <= n.pos < a + 8]
            lows[k] = mute(lows[k], a, a + 8) + keep
    for k in lows:                                               # бочка — только там, где играют барабаны
        if k == "бочка":
            lows[k] = [n for n in lows[k] if n.key > 75 or drums_on(int(n.pos // 16))]
    t["808"] = human(swing(lows["808"], SW), 6, seed=135)
    t["бочка"] = lows["бочка"]
    t["мелодия"] = hush(t["мелодия"])
    return {k: sorted(set(v)) for k, v in t.items()}

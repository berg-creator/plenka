def fall(o, at=12, top=99, down=24, n=10, ln=2, vel=114):
    """Съезд: n нот за ln шестнадцатых, вначале плотнее, сила со 114 падает сразу, потом тает до 8. Сила падает круче,
    чем в «Фонаре» (там 14 нот, прямая 114→10): проект прикидывает пик дорожки суммой нот внахлёст, и густой громкий
    съезд опустил бы фейдер «бочки 2» ниже основной бочки — а кик-перк должен быть ярче неё."""
    return [x._replace(ln=min(x.ln, .3)) for x in roll(o + at, ln, n, key=top, vel=(vel, round(vel * .35), round(vel * .18), 8),
                                                         pitch=-down, curve=.75)]



def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    def hush(notes: list[N]) -> list[N]:                         # в паузах петли молчит музыка
        for a, b in QUIET:
            notes = mute(notes, a, b)
        return notes

    for b in range(BARS):
        o, s, odd, lb = b * 16, section(b), b % 2, b % 4

        # Тема: зов в чётных тактах, ответ в нечётных; с такта 5; с такта 93 — одна петля
        if 4 <= b < 92 and s != "s":
            if b in (87, 91):
                notes = ANSWER_END
            elif odd:
                notes = ANSWER_2 if s in ("C", "D") and b % 4 == 3 else ANSWER
            else:
                notes = CALL_2 if s in ("C", "D") else CALL
            t["мелодия"] += [N(o + p, ln, k, v) for p, ln, k, v in notes]

        # Пэд: три такта си с фа-диезом, такт ре-диез с ля-диезом; в главных частях
        if s in ("B", "C", "D"):
            if lb == 0:
                t["пэд"] += [N(o, 28, k, v) for k, v in PAD_B]
            elif lb == 2:
                t["пэд"] += [N(o, 16, k, v) for k, v in PAD_B]
            elif lb == 3:
                t["пэд"] += [N(o, 12, k, v) for k, v in PAD_D]

        # 808
        if s in BASSED:
            if s == "s":                                          # своя находка: 808 поёт тему один
                bar = [N(o + 2, 2, Fs, 112), N(o + 4, 2, Ds, 104), N(o + 6, 2, Cs - 12, 100)] + \
                      glide(o + 9, 7, B - 12, B, at=5, over=1.5, vel=118)
            else:
                pat = BASS_A if s == "A" else BASS_C if s == "D" else BASS_B
                bar = [N(o + p, ln, k, 112) for p, ln, k in pat[b % 8]]
                if b % 8 == 7 and s != "A":                       # слайд — событие: раз в восьмёрку, в конце
                    last = bar[-1]
                    bar = bar[:-1] + glide(last.pos, last.ln, last.key, B, at=last.ln - 1.5, over=1.5)
                if b % 8 == 7 and s == "A":
                    bar = bar[:-1] + glide(o + 12, 4, Ds, Fs, at=2, over=1.5)
                if s == "D" and b % 4 == 1:                       # прыжок на октаву — раз в четыре такта
                    last = bar[-1]
                    bar = bar[:-1] + [last._replace(key=last.key + 12, ln=2)]
            if b in BREATHS:
                bar = mute(bar, o + 8, o + 16)
            if b % 8 == 7 and s in ("A",):
                bar = mute(bar, o + 8, o + 9)
            t["808"] += swing(bar, SW)

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in BREATHS:
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        # Кик как перк: задранная бочка по нотам петли
        if b == 39:
            t["бочка"] += [N(o + 12 + i, .3, k, v) for i, (k, v) in enumerate(((87, 96), (83, 108), (90, 100), (95, 122)))]
        if b == 71:
            t["бочка"] += [N(o + 8, .3, 83, 104), N(o + 9, .3, 83, 86), N(o + 12, .3, 90, 118)]
        if s not in DRUMS:
            continue

        kick = hits(o, KICKS[(b + (2 if s == "C" else 5 if s == "D" else 0)) % 8], vel=112, ghost=.45)
        claps = [N(o + 8, 1, 60, 112)]
        if b % 8 == 7:
            claps.append(N(o + 14, 1, 60, 60))
        if b in (16, 32, 56):
            claps = flam(claps[0], .25, .5) + claps[1:]

        key = 62 if s == "C" else 58 if s == "D" else 60
        plan = PLANS[(b // 8) % len(PLANS)].split()[b % 8]
        bone, fills = int(plan[0]), plan[1:]
        hat = swing(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b), SW)
        hat = over(hat, *(FILLS[f](o, key) for f in fills))

        perc = [N(o + 6, 1, 60, 70)] if odd else [N(o + 11, 1, 63, 62)] if b % 4 == 2 else []
        if b % 8 == 7:
            perc += echo([N(o + 10, 1, 62, 92)], 1.5, times=2, decay=.6, width=46, pitch=2)
        perc = swing(ping(perc, 46), SW)
        ohat = [N(o + (6 if b % 8 == 1 else 14), 2, 60, 78)] if b % 4 == 1 else []

        if b == 79:                                              # обрыв перед концом без барабанов
            kick, claps, hat, perc, ohat = (mute(x, o + 12, o + 16) for x in (kick, claps, hat, perc, ohat))
        t["бочка"] += swing(kick, SW)
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat
    t["мелодия"], t["пэд"] = hush(t["мелодия"]), hush(t["пэд"])
    t["808"] = human(t["808"], 6, seed=160)
    return {k: sorted(v) for k, v in t.items()}

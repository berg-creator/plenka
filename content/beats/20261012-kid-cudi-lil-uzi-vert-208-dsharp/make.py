def bar(o: float, notes, louder: int = 0) -> list[N]:
    return sg([N(o + p, ln, k, max(1, min(127, v + louder))) for p, ln, k, v in notes])


def kick_perc(o: float, notes) -> list[N]:
    return sg([N(o + p, .4, k, v) for p, k, v in notes])


def low(o: float, notes) -> list[N]:
    return sg([N(o + p, ln, k, LOW.get(p, 100), 0, FINE) for p, ln, k in notes])


def clip(o: float) -> list[N]:
    """Первый такт восьмёрки припева — с бас-клипа владельца: пауза в восьмую, три удара, ещё удар и съезд вниз к до."""
    slide = glide(o + 10, 6, E, C, at=3, over=2, vel=106)
    return low(o, ((2, 1.5, E), (4, 1.5, E), (6, 1.5, E))) + sg([n._replace(fine=FINE) for n in slide])


def hat_bar(o: float, bone: str, fill: str, k: int, vel: int, b: int) -> list[N]:
    notes = spread(sg(hits(o, bone, key=k, vel=vel, ln=.5)), 38, seed=b)
    if k != 60:                                     # припев: удары на шагах 6 и 14 — на квинту выше
        notes = [n._replace(key=n.key + 7) if round(n.pos - o) in (6, 14) else n for n in notes]
    return over(notes, FILLS[fill](o, k)) if fill != "." else notes


def lead(o: float, answer, louder: int = 0) -> list[N]:
    """Фраза мелодии: зов в такте o, ответ в следующем; к долгому до — подъезд с си-бемоля."""
    out = []
    for n in bar(o, CALL, louder) + bar(o + 16, answer, louder):
        out += grace(n, step=-2, ln=.5) if n.key == 72 and n.ln >= 1.5 else [n]
    return out


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    for s, start in enumerate(VERSES + HOOKS):
        verse = start in VERSES
        n_part = (VERSES if verse else HOOKS).index(start)
        for i in range(16):
            b, o = start + i, (start + i) * 16
            j = i % 8
            # Каркас: клэп на шаге 8, чуть позже доли; бочка рисунком на четыре такта, со свингом гитары
            t["клэп"].append(N(o + 8 + (2 if i % 2 else 1) / 24, 1, 60, (112, 120)[i % 2]))
            if verse and i % 4 == 3:
                t["клэп"].append(N(sw(o + 14), .5, 60, 40))                     # призрак клэпа
            kick = (KICK_V if verse else KICK_H)[i % 4]
            t["бочка"] += sg([N(o + p, 1, 60, v) for p, v in kick.items()])
            # 808: рисунок части; второй проход припева — с другой половины рисунка
            if verse:
                t["808"] += low(o, BASS_V[(j + 4 * (n_part == 1)) % 8])
            else:
                k8 = (j + 4 * (n_part == 1)) % 8
                t["808"] += clip(o) if k8 == 0 else low(o, BASS_H[k8])
            # Хэт: костяк — со свингом и разбросом, дробь поверх ровная
            plans = PLAN_V if verse else PLAN_H
            plan = plans[(2 * n_part + i // 8) % len(plans)].split()[j]
            t["хэт"] += hat_bar(o, (BONE_V if verse else BONE_H)[int(plan[0])], plan[1], 60 if verse else 62,
                                78 if verse else 84, b)
            # Открытый хэт и перк — по ушам
            if verse:
                if i % 4 == 1:
                    t["открытый хэт"] += sg([N(o + 12, 2, 60, 80)])
                if i % 2:
                    t["перк"] += sg([N(o + 14, 1, 60, 76, (-45, 45)[i // 2 % 2])])
            else:
                if i % 4 == 2:
                    t["открытый хэт"] += sg([N(o + 4, 2, 60, 84)])
                if i % 4 == 0:
                    t["открытый хэт"] += sg([N(o + 6, 1.5, 60, 72)])
                t["перк"] += sg([N(o + 3, 1, 60, 82, -45), N(o + 11, 1, 62, 74, 45)])
            # Музыка: в припеве хук каждые два такта; в куплетах (кроме первого) зов вполголоса раз в четыре такта
            if not verse and i % 2 == 0:
                last = start == HOOKS[-1] and i in (6, 14)
                t["мелодия"] += lead(o, ANS_END if last else (ANS_1, ANS_2)[i // 2 % 2])
            elif verse and start != VERSES[0] and i % 4 == 2:
                t["мелодия"] += bar(o, CALL, -26)
            # Задранная бочка отвечает в дыре «ответа» каждого четвёртого такта куплета
            if verse and i % 4 == 3:
                t["бочка"] += kick_perc(o, (UP3, DOWN3)[i // 4 % 2])

    # Вступление: гитара одна; с такта 5 — тихий хэт и перк
    for b, bone in zip(range(4, 8), ("x...x.x.x...x.x.", "x.x.x...x.x.x..o", "x...x.x.x.x...x.", "x.x...x.x.x.x...")):
        t["хэт"] += spread(sg(hits(b * 16, bone, vel=58, ln=.5)), 38, seed=b)
        t["перк"] += sg([N(b * 16 + 14, 1, 60, 64, (-40, 40)[b % 2])])

    # Мост 73–80: без барабанов; 808 долгими нотами, бочка поёт зов, мелодия отвечает
    for i in range(8):
        o = (BRIDGE + i) * 16
        if i % 2 == 0:
            t["808"] += low(o, ((0, 12, E),) if i != 4 else ((2, 1.5, E), (4, 1.5, E), (6, 6, E)))
            if i < 6:
                t["бочка"] += kick_perc(o, SING)
        else:
            t["808"] += low(o, ((0, 6, E), (6, 8, C)))
            t["мелодия"] += lead(o - 16, ANS_1 if i != 5 else ANS_2, -14)[len(CALL):]       # только ответ
        t["перк"] += echo(sg([N(o + 3, 1, 62, 80, -40)]), 3, times=2, decay=.6, width=45, pitch=-2)

    # Провалы: в паузах петли молчат барабаны и 808
    for a, z in REST:
        for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "перк"):
            t[k] = mute(t[k], (a - 1) * 16, (z - 1) * 16)
    # Стоп-тайм 109–110: барабаны и 808 только на атаках гитары, хэта нет
    o = 108 * 16
    for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "перк"):
        t[k] = mute(t[k], o, o + 32)
    hitsq, hitsa = [p for p, _, _ in STOP_Q], [o + 16 + p for p, _, _ in STOP_A]
    t["бочка"] += [N(o + p, 1, 60, v) for p, v in zip(hitsq, (120, 96, 112, 90, 116))] + [N(hitsa[0], 1, 60, 120)]
    t["клэп"] += [N(o + 8, 1, 60, 124), N(o + 16 + 8, 1, 60, 118)]
    t["808"] += [N(o + p, 1.5, E, v, 0, FINE) for p, v in zip(hitsq, (112, 98, 108, 96, 110))]
    t["808"] += [N(hitsa[0], 3, E, 112, 0, FINE), N(hitsa[1], 3, C, 104, 0, FINE), N(hitsa[2], 3, C, 108, 0, FINE)]
    t["мелодия"] += bar(o, CALL, -10)

    # Провалы перед припевами: задранная бочка в первой половине, «плёнка встаёт» во второй; вход припева — с форшлагом
    for b in (23, 55, 95):
        o = b * 16
        if b != 55:
            t["бочка"] += kick_perc(o, DROP)
        t["хэт"] += roll(o + 8, 8, 12, vel=(110, 50), pitch=-12, curve=.5)
        t["клэп"] = [n for n in t["клэп"] if not o + 16 + 8 <= n.pos < o + 16 + 9] + flam(N(o + 16 + 8 + 1 / 24, 1, 60, 122), gap=.5)
    t["хэт"] += roll(7 * 16 + 8, 8, 12, vel=(104, 46), pitch=-12, curve=.5)                    # вступление → куплет

    # Конец 113–120: 113–116 — гитара, 808 и хэт; 117–120 — гитара и мелодия
    for i in range(4):
        o = (OUT + i) * 16
        t["808"] += low(o, BASS_V[(i * 2 + 1) % 8] if i % 2 else BASS_V[i * 2 % 8])
        t["хэт"] += hat_bar(o, BONE_V[(i + 2) % 6], "..ca"[i], 60, 70, OUT + i)
    for i in (4, 6):
        t["мелодия"] += lead((OUT + i) * 16, ANS_1 if i == 4 else ANS_END, -8)

    t["808"] = human(t["808"], 4, seed=208)
    t["хэт"] = human(t["хэт"], 3, seed=12)
    return {k: sorted(n for n in v if n.pos < BARS * 16) for k, v in t.items()}

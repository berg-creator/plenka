def sw(x: float) -> float:
    """Место со свингом гитары: гнутся восьмые сетки 208, а не шестнадцатые."""
    return 2 * swing(x / 2, SW)


def sg(notes: list[N]) -> list[N]:
    return [n._replace(pos=round(sw(n.pos), 3), ln=round(sw(n.pos + n.ln) - sw(n.pos), 3)) for n in notes]


def cut(*pieces) -> list:
    """Куски нарезки одного такта: кусок на «и» доли встаёт со свингом гитары и от сдвига короче, а не длиннее."""
    return [[round(sw(to), 3), frm, round(min(ln, sw(to + ln) - sw(to)), 3), *kind] for to, frm, ln, *kind in pieces]



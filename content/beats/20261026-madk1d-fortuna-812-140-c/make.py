def drums_on(b: int) -> bool:
    return part(b) in ("куплет", "куплет 2", *CHORUS)


def hat_only(b: int) -> bool:
    return part(b) in ("заход", "разгон") or (part(b) == "конец" and b < 78)


def kick_perk(b: int, o: float) -> list[N]:
    """Кик как перк — та же бочка высоко, коротко и в полную силу; сегодня тритоном, как в петле."""
    name, rel = part(b), b - START[part(b)]
    if name in CHORUS and rel % 4 == 3:                      # бег вверх: до, фа-диез, соль
        return [N(o + 13, .3, 96, 112), N(o + 14, .3, 102, 118), N(o + 15, .3, 103, 124)]
    if name in CHORUS and b % 2 == 1:
        return [N(o + 6, .3, 96, 118), N(o + 15, .3, 102, 124)]
    if name == "куплет 2" and b % 8 == 5:
        return [N(o + 15, .3, 103, 120)]
    return []


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "арп", "808", "бочка", "бочка 2", "клэп", "хэт", "открытый хэт", "перк")}

    for b in range(BARS):
        o, odd, name = b * 16, b % 2, part(b)
        rel = b - START[name]
        bar_t = {k: [] for k in t}

        # Пэд: с такта 3; в припевах через раз по два такта; в разгоне нет; в конце — до такта 78
        if b >= 2 and name != "разгон" and not (name in CHORUS and rel % 4 >= 2) and not (name == "конец" and b >= 78):
            bar_t["пэд"] += [N(o, 13, k, 76) for k in BODY[odd]]

        # Мелодия: в куплетах и припевах; без барабанов — только зов через такт, тише
        if name in ("куплет", "куплет 2", *CHORUS) or (name == "без барабанов" and not odd):
            if name in CHORUS:
                notes = (ANSWER_C3 if name == "припев 3" else ANSWER_C) if odd else CALL_C
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 else ANSWER
            else:
                notes = CALL_2 if b % 8 == 6 else CALL
            soft = .74 if name == "без барабанов" else 1
            bar_t["мелодия"] += [N(o + p, ln, k, round(v * soft)) for p, ln, k, v in notes]

        # Арп — в припевах гуще, во втором куплете с 49, в провале
        if name in CHORUS or name == "провал" or (name == "куплет 2" and b >= 48):
            cells = ARP_HOT if name in CHORUS else ARP
            bar_t["арп"] += swing([N(o + p, ln, k, v) for p, ln, k, v in cells[odd]], SW)

        # 808: рисунок на четыре такта; в заходе, без барабанов и в конце — долгие ноты
        if rel % 4 == 0 and name in ("куплет", "куплет 2", *CHORUS):
            cells = {"куплет": BASS_A, "припев": BASS_B, "куплет 2": BASS_D, "припев 2": BASS_B,
                     "припев 3": BASS_D}[name]
            pick = (rel // 4 + (name == "припев 2")) % 2
            t["808"] += [N(o + p, ln, k, 112) for p, ln, k in cells[pick]]
        elif not odd and (name in ("заход", "без барабанов") or (name == "конец" and b < 78)):
            t["808"] += [N(o + p, ln, k, 108) for p, ln, k in BASS_LONG]
        if b in SLIDES:                                        # слайд — событие: конец такта уезжает с до на фа-диез
            t["808"] = mute(t["808"], o + 12, o + 16)
            t["808"] += glide(o + 12, 4, C, F, at=2, over=1.5)

        bar_t["бочка 2"] += kick_perk(b, o)

        if b in PLENKA:                                        # «плёнка встаёт»
            bar_t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        if hat_only(b):                                        # заход, разгон и начало конца: хэт четвертями с дробью
            hat = swing(spread(hits(o, QUARTERS[b % 4], key=60, vel=78, ln=.5), 38, seed=b), SW)
            if odd:                                            # дробь — через такт
                hat = over(hat, (FILLS["d"], FILLS["g"])[b // 2 % 2](o, 60))
            bar_t["хэт"] += hat
            if name in ("заход", "разгон"):
                for cell, key in PERCS[odd]:
                    bar_t["перк"] += swing(spread(hits(o, cell, key=key, vel=64, accent=1.2, ghost=.45), 46,
                                                  seed=b + 500 + key), SW)

        if drums_on(b):
            kick = hits(o, KICKS[name][rel % 4], vel=104, ghost=.45)
            bar_t["бочка"] += swing(kick, SW)

            # Клэп на второй и четвёртой доле, на 9 мс позже; на входе части — форшлаг
            claps = [N(o + 4.08, 1, 60, 108), N(o + 12.08, 1, 60, 114)]
            if b == START[name]:
                claps = flam(claps[0], .25, .5) + claps[1:]
            if b in ECHOES:                                    # клэп-эхо по ушам за четвёртой долей
                claps = claps[:-1] + echo([claps[-1]], 1.5, times=2, decay=.55, width=40)
            bar_t["клэп"] += swing(sorted(claps), SW)

            key = {"куплет": 60, "припев": 62, "куплет 2": 59, "припев 2": 63, "припев 3": 62}[name]
            plan = PLANS[(b // 8) % len(PLANS)].split()[b % 8]
            bone, fills = int(plan[0]), plan[1:]
            hat = swing(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b), SW)
            hat = over(hat, *(FILLS[f](o, key) for f in fills))
            if name in ("припев 2", "припев 3") and rel % 4 == 2:     # триоли восьмых во второй половине такта
                hat = [n for n in hat if n.pos < o + 8] + [N(o + 8 + i * 4 / 3, .5, key, (92, 64, 76)[i % 3],
                                                             (-30, 0, 30)[i % 3]) for i in range(6)]
            bar_t["хэт"] += hat

            for cell, pk in PERCS[odd]:
                bar_t["перк"] += swing(spread(hits(o, cell, key=pk, vel=72, accent=1.2, ghost=.45), 46,
                                              seed=b + 300 + pk), SW)
            if name in CHORUS and rel % 4 == 1:
                bar_t["открытый хэт"] += [N(o + (14 if rel % 8 == 1 else 6), 2, 60, 78)]

        if b in BOUNCE:                                        # отскок перед новой частью
            bar_t["бочка"] = [n for n in bar_t["бочка"] if n.pos < o + 12] + [
                N(o + 12, .5, 60, 108), N(o + 12.32, .4, 60, 89), N(o + 12.84, .4, 60, 64)]

        if b in STOPS:                                         # стоп-такт: со второй половины — один клэп
            for k in ("бочка", "бочка 2", "хэт", "перк", "открытый хэт"):
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        if b in CUTS:                                          # обрыв: барабаны молчат, звучит переход
            for k in ("бочка", "бочка 2", "клэп", "хэт", "перк", "открытый хэт"):
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        if b in PLENKA:                                        # плёнка: остальное молчит вторую половину такта
            for k in ("бочка", "бочка 2", "клэп", "перк", "открытый хэт"):
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        for k, notes in bar_t.items():
            t[k] += notes

    # У образца нота 808 — около трёх шестнадцатых: короткие ноты тянутся до следующей, но не дальше трёх
    bass = sorted(n for n in t["808"] if not n.slide)
    t["808"] = [n._replace(ln=min(3, nxt.pos - n.pos)) if n.ln <= 2 and nxt.pos - n.pos > n.ln else n
                for n, nxt in zip(bass, bass[1:] + [N(BARS * 16, 1)])] + [n for n in t["808"] if n.slide]
    # 808 молчит во вдохах, стоп-тактах и обрывах
    for b in PLENKA + STOPS + CUTS:
        t["808"] = mute(t["808"], b * 16 + 8, b * 16 + 16)
    t["808"] = human(swing(t["808"], SW), 6, seed=140)
    for k in ("мелодия", "пэд", "арп"):                        # в паузах петли молчат и свои партии
        for a, z in QUIET:
            t[k] = mute(t[k], a, z)
    return {k: sorted(set(v)) for k, v in t.items()}

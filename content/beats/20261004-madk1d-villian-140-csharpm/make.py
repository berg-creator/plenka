def bars(*parts):
    return [b for a, z in parts for b in range(a, z)]


def swap(hats: list[N], fill: list[N]) -> list[N]:
    """Дробь или триоль встаёт вместо ударов основного рисунка на своём отрезке."""
    if not fill:
        return hats
    start, end = min(n.pos for n in fill), max(n.pos + n.ln for n in fill)
    return [h for h in hats if not start <= h.pos < end] + fill


def triplet(pos: float, vel: int = 78) -> list[N]:
    """Три удара на две шестнадцатые: средний тише."""
    return [N(pos + i * 2 / 3, 2 / 3, 60, v) for i, v in enumerate((vel, vel - 18, vel - 6))]


def theme(o: int, down: int = 0, vel: int = 100) -> list[N]:
    out = []
    for p, ln, k in THEME_NOTES:
        n = N(o + p, ln, k - down, vel if p % 32 == 0 else vel - 10)
        out += grace(n, -1, .5) if p == 96 else [n]       # подъезд полутоном к долгой ре-диез
    return out



            kick = hits(o, KICKS[name][rel % 4], vel=104, ghost=.45)
            if b in NO_ONE:                                  # «клэп вместо раза»: бочка уходит с первой доли на шаг 4
                kick = [n for n in kick if n.pos % 16 >= 2] + [N(o + 4, 1, 60, 120)]
            bar_t["бочка"] += swing(kick, sw(b))

            # Клэп на третьей доле на 11 мс позже; после перелома через такт ещё и на «раз», как у образца
            claps = [N(o + 8.1, 1, 60, 112)]

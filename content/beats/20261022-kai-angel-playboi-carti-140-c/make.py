def kick_perk(b: int, o: float) -> list[N]:
    """Кик как перк — та же бочка высоко; фигуры свои, не из «Фонаря» и прошлых битов."""
    bar = b + 1
    if bar in (6, 14, 26, 34, 48, 56, 68, 76):              # эхо: удар и два повтора по ушам, каждый на 4 полутона ниже
        return echo([N(o + 9, .3, 108 if b >= CUT else 107, 124)], 2, times=2, decay=.72, width=50, pitch=-4)
    if bar in (4, 40):                                      # разгон вверх по второй половине такта
        return [x._replace(ln=min(x.ln, .3)) for x in roll(o + 8, 8, (2, 4, 8), key=96, pitch=(0, 4, 7, 11),
                                                           vel=(96, 112, 124))]
    if bar == 86:                                           # три удара октавами вниз
        return [N(o + s, .3, k, v) for s, k, v in ((0, 108, 124), (4, 96, 116), (8, 84, 108))]
    return []


def nudge(bone: str, seed: int) -> str:
    """Деталь такта: в половине тактов одна шестнадцатая костяка меняется — призрак в пустую нечётную или пропуск
    восьмой вне доли. Костяк возвращается через восемь тактов, детали — нет."""
    r, cells = random.Random(seed), list(bone)
    if r.random() < .5:
        return bone
    empty = [i for i in (1, 3, 5, 7, 9, 11, 13, 15) if cells[i] == "."]
    weak = [i for i in (2, 6, 10, 14) if cells[i] != "."]
    if empty and (r.random() < .6 or not weak):
        cells[r.choice(empty)] = "o"
    elif weak:
        cells[r.choice(weak)] = "."
    return "".join(cells)


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "арп", "808", "бочка", "бочка 2", "клэп", "хэт", "открытый хэт", "перк")}

    for b in range(BARS):
        o, odd, bar, name = b * 16, b % 2, b + 1, part(b)
        rel, late = b - START[name], b >= CUT
        bar_t = {k: [] for k in t}

        # Музыка: пэд — с такта 3, кроме провала до 43, тихой 61–62 и конца после 84; мелодия — в куплете, припеве,
        # перелом и финале, в провале — только зов через такт, тише; арп — с такта 13
        if b >= 2 and not (name == "провал" and b < 42) and b not in (60, 61) and b < 84:
            bar_t["пэд"] += [N(o, 14, k, 80) for k in (BODY_B if late else BODY)[odd]]
        if name in ("куплет", "припев", "перелом", "финал") or (name == "провал" and not odd):
            if late:
                notes = (ANSWER_B2 if name == "финал" else ANSWER_B) if odd else (CALL_B2 if b % 4 == 2 else CALL_B)
            elif name == "провал":
                notes = CALL_2
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 else ANSWER
            else:
                notes = CALL_2 if b % 8 == 6 else CALL
            soft = .72 if name == "провал" else 1
            bar_t["мелодия"] += [N(o + p, ln, k, round(v * soft)) for p, ln, k, v in notes]
        if (name == "куплет" and b >= 12) or name in ("тихая", "припев", "перелом", "финал") or b in (62, 63):
            cells = ARP_B if late else ARP_HOT if name == "припев" else ARP
            bar_t["арп"] += swing([N(o + p, ln, k, v) for p, ln, k, v in cells[odd]], sw(b))

        # 808: клетка на два такта, рисунок части; в тихих частях и в конце — долгие ноты; во вступлении и провале молчит
        if not odd:
            if name in ("тихая",):
                pat = BASS_LONG
            elif name in ("тихая 2", "конец"):
                pat = BASS_LONG_B if b < 86 else ()
            elif name in ("вступление", "провал"):
                pat = ()
            else:
                cells = BASS_B if late else BASS_A
                pat = cells[(b // 2 + (1 if name in ("припев", "финал") else 0)) % 4]
            t["808"] += [N(o + p, ln, k, 112) for p, ln, k in pat]
        if bar in SLIDES:                                    # слайд — событие: в конце такта нота уезжает
            a, z = SLIDES[bar]
            t["808"] = mute(t["808"], o + 13, o + 16)
            t["808"] += glide(o + 13, 3, a, z, at=1.5, over=1)

        bar_t["бочка 2"] += kick_perk(b, o)

        if b in PLENKA:                                      # «плёнка встаёт»
            bar_t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        if hat_only(b):                                      # тихие и конец: хэт четвертями с дробью
            key = 60 if not late else 58
            hat = swing(spread(hits(o, QUARTERS[b % 4], key=key, vel=78, ln=.5), 38, seed=b), sw(b))
            hat = over(hat, (FILLS["d"], FILLS["e"], FILLS["g"], FILLS["i"])[b % 4](o, key))
            bar_t["хэт"] += mute(hat, o + 8, o + 16) if b in PLENKA else hat
            perc = hits(o, PERCS[late][odd], key=60, vel=66, accent=1.2, ghost=.45)
            bar_t["перк"] += swing(spread(perc, 46, seed=b + 500), sw(b))


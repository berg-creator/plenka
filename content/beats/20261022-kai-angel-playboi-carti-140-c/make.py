def part(b: int) -> str:
    """Часть по такту, счёт с нуля."""
    for name, end in (("вступление", 4), ("куплет", 20), ("тихая", 24), ("припев", 40), ("провал", 44),
                      ("перелом", 60), ("тихая 2", 64), ("финал", 80)):
        if b < end:
            return name
    return "конец"



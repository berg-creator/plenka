def nudge(bone: str, seed: int) -> str:
    """Деталь такта: в половине тактов одна шестнадцатая костяка меняется — призрак в пустую нечётную или пропуск
    восьмой вне доли. Костяк возвращается через восемь тактов, детали — нет."""
    r, cells = random.Random(seed), list(bone)
    if r.random() < .5:
        return bone
    empty = [i for i in (1, 3, 5, 7, 9, 11, 13, 15) if cells[i] == "."]
    weak = [i for i in (2, 6, 10, 14) if cells[i] != "."]
    if empty and (r.random() < .6 or not weak):
        cells[r.choice(empty)] = "o"
    elif weak:
        cells[r.choice(weak)] = "."
    return "".join(cells)


def kick_perk(b: int, o: float) -> list[N]:
    """Кик как перк — та же бочка высоко: триоль на четвёртой доле по нотам аккорда такта, слева направо."""
    if b in PERK:
        keys = (PERK_CHORD1 if b < CUT else PERK_CHORD2)[at4(b)]
        return [N(o + 12 + i * 4 / 3, .3, k, v, p) for i, (k, v, p) in enumerate(zip(keys, (124, 116, 120), (-45, 0, 45)))]
    if b == 23:                                             # перед припевом — съезд вниз на две октавы, первая половина
        return [x._replace(ln=min(x.ln, .3)) for x in roll(o + 4, 4, 8, key=108, pitch=-24, vel=(124, 70))]
    return []


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("хор низ", "мелодия", "контрмелодия", "808", "бочка", "бочка 2", "клэп", "хэт",
                         "открытый хэт", "перк")}

    for b in range(BARS):
        o, odd, name, late = b * 16, b % 2, part(b), b >= CUT
        rel, q = b - START[name], at4(b)
        bar_t = {k: [] for k in t}

        # Хор низ — весь бит, долгие ноты на опорах; в припеве, после перелома и в финале вторая половина — квинтой
        root, fifth = (CHOIR2, CHOIR2_5) if late else (CHOIR1, CHOIR1_5)
        vel = (112, 106, 116, 104)[q]
        if name in ("припев", "финал") or (name == "перелом" and odd):
            bar_t["хор низ"] += [N(o, 9, root[q], vel), N(o + 10, 6, fifth[q], vel - 14)]
        elif b == 51:
            bar_t["хор низ"] += [N(o, 12, root[q], vel)]
        else:
            bar_t["хор низ"] += [N(o, 15, root[q], vel)]

        # Мелодия: в куплетах — первые два такта зова тише, в припеве целиком, после перелома — долгие ноты
        if name in ("куплет", "куплет 2") and b >= 8 and b != 51 and q < 2:
            bar_t["мелодия"] += [N(o + p, ln, k, round(v * .85)) for p, ln, k, v in HOOK[q]]
        elif name == "припев":
            notes = HOOK_END if (q == 3 and b % 8 == 7) else HOOK[q]
            bar_t["мелодия"] += [N(o + p, ln, k, v) for p, ln, k, v in notes]
        elif name in ("перелом", "финал"):
            notes = HOOK2_END if (q == 3 and name == "финал") else HOOK2[q]
            bar_t["мелодия"] += [N(o + p, ln, k, v) for p, ln, k, v in notes]

        if name in ("провал", "припев", "тихая", "перелом", "тихая 2", "финал"):
            cells = COUNTER2 if late else COUNTER
            bar_t["контрмелодия"] += [N(o + p, ln, k, v) for p, ln, k, v in cells.get(q, ())]

        # 808: рисунок части на четыре такта; в провале и тихих — долгие ноты; во вступлении, переходе и конце молчит
        r8, f8 = (ROOT2, FIFTH2) if late else (ROOT1, FIFTH1)
        if name in ("провал", "тихая", "тихая 2"):
            t["808"] += [N(o, 14, r8[q], 108)]
        elif name in BASS and b != 51:
            cells = BASS[name][rel % 4]
            t["808"] += [N(o + p, ln, r8[q] if d == "r" else f8[q], 112) for p, ln, d in cells]
            nxt = b + 1
            if q == 3 and drums_on(nxt):                    # слайд в следующую опору на последней восьмой
                to = (ROOT2 if nxt >= CUT else ROOT1)[at4(nxt)]
                t["808"] = mute(t["808"], o + 14, o + 16)
                t["808"] += glide(o + 14, 2, r8[q], to, at=1, over=1)
        elif name == "конец" and b == 78:
            t["808"] += [N(o, 14, r8[q], 100)]

        bar_t["бочка 2"] += kick_perk(b, o)

        if b in PLENKA:                                      # «плёнка встаёт»
            bar_t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        if hat_only(b):                                      # тихие части: хэт четвертями с дробью и перк
            key = 60 if not late else 58
            hat = swing(spread(hits(o, QUARTERS[b % 4], key=key, vel=78, ln=.5), 38, seed=b), sw(b))
            hat = over(hat, (FILLS["e"], FILLS["d"], FILLS["h"], FILLS["i"])[b % 4](o, key))
            bar_t["хэт"] += mute(hat, o + 8, o + 16) if b in PLENKA else hat
            perc = hits(o, PERCS[late][odd], key=60, vel=66, accent=1.2, ghost=.45)
            bar_t["перк"] += swing(spread(perc, 46, seed=b + 500), sw(b))

        if drums_on(b):
            if b in MARCH:                                   # бочка маршем: все доли с ростом силы
                kick = [N(o + s, 1, 60, v) for s, v in ((0, 72), (4, 88), (8, 104), (12, 120))]
            else:
                kick = hits(o, KICKS[name][rel % 4], vel=104, ghost=.48)
            bar_t["бочка"] += swing(kick, sw(b))

            # Клэп на третьей доле на 5 мс позже; в тактах LATE_CLAP — на восьмую позже; призрак перед частью
            claps = [N(o + (10.05 if b in LATE_CLAP else 8.05), 1, 60, 114)]
            if rel % 4 == 3 and b not in MARCH:
                claps += [N(o + 15, 1, 60, 40)]
            if b in ENTRY or b in MARCH:
                claps = flam(claps[0], .25, .5) + claps[1:]
            bar_t["клэп"] += sorted(claps)

            key = {"куплет": 60, "припев": 62, "куплет 2": 60, "перелом": 58, "финал": 61}[name]
            plan = (PLANS_B if late else PLANS)[(b // 8) % 4].split()[b % 8]
            bone, fills = int(plan[0]), plan[1:]
            hat = swing(spread(hits(o, nudge((BONES_B if late else BONES)[bone], b), key=key, vel=84, ln=.5), 38,
                               seed=b), sw(b))
            if b % 8 == 6:                                   # хэт пятёрками: вторая половина — пять ударов вниз и вправо
                hat = [n for n in hat if n.pos < o + 8] + [N(o + s, .5, key - (0, 2, 3, 5, 7)[i], 96 - i * 6,
                                                             -40 + i * 20) for i, s in enumerate(FIVE)]
            bar_t["хэт"] += over(hat, *(FILLS[f](o, key) for f in fills))

            perc = hits(o, PERCS[late][odd], key=64 if odd else 60, vel=72, accent=1.2, ghost=.45)
            bar_t["перк"] += swing(spread(perc, 46, seed=b + 300), sw(b))
            if rel % 4 == 1:
                bar_t["открытый хэт"] += [N(o + (14 if rel % 8 == 1 else 6), 2, 60, 78)]

        if b in BOUNCE:                                      # отскок перед тихой частью
            bar_t["бочка"] = [n for n in bar_t["бочка"] if n.pos < o + 12] + [
                N(o + 12, .5, 60, 108), N(o + 12.32, .4, 60, 89), N(o + 12.84, .4, 60, 64)]

        if b in PLENKA:                                      # плёнка: вторая половина такта — только дробь
            for k in ("бочка", "бочка 2", "клэп", "перк", "открытый хэт"):
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        for k, notes in bar_t.items():
            t[k] += notes

    # 808 молчит во вдохах; свинг и разброс силы — по частям
    for a, z in [(b * 16 + 8, b * 16 + 16) for b in PLENKA] + [(51 * 16, 52 * 16)]:
        t["808"] = mute(t["808"], a, z)
    t["808"] = human(swing([n for n in t["808"] if n.pos < CUT * 16], .58)
                     + swing([n for n in t["808"] if n.pos >= CUT * 16], .61), 6, seed=134)
    for k in ("хор низ", "мелодия", "контрмелодия"):          # в паузах петли молчат и свои партии
        for a, z in QUIET + [(51 * 16 + 12, 52 * 16)]:
            t[k] = mute(t[k], a, z)
        for b in PLENKA:
            t[k] = mute(t[k], b * 16 + 8, b * 16 + 16)
    return {k: sorted(set(v)) for k, v in t.items()}

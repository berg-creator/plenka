def bars(*parts):
    return [b for a, z in parts for b in range(a, z)]


def bounce(o: float) -> list[N]:
    """Отскок мячика: промежутки сжимаются, удары тише, ближе к центру и чуть выше."""
    out, at, gap = [], o, 2.0
    for i in range(8):
        out.append(N(at, .5, 60 + i // 2, 104 - i * 9, (-36 if i % 2 else 36) * (8 - i) // 8))
        at, gap = at + gap, gap * .7
    return out



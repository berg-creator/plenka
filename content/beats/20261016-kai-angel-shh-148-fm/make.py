def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "клавиши", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    for b in range(BARS):
        o, s, odd = b * 16, section(b), b % 2
        fm = (b // 2) % 2 == 0                                   # аккорд: два такта фа, два — ре-бемоль
        music = s != "gap"

        # Тема: зов в чётных тактах, ответ в нечётных
        if music:
            if b == 63:
                notes = ANSWER_END
            elif s == "C":
                notes = ANSWER_C if odd else CALL_C
            elif odd:
                notes = ANSWER_2 if b % 4 == 3 else ANSWER
            else:
                notes = CALL
            bar = [N(o + p, ln, k, v) for p, ln, k, v in notes]
            if not odd and b % 8 == 4 and s in ("B", "D"):       # подъезд к вершине раз в восьмёрку
                top = next(n for n in bar if n.key == 65)
                bar = [n for n in bar if n != top] + grace(top, -1, .5)
            if b in BREATHS:
                bar = mute(bar, o + 8, o + 16)
            t["мелодия"] += bar

            # Тень зова в перке: клавесы на две октавы выше, там, где 808 молчит
            if s == "D" and not odd:
                shadow = [N(o + p, .5, k + 24, round(v * .6)) for p, ln, k, v in notes if p < 12]
                t["перк"] += swing(spread(shadow, 40, seed=b + 500), SW)

        # Пэд: фа с до и ре-бемоль с ля-бемолем, до шага 12 — конец такта дышит
        if music and s != "I":
            keys = (53, 60) if fm else (56, 61)
            bar = [N(o, 12, k, v) for k, v in zip(keys, (82, 72))]
            t["пэд"] += mute(bar, o + 8, o + 16) if b in BREATHS else bar

        if s == "C" and not odd:
            t["клавиши"] += [N(o + p, ln, k, v) for p, ln, k, v in KEYS[(b - 32) // 2 % 3]]

        # 808
        if s in BASS:
            pat = BASS_C if s == "C" else BASS_A
            row = pat[b % 8]
            row = row if isinstance(row[0], tuple) else (row,)
            bar = [N(o + p, ln, k, 110) for p, ln, k in row]
            if s == "I":
                bar = [N(o, 16 if b == 0 else 8, F, 104)]
            if b in SLIDES:                                      # слайд вверх на малую терцию — событие
                last = bar[-1]
                bar = bar[:-1] + glide(last.pos, last.ln, last.key, last.key + 3, at=last.ln - 1.5, over=1.5)
            if b in BREATHS:
                bar = mute(bar, o + 8, o + 16)
            t["808"] += swing(bar, SW)

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — во вдохах
        if b in BREATHS:
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)

        # Кик как перк: задранная бочка
        if b == 23:
            t["бочка"] += [N(o + 12 + i, .4, k, v) for i, (k, v) in enumerate(((89, 120), (84, 106), (80, 96), (77, 84)))]
        if b == 55:
            t["бочка"] += [N(o + 4, .35, 89, 118), N(o + 5, .35, 92, 104), N(o + 10, .35, 84, 96)]
        if s not in DRUMS:
            continue

        kick = hits(o, KICKS[(b + (2 if s == "C" else 0)) % 8], vel=112, ghost=.45)
        claps = [N(o + 8, 1, 60, 110)]
        if b % 4 == 3:
            claps.append(N(o + 15, 1, 60, 70))
        if b in (2, 12, 32):
            claps = flam(claps[0], .25, .5) + claps[1:]

        key = 57 if s == "C" else 60
        plan = PLANS[(b // 8) % len(PLANS)].split()[b % 8]
        bone, fill = int(plan[0]), plan[1]
        hat = swing(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b), SW)
        hat = over(hat, FILLS[fill](o, key) if fill != "." else [])

        perc = [N(o + 6, 1, 60, 72)] if odd else [N(o + 13, 1, 63, 64)] if b % 4 == 2 else []
        if b % 8 == 7:
            perc += echo([N(o + 11, 1, 62, 94)], 1, times=2, decay=.6, width=46, pitch=3)
        perc = swing(spread(perc, 48, seed=b + 300), SW)
        ohat = [N(o + (12 if b % 8 == 1 else 6), 2, 60, 80)] if b % 4 == 1 and s in ("A", "B", "C") else []

        t["бочка"] += swing(kick, SW)
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat
    t["808"] = human(t["808"], 6, seed=148)
    return {k: sorted(v) for k, v in t.items()}

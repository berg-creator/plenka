def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "том", "том 2", "крэш")}

    for part, plan in PLANS.items():
        a, z = part
        verse = part == VERSE1
        for i, tok in enumerate(plan.split()):
            b = a + i
            o, bone, fill = b * 16, int(tok[0]), tok[1]
            key = 57 if verse else 60
            base = spread(hits(o, (VBONES if verse else BONES)[bone], key=key, vel=84, ln=.5), 38, seed=b)
            roll_ = [n._replace(key=n.key - 60 + key) for n in FILLS[fill](o)] if fill != "." else []
            t["хэт"] += over(base, roll_)
            if part == INTRO:
                continue

            low = b not in OFF
            # Клэп — шаг 8 каждого такта; первый клэп части — с тихим ударом перед ним
            clap = N(o + 8, 1, 60, 112)
            t["клэп"] += flam(clap) if b in (8, 24, 40, 56) else [clap]
            if b + 1 in OFF:       # клэп-эхо перед тактом без низа
                t["клэп"] += echo([N(o + 8, 1, 60, 112)], 3, times=2, decay=.55, width=45)[1:]
                t["клэп"] = [n._replace(fine=-100) if n.pos in (o + 11, o + 14) else n for n in t["клэп"]]
            if not low:
                continue

            # 808 и бочка: рисунок на восемь тактов, предпоследний такт блока — свой
            kind = "куплет" if verse else "финал" if part == FINAL else "хук"
            notes = BASS_LAST if b + 1 in OFF else BASS[kind][i % 8]
            for p, ln, k in notes:
                if i % 16 == 6 and (p, ln, k) == notes[-1]:
                    t["808"] += glide(o + p, ln, k, k - 5, at=ln - 1.5, over=1.5, vel=104)
                else:
                    t["808"].append(N(o + p, ln, k, 112 if p in (0, 4) else 98))
            t["бочка"] += hits(o, KICKS[(i + (3 if verse else 0)) % 8], vel=96)

            if part in (HOOK1, HOOK2) and i % 4 == 3:
                t["открытый хэт"].append(N(o + 12, 2, 60, 78, -20 if i % 8 == 3 else 20))
            if part == FINAL and i % 4 == 1:
                t["открытый хэт"].append(N(o + 6, 2, 60, 74, 15))

            # Томы — ответ клэпу 3+3+2, каждый удар ниже и тише, лево-право через удар
            if verse and i % 2 == 0:
                t["том"] += ping([N(o + 10, 1, 60, 104), N(o + 13, 1, 58, 92), N(o + 16, 1, 56, 80)], 45)
            if part == FINAL and i % 8 == 7:
                t["том 2"] += ping(roll(o + 12, 4, 4, key=64, vel=(70, 110), pitch=-7), 30)

    # Крэш на входах частей
    for b in (8, 24, 56):
        t["крэш"].append(N(b * 16, 8, 60, 100))
    t["крэш"].append(N(FALSE * 16 + 4, 8, 60, 112))

    # Последний такт — одна нота 808 и бочка
    end = 71 * 16
    for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "том", "том 2"):
        t[k] = [n for n in t[k] if n.pos < end]
    t["808"].append(N(end, 16, B, 110))
    t["бочка"].append(N(end, 1, 60, 100))
    t["808"] = human(sorted(t["808"]), 7, seed=11)

    # Плёнка встаёт: вторая половина такта — всё молчит, хэт тормозит и съезжает на октаву
    for b in BREATHS:
        a, z = b * 16 + 8, b * 16 + 16
        for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "том", "том 2"):
            t[k] = mute(t[k], a, z)
        t["хэт"] += roll(a, 8, 12, key=57 if b == 23 else 60, vel=(100, 55), pan=(-30, 30), pitch=-12, curve=.5)

    # Ложный вход: первая доля такта 41 — тишина; бочка и 808 бьют с шага 4
    a = FALSE * 16
    for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "том", "том 2"):
        t[k] = mute(t[k], a, a + 4)
    t["808"].append(N(a + 4, 6, B, 116))
    t["бочка"].append(N(a + 4, 1, 60, 104))
    return {k: sorted(v) for k, v in t.items()}

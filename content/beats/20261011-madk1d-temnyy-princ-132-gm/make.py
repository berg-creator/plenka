def drums(b: int) -> bool:
    return A <= b < BRK or BACK <= b < OUT


def plan(b: int) -> tuple[int, str]:
    start = max(s for s in PLANS if s <= b)
    bone, fill = PLANS[start].split()[b - start]
    return int(bone), fill


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "808", "бочка", "клэп", "хэт", "перк")}

    # Мелодия: зов в чётных тактах счёта с нуля, ответ — в нечётных; каждый второй ответ — с броском вверх

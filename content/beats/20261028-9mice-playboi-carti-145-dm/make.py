def triplet(o: float, beat: int, key: int, rise: bool) -> list[N]:
    """Доля такта триолью восьмых: три удара на четверть; в припеве — лесенкой вверх и слева направо."""
    up, pan = ((0, 2, 5), (-30, 0, 30)) if rise else ((0, 0, 0), (-14, 10, 0))
    return [N(o + beat * 4 + i * 4 / 3, .5, key + up[i], (98, 64, 80)[i], pan[i]) for i in range(3)]


def kick_perk(b: int, o: float) -> list[N]:
    """Кик как перк — та же бочка высоко, коротко и в полную силу."""
    name, rel = part(b), b - START[part(b)]
    if name == "припев" and rel % 4 == 3 and b != DROP:            # съезд ля, фа, ре
        return [N(o + 12, .3, 105, 122), N(o + 13, .3, 101, 116), N(o + 14, .3, 98, 110)]
    if name == "припев 2":
        if rel % 8 == 7:                                          # бег вверх ре, фа, ля, ре
            return [N(o + 12, .3, 98, 108), N(o + 13, .3, 101, 114), N(o + 14, .3, 105, 118), N(o + 15, .3, 110, 124)]
        if rel % 2 == 1:
            return [N(o + 7, .3, 110, 120)]
    if name == "куплет 2" and rel % 8 == 6:
        return [N(o + 15, .3, 105, 118)]
    return []


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("мелодия", "пэд", "плак", "808", "бочка", "бочка 2", "клэп", "хэт", "открытый хэт", "перк")}

    for b in range(BARS):
        o, name = b * 16, part(b)
        rel, slot = b - START[name], b % 8
        chord = HARM[(b - 4) % 8] if b >= 4 else HARM[b % 4 + 4] if b >= 2 else "D"
        bar_t = {k: [] for k in t}

        # --- музыка ---
        if b % 2 == 0 or b == 0:                                  # пэд — по два такта на аккорд
            soft = .8 if name in ("вступление", "конец") else 1
            bar_t["пэд"] += [N(o, 32 if b < BARS - 1 else 16, k, round(78 * soft)) for k in PAD[chord]]

        mel = ()
        ps = (b - 4) % 8
        if name in VERSE:
            mel = VERSE_MEL[ps]
        elif name in CHORUS:
            mel = CH_B2 if name == "припев 2" and rel >= 8 and ps == 5 else CHORUS_MEL[ps]
        elif name == "вступление":
            mel = {1: ANS, 2: CALL_B, 3: END}.get(b, ())
        elif name == "конец":
            mel = {0: CALL, 1: ANS_2, 2: CALL_C, 3: END}[rel]
        soft = .78 if name in ("вступление", "конец") or b == DROP else 1
        notes = [N(o + p, ln, k, round(v * soft)) for p, ln, k, v in mel]
        if name == "припев 2" and rel == 8:                       # подъезд к первой ноте второй половины
            notes = grace(notes[0], step=-1, ln=.5) + notes[1:]
        bar_t["мелодия"] += notes

        if name in VERSE and ps in PLAK_ANS:
            bar_t["плак"] += swing([N(o + p, ln, k, v) for p, ln, k, v in PLAK_ANS[ps]], SW)
        elif name in CHORUS and b != DROP:
            bar_t["плак"] += swing([N(o + p, ln, k, v) for p, ln, k, v in PLAK_CH[ps % 2]], SW)

        # --- 808 ---
        if name in VERSE or name in CHORUS:
            if b == DROP:
                bar_t["808"] += [N(o, 12, 26, 104)]
            else:
                cells = (BASS_H if name in CHORUS else BASS_V)[ps]
                bar_t["808"] += [N(o + p, ln, k, 112) for p, ln, k in cells]
                if name in VERSE and ps == 7:                     # слайд: ля уезжает на ре
                    bar_t["808"] = mute(bar_t["808"], o + 12, o + 16) + glide(o + 12, 4, 33, 38, at=2, over=1.5)
                if name in VERSE and ps == 3:                     # слайд: до уезжает на ре
                    bar_t["808"] = mute(bar_t["808"], o + 14, o + 16) + glide(o + 14, 2, 36, 38, at=1, over=1)
                if name in CHORUS and ps in (1, 5):               # слайд: ре съезжает на до
                    bar_t["808"] = mute(bar_t["808"], o + 10, o + 16) + glide(o + 10, 6, 26, 24, at=4, over=2)
                if name in CHORUS and ps == 7:                    # слайд: ля поднимается на ре
                    bar_t["808"] = mute(bar_t["808"], o + 8, o + 16) + glide(o + 8, 8, 33, 38, at=5, over=2)
                if name in CHORUS and ps == 3:                    # ныряние: ре на октаву вниз
                    bar_t["808"] = mute(bar_t["808"], o + 10, o + 16) + glide(o + 10, 6, 38, 26, at=3, over=2)
        elif name == "вступление" and b >= 2:
            bar_t["808"] += [N(o, 16, 26 if b == 2 else 34, 104)]
        elif name == "конец" and b < 62:
            bar_t["808"] += [N(o + p, ln, k, 108) for p, ln, k in BASS_V[rel]]
        elif b == 62:
            bar_t["808"] += [N(o, 14, 26, 96)]

        # --- барабаны ---
        if (name in VERSE or name in CHORUS) and b != DROP:
            figure = KICKS[name][rel % 4]
            bar_t["бочка"] += swing(hits(o, figure, vel=104, ghost=.45), SW)
            if b + 1 in (START["припев"], START["куплет 2"], START["припев 2"]) or b + 1 == DROP:
                bar_t["бочка"] = [n for n in bar_t["бочка"] if n.pos < o + 14] + [N(o + 14, 1, 60, 100),
                                                                                N(o + 14.5, 1, 61, 72)]
            bar_t["бочка 2"] += kick_perk(b, o)

            # Клэп на третьей доле, на 10 мс позже; в первом такте пары — ещё на шагах 10 и 12
            claps = [N(o + 8.1, 1, 60, 112)]
            if b == START[name]:
                claps = flam(claps[0], .25, .5)
            if name in CHORUS and rel % 2 == 0:
                claps += [N(o + 10, 1, 60, 72), N(o + 12, 1, 60, 88)]
            elif name in VERSE and rel % 4 == 2:
                claps += [N(o + 12, 1, 60, 80)]
            bar_t["клэп"] += swing(claps, SW)

            key = {"куплет": 60, "припев": 62, "куплет 2": 59, "припев 2": 63}[name]
            plan = PLANS[(b // 8) % len(PLANS)].split()[slot]
            bone, fill, beat = int(plan[0]), plan[1], plan[2]
            hat = hits(o, BONES[bone], key=key, vel=84, ln=.5)
            if name == "припев 2":                                # второй звук хэта на шагах 6 и 14
                hat = [n._replace(key=key + 7) if (n.pos - o) in (6, 14) else n for n in hat]
            hat = swing(spread(hat, 44, seed=b), SW)
            if beat != ".":
                beat = int(beat)
                hat = [n for n in hat if not o + beat * 4 <= n.pos < o + beat * 4 + 4] + \
                    triplet(o, beat, key, name in CHORUS)
            if fill != ".":
                hat = over(sorted(hat), FILLS[fill](o, key))
            bar_t["хэт"] += sorted(hat)

            if name in CHORUS and rel % 2 == 1:
                bar_t["открытый хэт"] += [N(o + (14 if name == "припев" or rel % 4 == 1 else 6), 2, 60, 78)]

            perk = "......x......x.." if b % 2 else "..x.......x....."
            bar_t["перк"] += swing(spread(hits(o, perk, vel=70), 45, seed=b + 300), SW)
            if name in VERSE and rel % 4 == 3 and b not in TAPE:     # перк лесенкой вниз
                bar_t["перк"] = [n for n in bar_t["перк"] if n.pos < o + 12] + \
                    echo([N(o + 12, .5, 67, 96, -45)], 4 / 3, times=2, decay=.78, width=0, pitch=-4)
                bar_t["перк"][-2:] = [n._replace(pan=p) for n, p in zip(bar_t["перк"][-2:], (0, 45))]

        if name == "конец" and b < 62:                            # хэт четвертями с дробью
            hat = swing(spread(hits(o, QUARTERS[rel], key=60, vel=76, ln=.5), 36, seed=b), SW)
            bar_t["хэт"] += over(hat, FILLS["d"](o, 60)) if rel else hat

        if b in TAPE:                                              # плёнка встаёт: дробь тормозит и съезжает вниз
            for k in bar_t:
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
            bar_t["хэт"] += roll(o + 8, 8, 10, key=62, vel=(104, 48), pan=(-20, 20), pitch=-12, curve=.5)
        if b == CUT:                                               # обрыв: вторая половина — тишина
            for k in bar_t:
                bar_t[k] = mute(bar_t[k], o + 8, o + 16)
        for k, notes in bar_t.items():
            t[k] += notes

    t["808"] = human(swing(t["808"], SW), 6, seed=28)
    for k in ("мелодия", "пэд", "плак"):                          # паузы музыки
        for a, z in QUIET:
            t[k] = mute(t[k], a, z)
    t["808"] = mute(t["808"], 3 * 16 + 8, 4 * 16)                 # вдох перед входом барабанов
    return {k: sorted(set(v)) for k, v in t.items()}

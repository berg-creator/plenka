def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("808", "бочка", "клэп", "хэт", "открытый хэт", "том", "том 2", "крэш", "мелодия", "контрмелодия")}

    for part, plan in PLANS.items():
        a, z = part
        verse, two = part == VERSE, part[0] >= CUT
        for i, tok in enumerate(plan.split()):
            b = a + i
            o, bone, fill = b * 16, int(tok[0]), tok[1]
            key = HAT_KEY.get(part, 60)
            bones = BONES2 if two else VBONES if verse else BONES
            base = spread(hits(o, bones[bone], key=key, vel=84, ln=.5), 38, seed=b)
            roll_ = [n._replace(key=n.key - 60 + key) for n in FILLS[fill](o)] if fill != "." else []
            t["хэт"] += over(base, roll_)
            if part == INTRO:
                continue

            low = b not in OFF
            # Клэп: до перелома — шаг 8, после — шаги 4 и 12; первый клэп части — с тихим ударом перед ним
            claps = [N(o + 4, 1, 60, 112), N(o + 12, 1, 60, 106)] if two else [N(o + 8, 1, 60, 112)]
            t["клэп"] += (flam(claps[0]) if b in (8, 24, 40, 56) else claps[:1]) + claps[1:]
            if b + 1 in OFF:       # клэп-эхо перед тактом без низа: два повтора тише, по сторонам и ниже на полтона
                t["клэп"] += [n._replace(fine=-100) for n in echo(claps[:1], 3, times=2, decay=.55, width=45)[1:]]
            if not low:
                continue

            # 808 и бочка: рисунок на восемь тактов, предпоследний такт блока — свой; высота — опора такта петли
            root = (ROOTS2 if two else ROOTS1)[(b - (CUT if two else 0)) % 4]
            kind = "куплет" if verse else "финал" if part == FINAL else "вторая" if two else "хук"
            notes = BASS_LAST[two] if b + 1 in OFF else BASS[kind][i % 8]
            for p, ln, fifth in notes:
                k = FIFTH[root] if fifth else root
                if i % 16 == 6 and (p, ln, fifth) == notes[-1]:
                    t["808"] += glide(o + p, ln, k, FIFTH[k], at=ln - 1.5, over=1.5, vel=104)
                else:
                    t["808"].append(N(o + p, ln, k, 112 if p in (0, 4) else 98))
            t["бочка"] += hits(o, KICKS2[i % 8] if two else KICKS[(i + (3 if verse else 0)) % 8], vel=96)

            if part == HOOK and i % 4 == 3:
                t["открытый хэт"].append(N(o + 12, 2, 60, 78, -20 if i % 8 == 3 else 20))
            if part == PART2 and i % 4 == 3:
                t["открытый хэт"].append(N(o + 6, 2, 60, 76, 20 if i % 8 == 3 else -20))
            if part == FINAL and i % 4 == 1:
                t["открытый хэт"].append(N(o + 6, 2, 60, 74, 15))

            # Томы — ответ клэпу 3+3+2, каждый удар ниже и тише, лево-право через удар
            if verse and i % 2 == 0:
                t["том"] += ping([N(o + 10, 1, 60, 104), N(o + 13, 1, 58, 92), N(o + 16, 1, 56, 80)], 45)
            if part == FINAL and i % 8 == 7:
                t["том 2"] += ping(roll(o + 12, 4, 4, key=64, vel=(70, 110), pitch=-7), 30)

    def say(name: str, bar: int, phrase, down: int = 0) -> None:
        t[name] += [N(bar * 16 + p, ln, k - down, v) for p, ln, k, v in phrase]

    # Мелодия до перелома — «зов, пауза, зов, ответ» на четыре такта петли; во вступлении — с такта 5
    for b in (4, 6):
        say("мелодия", b, ZOV)
    say("мелодия", 7, OTV)
    for c, b in enumerate(range(*HOOK, 4)):
        say("мелодия", b, ZOV)
        say("контрмелодия", b + 1, REPLY[c % 2])       # второй голос отвечает в паузе
        say("мелодия", b + 2, ZOV)
        say("мелодия", b + 3, OTV_UP if c == 3 else OTV)
    for c, b in enumerate(range(*VERSE, 4)):           # в куплете второй зов — октавой ниже или уступает второму голосу
        say("мелодия", b, ZOV)
        if c % 2 == 0:
            say("мелодия", b + 2, ZOV, down=12)
        if b + 3 not in OFF:                           # такт 40 — тишина перед переломом
            say("мелодия", b + 3, OTV)
    say("контрмелодия", 30, SOLO)                      # петля молчит — второй голос один
    say("контрмелодия", 38, SOLO_E)
    # После перелома — мотив в конце такта, через такт октавой ниже; раз в восемь тактов нижний кончается вверх
    for c, b in enumerate(range(CUT, 72, 2)):
        say("мелодия", b, MOTIF)
        say("мелодия", b + 1, MOTIF_UP if c % 4 == 3 else MOTIF, down=12)
    for b in range(CUT + 3, 72, 4):                    # второй голос: долгая ми в начале каждого четвёртого такта
        say("контрмелодия", b, LONG)
    for b in range(FINAL[0] + 1, 72, 4):               # в финале — ещё и в начале второго
        say("контрмелодия", b, RISE)
    t["мелодия"] = human(sorted(t["мелодия"]), 5, seed=3)

    # Крэш на входах частей; в финал — со второй доли (ложный вход)
    for b in (8, 24, CUT):
        t["крэш"].append(N(b * 16, 8, 60, 100))
    t["крэш"].append(N(FALSE * 16 + 4, 8, 60, 112))

    # Последний такт — одна нота 808 и бочка
    end = 71 * 16
    for k in ALL:
        t[k] = [n for n in t[k] if n.pos < end]
    t["808"].append(N(end, 16, ROOTS2[3], 110))
    t["бочка"].append(N(end, 1, 60, 100))
    t["808"] = human(sorted(t["808"]), 7, seed=11)

    # Плёнка встаёт: вторая половина такта — всё молчит, хэт тормозит и съезжает на октаву
    for b in BREATHS:
        a, z = b * 16 + 8, b * 16 + 16
        for k in ALL:
            t[k] = mute(t[k], a, z)
        t["хэт"] += roll(a, 8, 12, key=57 if b == 23 else 60, vel=(100, 55), pan=(-30, 30), pitch=-12, curve=.5)

    # Ложный вход: первая доля такта 57 — тишина; бочка, 808, клэп и крэш бьют с шага 4
    a = FALSE * 16
    for k in ALL:
        t[k] = mute(t[k], a, a + 4)
    t["808"].append(N(a + 4, 6, ROOTS2[0], 116))
    t["бочка"].append(N(a + 4, 1, 60, 104))
    return {k: sorted(v) for k, v in t.items()}

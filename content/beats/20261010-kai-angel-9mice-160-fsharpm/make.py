HALF = ((8, 1, 78, 110), (10, 1, 66, 90), (11, 1, 67, 80), (12, 1, 69, 94), (14, 2, 66, 86))  # такт 24, вторая половина
PICK = ((8, 1, 73, 96), (9, 1, 69, 84), (10, 1, 67, 88), (12, 1, 78, 118), (13, 3, 66, 92))   # такт 32, затакт
DOWN = ((8, 1, 78, 104), (9, 1, 69, 86), (10, 1, 67, 82), (11, 1, 66, 78), (12, 4, 61, 90))   # такт 40, спуск

# Тема после перелома — фраза в такт: верхний фа-диез на первой доле, дальше дыры; в третьем такте круга +1 нота
THEME = ((0, 1, 78, 100), (4, 1, 66, 80), (5, 1, 67, 90), (6, 1, 66, 74), (8, 1, 69, 94), (9, 1, 66, 78),
         (12, 2, 67, 86))
PULSE = (66, 66, 66, None, 66, 66, 78, 66, 66, 66, 66, None, 66, 66, 78, 66)    # пульс: шестнадцатые, прыжок на октаву
ARP = (61, 73, 66, 78, 62, 74, 69, 57)                                          # перебор восьмыми с бросками
MID = ((54, 54, 57, 54, 61, 61, 57, 55), (54, 54, 55, 54, 57, 57, 54, 54))      # средний голос: две ячейки по такту
LONG = (((0, 12, 66), (12, 8, 69), (20, 7.5, 73)), ((0, 12, 66), (12, 8, 69), (20, 7.5, 74)))   # долгие вверх по терциям
RISE = (78, 79, 81, 85, 86, 90, 91, 93, 97, 98, 102, 103)                       # конец: высокая нота каждые полтакта


def drums(b: int) -> bool:
    return V1 <= b < 70


def bar(o: int, notes) -> list[N]:
    return [N(o + p, ln, k, v) for p, ln, k, v in notes]


def compose() -> dict[str, list[N]]:
    names = ("мелодия", "пульс", "долгие ноты", "перебор", "средний голос", "808",
             "бочка", "клэп", "хэт", "открытый хэт", "перк")
    t = {k: [] for k in names}

    # Мелодия до перелома: только в паузах петли и тихо в конце её круга
    for b in (3, 11, 19, 27, 35, 43):
        t["мелодия"] += bar(b * 16, TAIL)
    t["мелодия"] += bar(15 * 16, CALL) + bar(23 * 16, HALF) + bar(31 * 16, PICK) + bar(39 * 16, DOWN)
    t["мелодия"].append(N(15 * 16 + 3.5, .5, 73, 70))                         # такт 16: подъезд к броску

    # После перелома: пять слоёв по складу петли; вдох — последняя доля каждого второго такта, у всех разом
    for b in range(SW, BARS):
        o, turn = b * 16, (b - SW) % 4
        stop = 12 if turn % 2 else 16
        if b < 70:
            theme = [n for n in THEME if n[0] < stop] + ([(14, 1, 73, 98)] if turn == 2 else [])
            t["мелодия"] += bar(o, theme)
            t["пульс"] += [N(o + i, 1, k, 108 if i % 4 == 0 else 96 if k > 70 else 84 + 6 * (i % 2 == 0))
                           for i, k in enumerate(PULSE) if k and i < stop]
        if b < 68:
            t["перебор"] += [N(o + 2 * i, 1.5, k, 92 if k > 70 else 76 + 4 * (i % 3)) for i, k in enumerate(ARP)
                             if 2 * i < stop]
            t["средний голос"] += [N(o + 2 * i, 1.5, k, 72 + 6 * (i % 4 == 0)) for i, k in enumerate(MID[turn % 2])
                                   if 2 * i < stop]
        if turn % 2 == 0:
            t["долгие ноты"] += [N(o + p, ln, k, 80 - 6 * i) for i, (p, ln, k) in enumerate(LONG[(b - SW) // 4 % 2])]
    # Конец: высокая короткая нота каждые полтакта, каждая выше прошлой — к концу мелодия растёт
    t["мелодия"] += [N(64 * 16 + 8 * i + 2, .75, k, 84 + 3 * i) for i, k in enumerate(RISE)]
    t["мелодия"] += bar(70 * 16, ((0, 1, 78, 96), (4, 4, 66, 84), (8, 1, 67, 70))) + bar(71 * 16, ((0, 6, 66, 64),))
    t["долгие ноты"] += [N(70 * 16, 12, 66, 70), N(70 * 16 + 12, 8, 69, 62)]

    # 808: куплет, припев, второй куплет — по басу автора; после перелома — тоника
    for b in range(V1, 70):
        turn = b % 4
        cycle = (BASS_V if b % 8 < 4 else BASS_V2) if b < CH else (BASS_C if b % 8 < 4 else BASS_C2) if b < V2 \
            else BASS_W if b < SW else (BASS_S if b % 8 < 4 else BASS_S2)
        notes = list(cycle[turn])
        o = b * 16
        if b in (30, 38, 54, 62):                                               # конец восьмёрки: съезд к фа-диезу
            p, ln, k = notes.pop()
            t["808"] += glide(o + p, ln, k, F + 12, at=ln / 2, over=ln / 2)
        if b in (9, 25, 57):                                                    # «выстрел»: вверх на две-три октавы и назад
            p, ln, k = notes.pop()
            t["808"] += [N(o + p, ln, k, 110), N(o + 12.5, .5, F + 36, 110, slide=True),
                         N(o + 13, .5, F + 48, 110, slide=True), N(o + 13.5, .5, F, 110, slide=True)]
        t["808"] += [N(o + p, ln, k, 110) for p, ln, k in notes]
    t["808"] = human(sorted(t["808"]), 6, seed=160)

    for b in range(BARS):
        o, turn = b * 16, b % 4
        if not drums(b):
            continue
        after = b >= SW
        # Каркас: до перелома клэп на третьей доле, после — на второй и четвёртой
        claps = [N(o + 4, 1, 60, 112), N(o + 12, 1, 60, 116)] if after else [N(o + 8, 1, 60, 116)]
        if b in (V1, CH, V2, SW):
            claps = flam(claps[0]) + claps[1:]
        if b % 8 == 6 and not after:                                             # клэп отвечает сам себе
            claps = echo(claps, 3, times=2, decay=.5, width=40)
        t["клэп"] += claps
        # Бочка — только по восьмым, призраки рядом с сильным ударом
        kick = ((0, 10), (6,), (0, 2), (10, 14)) if b < CH else ((0,), (0, 10), (6,), (0, 14)) if b < V2 \
            else ((0, 6), (10,), (0,), (2, 10)) if not after else ((0, 6), (8,), (0, 10), (6, 14))
        t["бочка"] += [N(o + p, 1, 60, 118 if p == 0 else 100) for p in kick[turn]]
        t["бочка"] += [N(o + 2 + 8 * (turn % 2), .5, 60, 44 + 8 * turn)]                    # призрак
        if b in (9, 13, 19, 25, 29, 35, 41, 45, 51, 57):                         # дробь задранной бочкой
            t["бочка"] += [N(o + 8, .3, 94, 118), N(o + 8.5, .3, 95, 114)]
            t["бочка"] += roll(o + 12, 2, 14, key=99, pitch=-24, vel=(114, 10), curve=.7) + [N(o + 14, .5, 72, 96)]
        if b in (61, 62, 63):                                                     # съезд каждый раз октавой ниже
            t["бочка"] += roll(o + 12, 2, 14, key=99 - 12 * (b - 61), pitch=-24, vel=(114, 10), curve=.7)
        # Хэт
        if after:
            plan, base, key, bones = PLAN_SW, SW, 60, DENSE
        else:
            plan, base, key = (PLAN_V1, V1, 60) if b < CH else (PLAN_CH, CH, 63) if b < V2 else (PLAN_V2, V2, 61)
            bones = VERSE if b < CH or b >= V2 else CHORUS
        word = " ".join(plan).split()[(b - base) % (8 * len(plan))]
        bone, fill = bones[int(word[0])], word[1]
        hat = spread(hits(o, bone, key=key, vel=82, ln=.5), 38, seed=b)
        t["хэт"] += over(hat, FILLS[fill](o) if fill != "." else [])
        # Открытый хэт и перк
        if CH <= b < V2 and turn in (1, 3):
            t["открытый хэт"].append(N(o + 12, 2, 60, 92))
        elif after and turn == 2:
            t["открытый хэт"] += [N(o + 6, 2, 58, 86), N(o + 0, 2, 58, 70)]
        if b < CH or V2 <= b < SW:
            if turn % 2:
                t["перк"] += [N(o + 6, 1, 60, 90, -45), N(o + 14, 1, 65, 78, 45)]
        elif b < V2:
            perc = [N(o + 3, 1, 62, 92, 40), N(o + 10, 1, 60, 84, -40)]
            t["перк"] += echo(perc[1:], 1.5, times=2, width=50, pitch=2) + perc[:1] if turn == 3 else perc
        else:
            t["перк"] += spread([N(o + 2, 1, 60, 88), N(o + 7, 1, 67, 80), N(o + 11, 1, 63, 84)], 50, seed=b + 7)

    # Хэт в конце восьмёрки: восьмые вниз и обратно, панорама влево и назад вправо
    for b in (22, 54):
        a = b * 16
        t["хэт"] = mute(t["хэт"], a, a + 16)
        t["хэт"] += [N(a + 2 * i, .5, k, 84 + 3 * i, p) for i, (k, p) in
                     enumerate(zip((72, 69, 68, 66, 64, 65, 67, 69), (-15, -35, -50, -62, -40, -10, 20, 45)))]
    # Такт 24: четыре восьмые вверх с ростом силы, дальше — вдох
    a = 23 * 16
    t["хэт"] = mute(t["хэт"], a, a + 8)
    t["хэт"] += [N(a + 2 * i, .5, k, v) for i, (k, v) in enumerate(zip((72, 75, 79, 84), (83, 96, 110, 123)))]
    # Такт 64: трещотка в последней доле — 48 нот одной высоты, сила волной
    a = 63 * 16 + 12
    t["хэт"] = mute(t["хэт"], a, a + 4)
    t["хэт"] += [N(a + i / 12, 1 / 12, 75, max(1, round(65 * (1 - abs(i - 24) / 24))), (-1) ** i * 15) for i in range(48)]
    # Отскок бочки перед входом части: три удара с падающей силой
    for b in (7, 31, 39):
        t["бочка"] += [N(b * 16 + 14, .32, 60, 108), N(b * 16 + 14.32, .52, 60, 89), N(b * 16 + 14.84, .5, 60, 64)]

    # Провалы перед восьмёрками — каждый своего размера
    drum_parts = ("бочка", "клэп", "хэт", "открытый хэт", "перк")
    keep = {"бочка": lambda n: n.pos % 16 >= 14 and int(n.pos // 16) in (7, 31, 39)}   # отскок остаётся
    for name in drum_parts + ("808",):
        cuts = [(15 * 16, 16 * 16), (23 * 16 + 8, 24 * 16), (31 * 16, 32 * 16), (39 * 16 + 8, 40 * 16),
                (47 * 16 + 12, 48 * 16), (53 * 16 + 12, 54 * 16), (59 * 16 + 12, 60 * 16)]
        if name == "808":
            cuts += [(47 * 16, 48 * 16)]
            cuts = [c for c in cuts if c != (53 * 16 + 12, 54 * 16)]           # доля 54.4 — 808 играет
        if name == "перк":
            cuts += [(23 * 16, 23 * 16 + 8), (47 * 16, 48 * 16)]
        for a, z in cuts:
            spare = [n for n in t[name] if a <= n.pos < z and keep.get(name, lambda n: False)(n)]
            t[name] = mute(t[name], a, z) + spare
    # Плёнка встаёт: вторая половина такта 24 и последняя доля такта 48
    t["хэт"] += roll(23 * 16 + 8, 8, 12, vel=(110, 50), pitch=-12, curve=.5)
    t["хэт"] += roll(47 * 16 + 12, 4, 8, vel=(104, 46), pitch=-12, curve=.5)
    t["хэт"] = human(t["хэт"], 5, seed=10)
    return {k: sorted(v) for k, v in t.items()}

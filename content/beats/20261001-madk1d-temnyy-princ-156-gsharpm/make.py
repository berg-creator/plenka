"""Бит 01 под MADK1D и Тёмного принца, переписанный под замер: 156 BPM, соль-диез минор, G#m – E – B – D#m.

Образец для prompts/beats.md. Первую версию владелец 01.10.2026 собрал в FL Studio и одобрил, а знакомый
из музыки сказал, что бит звучит неактуально. Замер (src/zamer.py, data/beats_zamer.json) показал, чем он
отличался от битов и треков сцены канала: бочка стояла под каждой нотой 808 (98% против 10–30%), 808 играл
только тоники длинными нотами и пропадал на весь куплет, хэты были раскиданы по панораме втрое шире,
триолей в хэте было вчетверо меньше. Гармония, мелодия и форма остались — их владелец одобрил;
барабаны и 808 переписаны по скелету «сцена» из брифа:

- 808 ведёт сам: пять нот в такт, короткие связки и одна длинная, восемь разных нот в октаве;
- бочка — на первой доле и иногда на второй, под 808 попадает в каждой пятой ноте;
- хэт — восьмые, дробь в половине тактов припева, триоли в половине, панорама узкая, широкая только в дроби;
- низ не выключается частями: в куплете и на мосту 808 играет, вместо этого три вдоха в полтакта и одно
  выключение на такт;
- мелодии отвечает второй голос, на мосту мелодия уходит на октаву вниз.

С 02.10.2026 это образец записи compose() и приёмов, а не музыки и не паспорта: бит написан до раздела «Цвет»,
владелец назвал его звук «Майнкрафтом», полей form, color, mix, sounds и fx в INFO нет — сборка его бракует.
"""
from __future__ import annotations

from src.noty import N, echo, flam, glide, grace, hits, human, mute, roll, spread, strum

INFO = dict(
    title="MADK1D x Тёмный принц — Полночь",
    bpm=156, key="G#m", scale=[8, 10, 11, 1, 3, 4, 6], bars=80,
    tonal=["аккорды", "гитара", "мелодия", "контрмелодия", "808"],
    skeleton="сцена",
    like="темп и тональность — от первой версии бита; рисунок барабанов и 808 — с замера 01.10.2026 "
         "(data/beats_zamer.json: s01 и s05 — type beat'ы под MADK1D и Big Baby Tape, r02 — madk1d «8 миля»)",
    parts="вступление 1–4, припев 5–20, куплет 21–36, припев 37–52, мост 53–60, припев 61–76, конец 77–80",
    tricks=[
        "808: ведёт низ сам — в такте пять нот, короткая связка из трёх и длинная; раз в припев (такты 12, 44 "
        "и 76) нота съезжает слайдом на октаву вниз; сила вразброс",
        "бочка: редкая — на первой доле, во втором и четвёртом такте круга ещё на второй; под 808 она только "
        "в начале такта",
        "хэт: восьмые, панорама узкая; во втором такте круга — триоль в конце, в третьем — дробь 1/32 "
        "перед клэпом, в четвёртом — триоль и дробь, которая уходит слева направо и вниз на кварту",
        "вдохи: в последнем такте первого припева, куплета и моста вторая половина пустая — ни барабанов, ни 808; "
        "в такте 68 на целый такт пропадают 808 и бочка",
        "клэп: форшлаг в третьем такте круга; в тишину перед вторым и третьим припевом — дробь с разгоном",
        "мелодия: первая нота фразы — с коротким подъездом снизу; на мосту вся мелодия октавой ниже",
        "контрмелодия: отвечает мелодии в четвёртом и восьмом такте припева — повесь другой инструмент, тише",
        "перк: в куплете щелчок на слабых местах; в припеве эхо нотами — три повтора тише и ниже, по сторонам",
        "аккорды: во вступлении, на мосту и в конце — перебором; гитара — сила вразброс",
    ],
)

INTRO, HOOK1, VERSE, HOOK2, BRIDGE, HOOK3, OUTRO = (0, 4), (4, 20), (20, 36), (36, 52), (52, 60), (60, 76), (76, 80)
HOOKS = (HOOK1, HOOK2, HOOK3)
BREATH = (19, 35, 59)       # последний такт перед новой частью: вторая половина — тишина
DROP = 67                   # такт без 808 и бочки посреди последнего припева
SLIDES = (11, 43, 75)       # слайд 808 — событие, а не привычка: у сцены замера их 0,3–0,5 на восемь тактов

# Аккорды первого бита: круг из четырёх со сменой каждый такт. Так больше не пишем — prompts/beats.md, «Цвет»
CHORDS = ((56, 59, 63), (56, 59, 64), (54, 59, 63), (54, 58, 63))      # G#m, E/G#, B/F#, D#m/F#
ARP = ((56, 63, 68, 71, 63, 68, 71, 68), (52, 59, 64, 68, 59, 64, 68, 64),
       (59, 66, 71, 75, 66, 71, 75, 71), (51, 58, 63, 66, 58, 63, 66, 63))

# Мелодия припева, восемь тактов: (такт, доля, длина в долях, нота)
LEAD = ((0, 0, 1.5, 75), (0, 1.5, .5, 71), (0, 2, 1, 73), (0, 3, 1, 75),
        (1, 0, 2, 71), (1, 2.5, .5, 68), (1, 3, 1, 71),
        (2, 0, 1.5, 78), (2, 1.5, .5, 75), (2, 2, 1, 73), (2, 3, 1, 71),
        (3, 0, 3, 70),
        (4, 0, 1.5, 75), (4, 1.5, .5, 71), (4, 2, 1, 73), (4, 3, 1, 75),
        (5, 0, 2, 80), (5, 2, 1, 78), (5, 3, 1, 76),
        (6, 0, 1.5, 75), (6, 1.5, .5, 78), (6, 2, 1, 75), (6, 3, 1, 73),
        (7, 0, 2, 75), (7, 2, 1.5, 70))
ANSWER = ((12, 82), (13, 80), (14, 78), (15, 75))       # ответ мелодии в четвёртом такте, шестнадцатыми вниз
# Второй голос — под длинными нотами мелодии, октавой ниже, по звукам ре-диез минора
COUNTER = ((3, .5, .5, 51), (3, 1, .5, 54), (3, 1.5, 1.5, 58), (7, .5, .5, 58), (7, 1, .5, 54), (7, 1.5, 1, 51))

# 808 по такту круга: (шестнадцатая, длина, нота). Владелец держит 808 на нотах 27–39; все — в тональности.
# Замер сцены: 3,5–5 нот в такт, половина нот — короче двух шестнадцатых, 7–11 разных нот, низ звучит 80–87% такта
BASS_HOOK = (((0, 5, 32), (6, 1, 32), (7, 1, 35), (8, 2, 39), (10, 6, 32)),
             ((0, 6, 28), (6, 2, 28), (10, 1, 35), (11, 1, 32), (12, 4, 28)),
             ((0, 6, 35), (6, 1, 37), (7, 1, 39), (8, 4, 35), (14, 2, 30)),
             ((0, 6, 27), (6, 2, 30), (8, 2, 34), (10, 6, 27)))
BASS_VERSE = (((0, 6, 32), (6, 2, 32), (10, 6, 35)), ((0, 8, 28), (10, 6, 28)),
              ((0, 6, 35), (6, 2, 35), (10, 6, 30)), ((0, 8, 27), (10, 2, 27), (12, 4, 34)))
ROOTS = (32, 28, 35, 27)
DRUMS = ("808", "бочка", "клэп", "хэт", "открытый хэт", "перк")


def bars(*parts):
    return [b for a, z in parts for b in range(a, z)]


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("аккорды", "гитара", "мелодия", "контрмелодия", *DRUMS)}
    soft = set(bars(INTRO, BRIDGE, OUTRO))
    for b in range(INFO["bars"]):
        t["аккорды"] += (strum(b * 16, 16, CHORDS[b % 4], gap=.5, vel=(64, 84)) if b in soft
                         else [N(b * 16, 16, n, 78) for n in CHORDS[b % 4]])
    for b in bars(INTRO, HOOK1, VERSE, HOOK2, HOOK3, OUTRO):
        t["гитара"] += [N(b * 16 + i * 2, 2, n, 92 if i % 4 == 0 else 72) for i, n in enumerate(ARP[b % 4])]
    t["гитара"] = human(t["гитара"], 6, seed=2)

    for a, z in (*HOOKS, BRIDGE):
        down = 12 if (a, z) == BRIDGE else 0             # на мосту мелодия — октавой ниже
        for rep in range(0, z - a, 8):
            for b, beat, ln, n in LEAD:
                # Первая нота каждой четвёрки тактов подъезжает с полутона ниже. Мелодию играет синтезатор:
                # слайд там не работает, поэтому подъезд — короткой нотой
                note = N((a + rep + b) * 16 + beat * 4, ln * 4, n - down, 96)
                t["мелодия"] += grace(note) if beat == 0 and b % 4 == 0 else [note]
            if not down:
                t["мелодия"] += [N((a + rep + 3) * 16 + p, 1, n, 84 - i * 10) for i, (p, n) in enumerate(ANSWER)]
                t["контрмелодия"] += [N((a + rep + b) * 16 + beat * 4, ln * 4, n, 80) for b, beat, ln, n in COUNTER]

    hook = set(bars(*HOOKS))
    for b in bars(HOOK1, VERSE, HOOK2, BRIDGE, HOOK3):
        o, c, bridge = b * 16, b % 4, b in bars(BRIDGE)
        t["клэп"] += flam(N(o + 8, 1, 60, 110), gap=.33) if b in hook and c == 2 else [N(o + 8, 1, 60, 110)]
        if b % 8 == 7:
            t["клэп"].append(N(o + 14, 1, 60, 70))
        if bridge:                                       # мост: клэп и длинный 808 — низ остаётся
            t["808"].append(N(o, 14, ROOTS[c], 104))
            continue

        for p, ln, key in (BASS_HOOK if b in hook else BASS_VERSE)[c]:
            if b in SLIDES and p == 10:                  # раз в припев: нота съезжает на октаву вниз
                t["808"] += glide(o + p, ln, key + 12, key, at=2, over=2)
            else:
                t["808"].append(N(o + p, ln, key, 110))
        # Бочка редкая и не под каждой нотой 808: первая доля, во 2-м и 4-м такте круга — ещё вторая
        t["бочка"] += hits(o, "x...x..........." if c % 2 else "x...............", vel=115)

        if b not in hook:                                # куплет: восьмые с призраками, фишка раз в два такта
            hats = hits(o, "X.o.x.o.X.o.x.o.", vel=88, ln=.5)
            fill = roll(o + 10, 1.5, 3, vel=(50, 84)) if c == 1 else roll(o + 14, 2, 3, vel=(60, 92)) if c == 3 else []
            t["перк"] += hits(o, "...x.......x....", key=64, vel=70)
        else:
            hats = hits(o, "X.x.X.x.X.x.X.x.", vel=86, ln=.5)
            if c == 1:                                   # триоль в конце такта
                fill = roll(o + 14, 2, 3, vel=(62, 96))
            elif c == 2:                                 # 1/32 перед клэпом, через раз — выше на терцию
                fill = roll(o + 6, 2, 4, vel=(55, 100), pitch=3 if b % 8 == 6 else 0)
            elif c == 3:                                 # триоль и дробь слева направо, вниз на кварту
                fill = roll(o + 12, 2, 3, vel=(60, 90)) + roll(o + 14, 2, 4, vel=(55, 108), pan=(-45, 45), pitch=-5)
            else:
                fill = []
                t["открытый хэт"].append(N(o + 14, 2, 60, 92, 20))
            if c == 2:                                   # эхо нотами: три повтора тише и ниже, по сторонам
                t["перк"] += echo([N(o + 3, 1, 64, 92)], 3, times=3, decay=.65, width=50, pitch=-2)
        hats = spread(hats, 18, seed=b)                  # узко: у лидеров замера разброс панорамы хэта 3–20
        if fill:
            start, end = min(n.pos for n in fill), max(n.pos + n.ln for n in fill)
            hats = [h for h in hats if not start <= h.pos < end] + fill
        t["хэт"] += hats

    for k in DRUMS:                                      # вдохи: полтакта тишины перед новой частью
        for b in BREATH:
            t[k] = mute(t[k], b * 16 + 8, b * 16 + 16)
    for k in ("808", "бочка"):                           # выключение на такт посреди последнего припева
        t[k] = mute(t[k], DROP * 16, DROP * 16 + 16)
    t["808"] = human(t["808"], 7, seed=1)

    # Сбивки в тишину: хэт перед первым припевом, клэп с разгоном — перед вторым и третьим
    t["хэт"] += roll(3 * 16 + 12, 4, 8, vel=(45, 100), pan=(-40, 40))
    t["клэп"] += roll(35 * 16 + 12, 4, 8, vel=(50, 105), pitch=-5)
    t["клэп"] += roll(59 * 16 + 8, 8, 16, vel=(45, 115), pitch=7, curve=1.6)
    return t

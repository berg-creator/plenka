"""Бит 01 под MADK1D и Тёмного принца: 156 BPM, соль-диез минор, G#m – E – B – D#m.

Образец для prompts/beats.md. Ноты этого бита владелец 01.10.2026 собрал в FL Studio
и одобрил; здесь к ним добавлено то, что он дорисовал сам (хэты по панораме, сила 808
вразброс, 808 на две октавы ниже мелодии), и приёмы пианоролла из src/noty.py.

    python -m src.noty --build content/beats/20261001-madk1d-temnyy-princ-156-gsharpm
"""
from __future__ import annotations

from src.noty import N, echo, flam, glide, grace, human, roll, spread, strum

INFO = dict(
    title="MADK1D x Тёмный принц — Полночь",
    bpm=156, key="G#m", scale=[8, 10, 11, 1, 3, 4, 6], bars=84,
    tonal=["аккорды", "гитара", "мелодия", "808"],
    like="два самых просматриваемых type beat'а сентября 2026 под MADK1D и Тёмного принца",
    parts="вступление 1–8, припев 9–24, куплет 25–40, припев 41–56, мост 57–64, припев 65–80, конец 81–84",
    tricks=[
        "хэт: вся партия раскидана по панораме; в конце каждого круга дробь 1/32 съезжает слева направо "
        "и вниз на кварту; на 6-м такте восьмёрки — очередь 1/64 вверх; на 10-м — дробь с разгоном; "
        "на 2-м — триоли; в куплете рисунок реже, с тихими призраками",
        "808: концы фраз подъезжают слайдом на октаву и на квинту; сила вразброс",
        "клэп: форшлаг на третьем такте круга; из моста в припев — дробь с разгоном и подъёмом на квинту",
        "перк: эхо нотами — четыре удара тише и ниже, по сторонам; повесь любой короткий щелчок",
        "мелодия: первая нота фразы — с коротким подъездом снизу; в конце четвёрки ответ шестнадцатыми, затухает",
        "аккорды: во вступлении и мосте — перебором; гитара — сила вразброс",
    ],
)

INTRO, HOOK1, VERSE, HOOK2, BRIDGE, HOOK3, OUTRO = (0, 8), (8, 24), (24, 40), (40, 56), (56, 64), (64, 80), (80, 84)
HOOKS = (HOOK1, HOOK2, HOOK3)
DRUMS = (HOOK1, VERSE, HOOK2, HOOK3)

# Аккорды по кругу из четырёх тактов; верхний голос почти стоит на месте
CHORDS = ((56, 59, 63), (56, 59, 64), (54, 59, 63), (54, 58, 63))      # G#m, E/G#, B/F#, D#m/F#
ARP = ((56, 63, 68, 71, 63, 68, 71, 68), (52, 59, 64, 68, 59, 64, 68, 64),
       (59, 66, 71, 75, 66, 71, 75, 71), (51, 58, 63, 66, 58, 63, 66, 63))
ROOTS = (32, 28, 35, 27)                    # 808 — там, куда его поставил владелец: на две октавы ниже гитары

# Мелодия припева, восемь тактов: (такт, доля, длина в долях, нота). Сильные доли — на звуках аккорда
LEAD = ((0, 0, 1.5, 75), (0, 1.5, .5, 71), (0, 2, 1, 73), (0, 3, 1, 75),
        (1, 0, 2, 71), (1, 2.5, .5, 68), (1, 3, 1, 71),
        (2, 0, 1.5, 78), (2, 1.5, .5, 75), (2, 2, 1, 73), (2, 3, 1, 71),
        (3, 0, 3, 70),
        (4, 0, 1.5, 75), (4, 1.5, .5, 71), (4, 2, 1, 73), (4, 3, 1, 75),
        (5, 0, 2, 80), (5, 2, 1, 78), (5, 3, 1, 76),
        (6, 0, 1.5, 75), (6, 1.5, .5, 78), (6, 2, 1, 75), (6, 3, 1, 73),
        (7, 0, 2, 75), (7, 2, 1.5, 70))
ANSWER = ((12, 82), (13, 80), (14, 78), (15, 75))       # ответ мелодии в четвёртом такте, шестнадцатыми вниз

# 808 в припеве по такту круга: (шестнадцатая, длина). Бочка бьёт там же
BASS_HOOK = (((0, 6), (6, 4), (10, 6)), ((0, 6), (6, 4), (10, 4), (14, 2)),
             ((0, 6), (6, 4), (10, 6)), ((0, 3), (3, 3), (6, 5), (11, 3), (14, 2)))
BASS_VERSE = ((0, 8), (10, 6))
KICK_VERSE = (0, 6, 10)
# Последний такт части с барабанами: вторая половина пустая, чтобы следующая часть вошла с тишины
GAP = {z - 1 for _, z in DRUMS}


def bars(*parts):
    return [b for a, z in parts for b in range(a, z)]


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("аккорды", "гитара", "мелодия", "808", "бочка", "клэп", "хэт", "открытый хэт", "перк")}
    soft = set(bars(INTRO, BRIDGE))
    for b in range(INFO["bars"]):
        t["аккорды"] += (strum(b * 16, 16, CHORDS[b % 4], gap=.5, vel=(64, 84)) if b in soft
                         else [N(b * 16, 16, n, 78) for n in CHORDS[b % 4]])
    for b in bars(INTRO, HOOK1, VERSE, HOOK2, HOOK3, OUTRO):
        t["гитара"] += [N(b * 16 + i * 2, 2, n, 92 if i % 4 == 0 else 72) for i, n in enumerate(ARP[b % 4])]
    t["гитара"] = human(t["гитара"], 6, seed=2)

    for a, z in (*HOOKS, BRIDGE):
        for rep in range(0, z - a, 8):
            for b, beat, ln, n in LEAD:
                pos = (a + rep + b) * 16 + beat * 4
                # Первая нота каждой четвёрки тактов подъезжает с полутона ниже. Мелодию играет синтезатор:
                # слайд там не работает, поэтому подъезд — короткой нотой
                note = N(pos, ln * 4, n, 96)
                t["мелодия"] += grace(note) if beat == 0 and b % 4 == 0 else [note]
            t["мелодия"] += [N((a + rep + 3) * 16 + p, 1, n, 84 - i * 10) for i, (p, n) in enumerate(ANSWER)]

    hook = set(bars(*HOOKS))
    for b in bars(*DRUMS):
        o, c, root = b * 16, b % 4, ROOTS[b % 4]
        live = (lambda p: b not in GAP or p < 8)
        bass = BASS_HOOK[c] if b in hook else BASS_VERSE
        for p, ln in bass:
            if not live(p):
                continue
            ln = min(ln, 8 - p) if b in GAP else ln
            if b in hook and c == 1 and p == 14:             # конец второго такта: вверх на октаву
                t["808"] += glide(o + p, ln, root, root + 12, over=ln)
            elif b in hook and c == 3 and p == 11:           # конец круга: вверх на квинту
                t["808"] += glide(o + p, ln, root, root + 7, at=1.5, over=1.5)
            else:
                t["808"].append(N(o + p, ln, root, 110))
        t["бочка"] += [N(o + p, 1, 60, 115) for p in ([p for p, _ in bass] if b in hook else KICK_VERSE) if live(p)]

        clap = N(o + 8, 1, 60, 110)
        t["клэп"] += flam(clap, gap=.33) if b in hook and c == 2 else [clap]
        if b % 8 == 7 and b not in GAP:
            t["клэп"] += [N(o + 14, 1, 60, 62), N(o + 15, 1, 60, 84)]

        opened = b in hook and c in (0, 2)
        if b in hook:
            hats = [N(o + p, .5, 60, 100 if p % 4 == 0 else 74) for p in range(0, 16, 2) if not (opened and p == 14)]
        else:                                # куплет: реже и с тихими призраками между долями
            hats = [N(o + p, .5, 60, v) for p, v in ((0, 100), (3, 45), (4, 80), (8, 100), (11, 45), (12, 80), (14, 62))]
        hats = spread(hats, 55, seed=b)
        fill = []
        if c == 3:                           # конец круга: 1/32 слева направо и вниз на кварту
            fill = roll(o + 12, 4, 8, vel=(52, 108), pan=(-70, 70), pitch=-5)
        elif b % 8 == 5:                     # очередь 1/64 вверх на малую терцию
            fill = roll(o + 10, 2, 8, vel=(45, 95), pitch=3)
        elif b % 16 == 9:                    # разгон: десять ударов сгущаются к концу такта и уходят влево
            fill = roll(o + 8, 8, 10, vel=(50, 105), pan=(60, -60), pitch=4, curve=2)
        elif c == 1:                         # триоли на последней доле
            fill = roll(o + 12, 4, 6, vel=(70, 96))
        if fill:
            hats = [h for h in hats if h.pos < fill[0].pos] + fill
        t["хэт"] += [h for h in hats if live(h.pos - o)]
        if opened:
            t["открытый хэт"].append(N(o + 14, 2, 60, 96, 30 if c else -30))

        if c == 2 and b not in GAP:          # эхо нотами: четыре удара, каждый тише и на тон ниже, по сторонам
            t["перк"] += echo([N(o + 6, 1, 64, 96)], 3, times=3, decay=.65, width=65, pitch=-2)

    t["808"] = human(t["808"], 7, seed=1)
    # Сбивки без остальных барабанов: в тишину перед первым припевом и из моста в последний
    t["клэп"] += roll(7 * 16 + 12, 4, 8, vel=(40, 100), pitch=-5)
    t["клэп"] += roll(63 * 16 + 8, 8, 16, vel=(35, 115), pitch=7, curve=1.6)
    return t

def drums(b: int) -> bool:
    return 1 <= b < BARS - 1


def compose() -> dict[str, list[N]]:
    t = {k: [] for k in ("аккорды", "мелодия", "плак", "арп", "мелодия верх", "808",
                         "бочка", "клэп", "хэт", "открытый хэт", "перк")}

    def plays(part: str, b: int) -> bool:
        return section(b) in LAYERS[part].split() and b < BARS - 1

    for b in range(BARS):
        o, s, odd = b * 16, section(b), b % 2
        phrase = b - odd                                # начало двухтактовой фразы

        # Аккорды: ре-диез с ля-диезом парами восьмыми весь такт; си с фа-диезом до шага 10; каждый четвёртый такт —
        # без пары на шаге 4
        if plays("аккорды", b):
            if not odd:
                steps, keys, vels = range(0, 16, 2), (58, 63), (100, 72, 84, 70, 96, 72, 86, 76)
            else:
                steps = (0, 2, 6, 8) if b % 4 == 3 else (0, 2, 4, 6, 8)
                keys, vels = (59, 66), (98, 74, 88, 72, 92)
            t["аккорды"] += [N(o + p, 2, k, v - (8 if k == keys[1] else 0)) for p, v in zip(steps, vels) for k in keys]

        # Тема: зов в чётных тактах, ответ в нечётных
        if plays("мелодия", b) and b != DROPS[1]:
            late = s in ("H", "I")
            if not odd:
                notes = CALL_B if late else CALL
            elif s == "I":
                notes = ANSWER_END
            elif late and b % 4 == 3:
                notes = ANSWER_B
            else:
                notes = ANSWER_2 if b % 4 == 3 else ANSWER
            bar = [N(o + p, ln, k, v) for p, ln, k, v in notes]
            if not odd and b % 8 == 4 and s in ("D", "E"):          # подъезд к вершине раз в восьмёрку
                top = next(n for n in bar if n.key == 75 and n.pos == o + 10)
                bar = [n for n in bar if n != top] + grace(top, -2, .5)
            if b == BREATHS[0]:
                bar = mute(bar, o + 8, o + 16)
            t["мелодия"] += bar

        if plays("плак", b) and not odd:
            t["плак"] += [N(o + p, 1, k, v) for (p, k), v in zip(PLUCK, PLUCK_VEL)]
        if plays("арп", b) and not odd:
            t["арп"] += [N(o + p, ln, k, v) for p, ln, k, v in ARP]
        if plays("мелодия верх", b) and b % 4 == 0:
            t["мелодия верх"] += [N(o + p, ln, k, v) for p, ln, k, v in TOP if o + p + ln <= (BARS - 1) * 16]

        # 808
        if b in DROPS or b == 0:
            pass
        elif s == "K":
            t["808"] += [N(o, 16 if b < BARS - 1 else 8, DS if not odd else B, 84)]
        else:
            i = b % 8                                        # чётные строки — ре-диез, как аккорды
            bar = [N(o + p, ln, k, 110) for p, ln, k in (BASS_B if b >= 40 else BASS_A)[i]]
            if b in SLIDES:                                  # слайд вверх на кварту раз в восемь-шестнадцать тактов
                last = bar[-1]
                bar = bar[:-1] + glide(last.pos, last.ln, last.key, last.key + 5, at=last.ln - 1.5, over=1.5)
            if b in ENDS:                                    # своя находка: отскок на октаву
                last = bar[-1]
                bar = bar[:-1] + [N(last.pos, 1, last.key, 112), N(last.pos + 1, 1, last.key + 12, 104, -40),
                                  N(last.pos + 2, last.ln - 2, last.key, 108)]
            if b in BREATHS:
                bar = mute(bar, o + 8, o + 16)
            t["808"] += swing(bar, SW)

        # «Плёнка встаёт»: дробь тормозит и съезжает на октаву — вдохи и провалы
        if b in (BREATHS[0], *DROPS):
            t["хэт"] += roll(o + 8, 8, 10, vel=(104, 48), pan=(-30, 30), pitch=-12, curve=.5)
        if not drums(b):
            continue
        cut = b in BREATHS or b in DROPS                    # вторая половина такта — без барабанов
        quiet = s == "K"

        kick = hits(o, KICKS[(b + (3 if b >= 40 else 0)) % 8] if not quiet else "x...............", vel=112, ghost=.45)
        if b in KICK_PERC:                                   # кик как перк: задранная бочка, три удара вниз
            kick += [N(o + 12, .4, 94, 118), N(o + 13, .4, 89, 100), N(o + 14.5, .4, 85, 84)]
        claps = [N(o + 8, 1, 60, 110)]
        if b % 4 == 1 and not quiet:
            claps.append(N(o + 14, 1, 60, 74))
        if b in (8, 25, 65, 80):
            claps = flam(claps[0], .25, .5) + claps[1:]

        key = 62 if s == "E" else 60
        plan = PLANS[(b // 8) % len(PLANS)].split()[b % 8]
        bone, fill = int(plan[0]), plan[1]
        hat = swing(spread(hits(o, BONES[bone], key=key, vel=84, ln=.5), 38, seed=b), SW)
        hat = over(hat, FILLS[fill](o, key) if fill != "." else [])
        if quiet:
            hat = [n for n in hat if (n.pos - o) % 2 == 0 or n.vel > 90]

        perc = [N(o + 7, 1, 60, 78)] if odd else [N(o + 11, 1, 63, 70)] if b % 4 == 2 else []
        if b % 8 == 7 and not cut:
            perc += echo([N(o + 13, 1, 65, 100)], 1, times=2, decay=.6, width=48, pitch=2)
        perc = swing(spread(perc, 50, seed=b + 300), SW)
        ohat = [N(o + (12 if b % 8 == 3 else 6), 2, 60, 80)] if b % 4 == 3 and s in "DHJ" else []

        if cut:
            kick, claps, hat, perc, ohat = (mute(x, o + 8, o + 16) for x in (kick, claps, hat, perc, ohat))
        t["бочка"] += swing(kick, SW)
        t["клэп"] += claps
        t["хэт"] += hat
        t["перк"] += perc
        t["открытый хэт"] += ohat
    t["808"] = human(t["808"], 6, seed=140)
    t["хэт"] = sorted(t["хэт"])
    return {k: sorted(v) for k, v in t.items()}

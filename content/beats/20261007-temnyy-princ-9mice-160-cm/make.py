def music(b: int) -> bool:
    """Музыка молчит каждый четвёртый такт — пустота: «A Milli» звучит 54% времени, порог цвета — 20% тишины."""
    return b % 4 != 3


def launch(o: float, key: int, ln: int, seed: int) -> list[N]:
    """Один запуск куска: тихий удар на первом шаге, сильные на втором и четвёртом; у короткого третьего нет."""
    lo, hi = 55 + seed % 9, 100 + (seed * 7) % 11
    out = [N(o, 1, key, lo), N(o + 1, 2 if ln > 4 else ln - 1, key, hi)]
    if ln > 4:
        out.append(N(o + 3, ln - 3, key, hi + 4 if seed % 2 else hi - 3))
    return out


def circle(o: float, key: int, bars: int = 2, seed: int = 0) -> list[N]:
    """Круг «A Milli» в два такта: шесть запусков встык через 6, 6, 6, 6, 4, 4 шестнадцатых; bars=1 — только первый такт."""
    out = []
    for i, (p, ln) in enumerate(zip((0, 6, 12, 18, 24, 28), (6, 6, 6, 6, 4, 4))):
        if p < bars * 16:
            out += launch(o + p, key, min(ln, bars * 16 - p), seed + i)
    return out



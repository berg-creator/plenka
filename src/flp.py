def main() -> None:
    ap = argparse.ArgumentParser(description="Проект FL Studio из нот, звуков и обработки бита")
    ap.add_argument("--selftest", action="store_true", help="проект читается обратно: темп, каналы, ноты, микшер, автоматизация")
    ap.add_argument("--read", metavar="ФАЙЛ", help="что лежит в проекте .flp")
    args = ap.parse_args()
    if args.selftest:
        selftest()
    elif args.read:
        got = read(Path(args.read).read_bytes())
        print(f"{got['bpm']:g} BPM")
        for i, c in enumerate(got["channels"]):
            print(f"канал {i}: {c['name']} — {c['kind']}" + (f", дорожка микшера {c['insert']}" if c["kind"] != "автоматизация" else "")
                  + (f", {c['plugin']}" + (f" «{x}»" if (x := _factory(c["plugin"], c["state"])) else "") if c["plugin"] else "")
                  + (f", звук {c['sound']}" if c["sound"] else "") + (f", корневая нота {c['root']}" if c["root"] is not None else "")
                  + (f", группа отсечки {c['cut']}" if c["cut"] else "") + (f", ручка громкости {c['knob']}%" if c["knob"] != 78 and c["kind"] != "автоматизация" else "")
                  + (", огибающая громкости: атака {}, hold {}, спад {}, sustain {}, release {}".format(*c["env"]) if c["env"] else "")
                  + (f", состояние плагина {len(c['state'])} байт" if c["state"] else "")
                  + (", стоит: " + ", ".join(_bars(a, b) if a == int(a) and b == int(b) else f"с {a / 4 + 1:.2f} до {b / 4 + 1:.2f}"
                                             for a, b in c["at"]) if c["kind"] == "аудиоклип" and c.get("at") else "")
                  + (", задом наперёд" if c.get("back") else "")
                  + (", растяжка FL: длина {:g} такта, высота {:+d} центов, множитель {}, режим {}".format(c["stretch"][0] / 768, *c["stretch"][1:])
                     if c.get("stretch") else "")
                  + ((f", плавно {c['fade']}: " if c["fade"] else ", держит 1: ") + (", ".join(_bars(a, b) for a, b in c["on"]) or "нигде")
                     if c["kind"] == "автоматизация" else ""))
        for x in got["links"]:
            print(f"привязка: канал {x['clip']} → " + (f"микшер {x['insert']}, слот {x['slot'] + 1}, {'mix' if x['mix'] else 'другой параметр'}"
                                                         if x["insert"] is not None else "не микшер"))
        for p, pat in got["patterns"].items():
            print(f"паттерн {p}: {pat['name']} — " + ", ".join(f"канал {c}: нот {len(n)}" for c, n in pat["notes"].items()))
        for kind, idx, ln, track in got["clips"]:
            print(f"клип: {kind} {idx}, тактов {ln / BAR:g}, дорожка плейлиста {track + 1}")
        print("маркеры: " + ", ".join(f"{bar} {name}" for bar, name in got["markers"]))
        for i, x in got["inserts"].items():
            print(f"микшер {i}: {x['name'] or ('мастер' if not i else '—')} — фейдер {x['level']}%, слоты: "
                  + (", ".join(f"{s + 1} {p}" + (f" ({proq.say(got['eq'][i, s])})" if (i, s) in got["eq"] else "")
                               + (" (разведение {2} из 96, сдвиг фазы {3} из 512, панорама {0} из 128)".format(*got["wide"][i, s])
                                  if (i, s) in got["wide"] else "")
                               + (" (настройки владельца из «Фонаря»)" if (i, s) in got["owner"] else "")
                               for s, p in x["slots"].items()) or "пусто") + f"; идёт в {x['to']}"
                  + (", моно" if i in got["mono"] else "")
                  + "".join(f"; в {to} — сайдчейном (уровень посыла 0)" for at, to in got["duck"] if at == i))
    else:
        ap.print_help()


if __name__ == "__main__":
    main()

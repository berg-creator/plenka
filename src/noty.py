def selftest() -> None:
    """Образцы и одобренные звуки у селфтеста свои, синтетические: настоящие файлы пополняет Мак, и проверка кода
    от их содержимого зависеть не должна. Замер образцов — как у пробного бита: хэт восьмыми, бочку и 808 «замер
    не разобрал» (0 — не сверяется); «вдвое» — тот же ролик, чей замер сел на половинный темп. Одобрены один звук
    и все замеренные петли."""
    from unittest import mock
    from . import config
    z = {"hat_per_bar": 8, "kick_per_bar": 0, "b808_per_bar": 0}
    rows = [{"id": f"s{bpm}", "url": f"https://youtu.be/s{bpm}", "title": f"(free) a x b type beat — {bpm}", "like": ["A", "B"],
             "views": None, "bpm": bpm, "key": None, "zamer": z | {"bpm": bpm}, "note": ""} for bpm in (140, 170, 85)]
    rows.append(rows[0] | {"id": "вдвое", "zamer": {"bpm": 70, "hat_per_bar": 16}})
    with tempfile.TemporaryDirectory() as tmp, mock.patch.object(config, "BEAT_SAMPLES", Path(tmp) / "samples.json"), \
            mock.patch.object(config, "BEAT_MUSIC", Path(tmp) / "music.json"):
        config.BEAT_SAMPLES.write_text(json.dumps(rows, ensure_ascii=False), encoding="utf-8")
        config.BEAT_MUSIC.write_text(json.dumps({"sounds": {min(known()): {"kind": "лид", "bright": 2400}},
                                                 "loops": {name: {"bpm": loop_bpm(name)} for name in loops()}},
                                                ensure_ascii=False), encoding="utf-8")
        _checks()


def main() -> None:
    p = argparse.ArgumentParser(description="Ноты для бита: партитуры FL Studio и MIDI")
    p.add_argument("--selftest", action="store_true", help="проверить приёмы и запись файлов, без сети")
    p.add_argument("--build", metavar="ПАПКА", type=Path, help="собрать архив из ПАПКА/make.py")
    p.add_argument("--prev", metavar="ФАЙЛ", type=Path, nargs="+", default=(),
                   help="make.py прошлых битов, от вчерашнего назад: тот же образец, петля или мелодия, что в двух первых, — "
                        "бит не годен")
    p.add_argument("--out", metavar="КУДА", type=Path, help="куда положить архив (по умолчанию — временная папка)")
    p.add_argument("--send", metavar="АРХИВ", type=Path, help="отправить собранный архив владельцу")
    p.add_argument("--sounds", action="store_true", help="переписать список имён звуков и пресетов библиотеки (только Мак)")
    p.add_argument("--gather", action="store_true", help="собрать папку «00 - Сегодня»: ноты свежего бита и его звуки (только Мак)")
    p.add_argument("--project", metavar="ПАПКА", type=Path,
                   help="пробная сборка: проект FL бита из ПАПКА/make.py со звуками — в папку --out, «Сегодня» не тронута (только Мак)")
    p.add_argument("--net", action="store_true", help="ночной шаг: следующий источник из data/net_sources.json — в набор 11 (только Мак)")
    p.add_argument("--dry-run", action="store_true", help="с --net: что взял бы шаг, без загрузки звука и записи")
    p.add_argument("--loop", metavar="СЛОВО", help="замер петель с этим словом в имени: ноты, опоры по тактам, вторая петля на перелом")
    a = p.parse_args()
    if a.selftest:
        selftest()
    elif a.build:
        build(a.build, a.out or Path(tempfile.mkdtemp(prefix="noty-")), tuple(a.prev))
    elif a.send:
        send(a.send)
    elif a.sounds:
        from . import config, state
        names = library()
        if not names:
            raise SystemExit("Библиотеки на этой машине нет — список не тронут.")
        old = json.loads(config.BEAT_SOUNDS.read_text("utf-8")) if config.BEAT_SOUNDS.exists() else {}
        # незнакомые поля файла остаются: рядом с именами лежит то, что о звуках намерено
        config.BEAT_SOUNDS.write_text(json.dumps(old | {"date": state.now().strftime("%Y-%m-%d"), "sounds": names},
                                                 ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"{len(names)} имён → {config.BEAT_SOUNDS}")
    elif a.gather:
        print(gather())
    elif a.project:
        if not a.out:
            raise SystemExit("куда класть проект — флагом --out ПАПКА")
        try:
            print(aside(a.project, a.out))
        except subprocess.CalledProcessError as e:          # бит не прошёл сборку — показать, чем
            raise SystemExit((e.stderr or e.stdout or str(e)).strip()[-3000:])
    elif a.net:
        from . import set11
        print(set11.run(a.dry_run))
    elif a.loop:
        print(loop_card(a.loop))
    else:
        p.print_help()


if __name__ == "__main__":
    main()

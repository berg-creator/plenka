def _pcm(raw: bytes, width: int) -> array:
    """PCM 16 или 24 бита → отсчёты по 32 бита, значение сдвинуто в старшие байты. Срезами, а не циклом
    по отсчётам: дорожка на весь бит — десяток миллионов отсчётов."""
    wide = bytearray(len(raw) // width * 4)
    for i in range(width):
        wide[4 - width + i::4] = raw[i::width]
    return array("i", bytes(wide))


def _raw(pcm: array, width: int) -> bytes:
    wide, out = pcm.tobytes(), bytearray(len(pcm) * width)
    for i in range(width):
        out[i::width] = wide[4 - width + i::4]
    return bytes(out)


def loop_track(src: Path, dst: Path, tempo: int | None, plan: dict, second: bool = False) -> None:
    """Петля на весь бит одним файлом (владелец, 05.10.2026: «может, ты мне дашь дорожку петли на весь трек сразу»).
    Длина — весь бит; повторы стоят по сетке тактов, а не встык по длине файла; в паузах (rests) тишина; первая петля
    играет до перелома, вторая — после, и обе дорожки ставятся с первого такта. Затухание и возврат (`FADE`) — внутри
    самой паузы: атака первой ноты после неё цела. Темп бита равен темпу петли или вдвое выше — растяжки нет, поэтому
    хватает стандартной библиотеки, а формат файла остаётся прежним. plan пришёл из make.py — это числа, а не пути:
    файлы называет вызывающий. Не PCM 16/24 или план негоден — исключение, в папке остаётся просто копия петли."""
    bpm, bars, cut = float(plan["bpm"]), int(plan["bars"]), plan.get("switch")
    rests = [(float(a), float(b)) for a, b in plan.get("rests") or ()]
    if not (tempo and bpm in (tempo, tempo * 2) and bars >= 1 and bars * 240 / bpm <= 600):
        raise ValueError("темп петли и бита не сходятся или бит длиннее десяти минут")
    with wave.open(str(src), "rb") as w:
        ch, width, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        if width not in (2, 3) or sys.byteorder != "little" or array("i").itemsize != 4:
            raise ValueError(f"{width * 8} бит: читаются только 16 и 24")
        one = _pcm(w.readframes(n), width)
    total = round(bars * 240 / bpm * sr)

    def at(bar: float) -> int:          # кадр, с которого начинается такт; дробный такт — доля такта
        return min(max(round((bar - 1) * 240 / bpm * sr), 0), total)

    period = round(n / sr * tempo / 240) * 240 / tempo * sr         # повтор — целое число тактов петли, в кадрах
    if period < 1:
        raise ValueError("петля короче такта")
    lo, hi = (at(int(cut)), total) if second and cut else (total, total) if second else (0, at(int(cut)) if cut else total)
    fade = round(FADE * sr)
    out, k = array("i", bytes(4 * total * ch)), 0
    while (a := lo + round(k * period)) < min(hi + fade, total):    # хвост в `fade` за переломом — под затухание
        piece = one[:(min(lo + round((k + 1) * period), hi + fade, total) - a) * ch]
        out[a * ch:a * ch + len(piece)] = piece
        k += 1
    quiet: list[list[int]] = []
    for a, b in sorted([(0, lo), (hi, total)] + [(at(a), at(b)) for a, b in rests]):
        if quiet and a <= quiet[-1][1]:             # паузы встык и внахлёст — одна: между ними нечему затухать
            quiet[-1][1] = max(quiet[-1][1], b)
        elif b > a:
            quiet.append([a, b])
    for a, b in quiet:
        f = min(fade, (b - a) // 2)
        down, up = f if a > 0 else 0, f if b < total else 0         # у края файла затухать не из чего и не во что
        for i in range(f):
            for j in range(ch):
                if down:
                    out[(a + i) * ch + j] = out[(a + i) * ch + j] * (f - i) // f
                if up:
                    out[(b - 1 - i) * ch + j] = out[(b - 1 - i) * ch + j] * (f - i) // f
        out[(a + down) * ch:(b - up) * ch] = array("i", bytes(4 * (b - up - a - down) * ch))
    with wave.open(str(dst), "wb") as w:
        w.setnchannels(ch)
        w.setsampwidth(width)
        w.setframerate(sr)
        w.writeframes(_raw(out, width))


def lay(built: Path | None, sounds: dict, kits: Path, serum: Path,
        roots: dict[str, Path] | None = None, listed: set[str] | None = None, plan: dict | None = None,
        preset: dict | None = None) -> list[str]:
    """Папки «Сегодня»: партитуры и записка собранного бита и копии названных звуков — сэмплы в kits,
    пресеты в serum, имя партии впереди. Прошлые файлы обеих папок убираются: там только копии.
    Оригиналы открываются лишь на чтение. sounds пришёл из make.py — это данные, а не доверенный путь:
    копируется только то, что есть в списке. plan — план дорожки петли на весь бит (`loop_track`): она собирается
    из копии, уже лежащей в папке, сырая копия остаётся рядом. preset — свои пресеты Serum (поле паспорта): собираются
    и проверяются звуком самим плагином (`serum.tune`), итог — строкой в записке; в недостачу он не идёт: бит от своего
    пресета не зависит. Возвращает, что не легло, — оно же дописано в записку."""
    from .serum import tune
    roots, listed, missed, copied = roots or LIBRARY, known() if listed is None else listed, [], {}
    for folder in (kits, serum):
        assert folder.name == TODAY, f"{folder}: чистится только папка «{TODAY}»"
        folder.mkdir(parents=True, exist_ok=True)
        for old in folder.iterdir():
            if old.is_file() or old.is_symlink():
                old.unlink()
    for f in sorted((built / "fl").glob("*.fsc")) if built else []:
        shutil.copyfile(f, kits / f.name)
    for part, names in (sounds.items() if isinstance(sounds, dict) else []):
        label = re.sub(r"[/\\:\0]", " ", str(part))[:40]
        for name in map(_nfc, _names(names)):
            key, _, rel = name.partition("/")
            if name not in listed or key not in roots:
                missed.append(f"{label}: «{name}» — нет в списке библиотеки")
                continue
            src = roots[key] / rel
            dst = (serum if key == "Serum" else kits) / f"{label[:1].upper()}{label[1:]} — {src.name}"
            try:
                shutil.copyfile(src, dst)           # из Терминала чтение само скачает заглушку iCloud, помощнику — отказ
                copied.setdefault(str(part), (dst, name))
            except OSError as e:
                dst.unlink(missing_ok=True)
                why = "нет на диске" if isinstance(e, FileNotFoundError) else f"не прочитался ({e.strerror})"
                # Фоновому процессу (помощник под launchd) macOS заглушку не отдаёт: errno 11 сразу, скачивание не начинается.
                # `brctl download` оттуда же работает — файл на месте через секунды (проба 05.10.2026); заберёт повтор (`_mark`)
                if e.errno == errno.EDEADLK:
                    try:
                        subprocess.run(["brctl", "download", str(src)], capture_output=True, timeout=30)
                    except (OSError, subprocess.SubprocessError):
                        pass
                    why = "выгружен в iCloud и ещё не скачан: скачивание запрошено"
                missed.append(f"{label}: «{name}» — {why}")
    for i, part in enumerate(("петля", "петля 2")):
        if isinstance(plan, dict) and part in copied:
            track = kits / f"{part.capitalize()} — на весь бит.wav"
            try:
                loop_track(copied[part][0], track, loop_bpm(copied[part][1]), plan, second=bool(i))
            except (wave.Error, EOFError, OSError, ValueError, TypeError, KeyError, MemoryError) as e:
                track.unlink(missing_ok=True)
                missed.append(f"{part}: дорожка на весь бит не собралась ({e}) — в папке копия петли: расставь её по тактам")
    try:
        made = tune(preset, serum, roots.get("Serum", Path()), listed) if preset else []
    except Exception as e:              # свой пресет — добавка: его сбой не должен стоить владельцу папки с нотами
        made = [f"пресет не собрался: {type(e).__name__}: {e}"]
    note = (built / "о бите.txt").read_text("utf-8") if built and (built / "о бите.txt").exists() else ""
    (kits / "о бите.txt").write_text(
        note + ("\n\nСвой пресет Serum — проверен плагином на Маке, на слух не проверен:\n" + "\n".join(f"• {m}" for m in made) if made else "")
        + ("\n\nНе легло в папку:\n" + "\n".join(f"• {m}" for m in missed) if missed else ""), encoding="utf-8")
    return missed


def _sandboxed(folder: Path, tmp: Path) -> None:
    """Сборка бита в песочнице macOS: make.py писала модель, читавшая сеть, а на Маке рядом ключ входа
    в Telegram владельца. Сети нет, подпроцессов нет, запись — только в tmp, .env и приватное состояние
    не читаются, окружение пустое. В Actions ту же роль играет шаг без секретов (beats.yml)."""
    from . import config
    profile = ("(version 1)(allow default)(deny network*)(deny process-fork)(deny file-write*)"
               f'(allow file-write* (subpath "{tmp}"))(allow file-write* (literal "/dev/null"))'
               f'(deny file-read* (literal "{config.ROOT / ".env"}"))(deny file-read* (subpath "{config.PRIVATE}"))')
    subprocess.run(["/usr/bin/sandbox-exec", "-p", profile, sys.executable, "-B", "-m", "src.noty",
                    "--build", str(folder), "--out", str(tmp / "out")], cwd=config.ROOT, check=True, timeout=300,
                   env={"PATH": "/usr/bin:/bin", "HOME": str(tmp), "TMPDIR": str(tmp)}, capture_output=True, text=True)


def _project(plan: Path, kits: Path, serum: Path, home: Path | None = None) -> None:
    """Готовый проект FL — в «Сегодня», когда звуки и пресеты уже лежат (`flp.today`); строка о нём — в записку.
    Проект — добавка: его сбой не должен стоить владельцу папки с нотами, поэтому любая ошибка — строка, а не падение.
    home — где папка будет лежать потом (`aside`): пути звуков проекта ведут туда."""
    try:
        from . import flp
        line = flp.today(kits, serum, json.loads(plan.read_text("utf-8")), home=home)
    except Exception as e:
        line = f"Проект FL не собрался ({type(e).__name__}: {e}) — собери из партитур и звуков этой папки, как раньше."
    with (kits / "о бите.txt").open("a", encoding="utf-8") as f:
        f.write(f"\n\n{line}")


def _mark(mark: str, seen: str, missed: list[str]) -> str:
    """Метка собранной папки. Звук не лёг из-за iCloud — к метке дописан номер попытки, и следующий круг помощника
    соберёт папку заново: скачивание уже запрошено (`lay`). Не больше RETRY повторов: без сети папка не должна
    пересобираться вечно. До 05.10.2026 метка ставилась и при недостаче: бочка, хэт и клэпы бита того дня
    не легли с первого раза, и больше их никто не запрашивал."""
    left = seen[len(mark):].strip() if seen.startswith(mark) else ""
    tries = int(left) if left.isdigit() else 0
    return f"{mark} {tries + 1}" if tries < RETRY and any("iCloud" in m for m in missed) else mark


def _fill(make: str, beat: str, tmp: Path, kits: Path, serum: Path, home: Path | None = None) -> list[str]:
    """Текст make.py → папки kits и serum: сборка в песочнице, ноты, звуки, пресеты, дорожки петли и проект FL.
    Возвращает, что не легло."""
    (tmp / beat).mkdir()
    (tmp / beat / "make.py").write_text(make, "utf-8")
    _sandboxed(tmp / beat, tmp)
    out = tmp / "out"
    plan, own = out / f"{beat}.loop.json", out / f"{beat}.preset.json"
    missed = lay(out / beat, json.loads((out / f"{beat}.sounds.json").read_text("utf-8")), kits, serum,
                 plan=json.loads(plan.read_text("utf-8")) if plan.exists() else None,
                 preset=json.loads(own.read_text("utf-8")) if own.exists() else None)
    missed += _net(out / f"{beat}.net.json", kits)
    _project(out / f"{beat}.flp.json", kits, serum, home)
    return missed


def aside(make: Path, out: Path) -> str:
    """Проект бита из ПАПКА/make.py — в отдельную папку со своими звуками: пробная сборка, «Сегодня» и ветки не тронуты.
    Собирается во временных папках «Сегодня» тем же путём, что утром (`_fill`), файлы копируются в out, а пути звуков
    проекта с самого начала ведут туда. Файлы out с теми же именами переписываются, остальные остаются."""
    with tempfile.TemporaryDirectory(prefix="noty-") as tmp:
        tmp = Path(tmp).resolve()
        kits, serum = tmp / "kits" / TODAY, tmp / "serum" / TODAY
        missed = _fill((make / "make.py").read_text("utf-8"), make.resolve().name, tmp, kits, serum, out.resolve())
        out.mkdir(parents=True, exist_ok=True)
        for f in (*kits.iterdir(), *serum.iterdir()):
            shutil.copyfile(f, out / f.name)
    return f"{make.resolve().name}: проект, ноты и звуки — в {out}" + (f"; не легло звуков: {len(missed)}" if missed else "")


def gather(kits: Path | None = None, serum: Path | None = None) -> str:
    """Свежая ветка claude/beats-* → папки «Сегодня» в браузере FL и в пресетах Serum. Собранное второй
    раз не трогается: помощник на Маке заходит сюда раз в десять минут. Спал Мак — соберёт, проснувшись.
    Проект, сохранённый владельцем в «Сегодня» после сборки, перед чисткой переезжает рядом со звуками (`flp.keep`)."""
    from . import config, flp

    def git(*args: str) -> str:
        return subprocess.run(["git", "-C", str(config.ROOT), *args], capture_output=True, text=True,
                              check=True, timeout=120).stdout

    kits, serum = kits or LIBRARY["KITS"] / TODAY, serum or LIBRARY["Serum"] / "User" / TODAY
    if not kits.parent.is_dir() or not serum.parent.is_dir():
        return "библиотеки FL или пресетов Serum на этой машине нет"
    git("fetch", "-q", "origin", "+refs/heads/claude/beats-*:refs/remotes/origin/claude/beats-*")
    heads = dict(line.split() for line in git("for-each-ref", "--sort=committerdate", "--format=%(refname:short) %(objectname)",
                                              "refs/remotes/origin/claude/beats-*").splitlines())
    ids = {ref.removeprefix("origin/claude/beats-"): sha for ref, sha in heads.items()
           if re.fullmatch(r"origin/claude/beats-[0-9a-z-]+", ref)}
    if not ids:
        return "веток с битами нет"
    # id начинается с даты; два бита за день (утренний забракован, рутина перезапущена) — нужен поздний по коммиту,
    # а не по алфавиту пары: ветки идут в порядке коммитов
    beat = max(enumerate(ids), key=lambda x: (x[1][:8], x[0]))[1]
    mark = f"{beat} {ids[beat]}"
    seen, missed = (kits / ".бит").read_text("utf-8") if (kits / ".бит").exists() else "", []
    if seen == mark:
        return f"{beat}: уже собрано"
    make = git("show", f"origin/claude/beats-{beat}:content/beats/{beat}/make.py")
    saved = flp.keep(kits)              # до первой чистки; не переехала (ошибка диска) — падаем, папку не стираем
    with tempfile.TemporaryDirectory(prefix="noty-") as tmp:
        tmp = Path(tmp).resolve()
        try:
            missed = _fill(make, beat, tmp, kits, serum)
            done = "ноты на месте" + (f", не легло звуков: {len(missed)}" if missed else "")
        except (subprocess.SubprocessError, OSError, ValueError) as e:      # не собрался — записка, а не падение
            lay(None, {}, kits, serum)
            why = (getattr(e, "stderr", "") or getattr(e, "stdout", "") or str(e)).strip()[-1500:]
            (kits / "о бите.txt").write_text(f"{beat}: ноты на Маке не собрались — возьми архив из Telegram.\n\n{why}", "utf-8")
            done = "ноты не собрались, в папке записка"
    if saved:
        with (kits / "о бите.txt").open("a", encoding="utf-8") as f:
            f.write(f"\n\n{saved}")
    (kits / ".бит").write_text(_mark(mark, seen, missed), "utf-8")
    return f"{beat}: {done}" + (", вчерашний проект владельца сохранён рядом" if saved else "")


def loop_card(word: str) -> str:
    """Что замер знает о петлях с этим словом в имени; петля одна — ещё и чем сменить её на переломе.
    Автору нот: звука он не слышит, и ноты петли — единственное, по чему пишутся мелодия и 808."""
    heard = loops()

    def line(name: str, first: str = "") -> str:      # first — первая петля бита: scale тогда собран для пары
        m = heard[name]
        return (f"{name} — {loop_bpm(name)} BPM, тактов {m['bars']}, ноты {' '.join(m['notes'])}, "
                f"опоры по тактам {' '.join(m['roots'])}, тоника {m['key']} ({m['sure']:.2f}), "
                + (f"бит на обеих петлях — scale={_scale(heard, first, name)}" if first else f"scale={_scale(heard, name)}")
                + ("" if LOOP_NOTES[0] <= len(m["notes"]) <= LOOP_NOTES[1] else f" — нот не {LOOP_NOTES[0]}–{LOOP_NOTES[1]}: в бит не идёт"))

    fit = sorted(name for name in heard if word.lower() in name.lower())
    out = [line(name) for name in fit[:40]]
    if len(fit) == 1:
        a = fit[0]
        pairs = sorted(((len(set(heard[a]["notes"]) & set(m["notes"])), name) for name, m in heard.items()
                        if loop_bpm(name) == loop_bpm(a) and LOOP_NOTES[0] <= len(m["notes"]) <= LOOP_NOTES[1]
                        and not _twin(a, name, heard)), reverse=True)
        out += ["", "Вторая петля на перелом — тот же темп, другой риф; впереди те, у кого больше общих нот:"]
        out += [f"общих {c}: {line(name, a)}" for c, name in pairs[:12]]
    return "\n".join(out) or "петель с таким словом в замере нет: python3 -m src.noty --loop Gtr"


def _pages(text: str, limit: int = 4000) -> list[str]:
    """Записка по сообщениям Telegram (4096 знаков), по строкам: со звуками и обработкой она в одно не влезает."""
    out = [""]
    for line in text.splitlines(keepends=True):
        if len(out[-1]) + len(line) > limit:
            out.append("")
        out[-1] += line
    return [page for page in out if page.strip()]


def send(archive: Path) -> None:
    """Архив и следом записка: в подпись к файлу (1024 знака) она не влезает."""
    from . import config, telegram
    text = archive.with_suffix(".txt").read_text("utf-8")
    telegram.send_document(config.secret("TELEGRAM_ADMIN_ID"), archive, "\n".join(text.splitlines()[:2]))
    for page in _pages(text):
        telegram.send_message(config.secret("TELEGRAM_ADMIN_ID"), page)



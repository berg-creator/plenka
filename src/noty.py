def _when(rests) -> str:
    """Паузы петли словами: (16, 17) — «такт 16», (1, 5) — «такты 1–4», (8.5, 9) — «с 8.5 до 9»."""
    return ", ".join(f"такт {a:g}" if b - a == 1 and a == int(a) else f"такты {a:g}–{b - 1:g}" if a == int(a) and b == int(b)
                     else f"с {a:g} до {b:g}" for a, b in rests)


